# Фермата, сезоните, времето и пазарът в селото (част от света - world.Свят я наследява).
# Данните са в data/ferma.json. Селянинът сее, полива, бере, събира яйца и дои кравата;
# продава на пазара. Пазарът има наличност: малко стока = висока цена (суша = скъпи домати).
import json
import math
import os
import random

import tiles

ПЛОЧКА = tiles.ПЛОЧКА
ПЪТ = os.path.join(tiles.ПАПКА, "data", "ferma.json")
ФЕРМЕРИ = ("селянин", "собственик")      # кой може да работи на нивите


class ФермаМиксин:
    # ---------- начало ----------
    def _ферма_начало(self):
        try:
            with open(ПЪТ, encoding="utf-8") as f:
                self.ферма_данни = json.load(f)
        except (OSError, ValueError):
            self.ферма_данни = {"сезони": ["лято"], "дни_в_сезон": 99, "време": {"лято": {"слънце": 1}},
                                "култури": {}, "пазар": {"местни": [], "цел": 30, "начало": 0, "внос_на_ден": 0}}
        д = self.ферма_данни
        self.ниви = {tuple(к): self._празна_нива() for к in self.село_инфо.get("ниви", [])} if self.село else {}
        self.яйца = 2
        self.доено = -10 ** 6                  # кога е издоена кравата (минута от началото на играта)
        пазар = д.get("пазар", {})
        self.пазар_стока = {к: float(пазар.get("начало", 20)) for к in пазар.get("местни", [])}
        self.време_днес = self._ново_време()

    @staticmethod
    def _празна_нива():
        return {"к": None, "р": 0.0, "в": 0.0, "сухо": 0.0, "стрес": 0.0, "мъртво": False}

    # ---------- сезон, време ----------
    def сезон(self):
        """Сезонът по истинския месец: декември-февруари зима, март-май пролет и т.н."""
        месец = self.дата().month if hasattr(self, "начална_дата") else 4
        сезони = self.ферма_данни.get("сезони", ["пролет", "лято", "есен", "зима"])
        if len(сезони) < 4:
            return сезони[0]
        return сезони[3] if месец in (12, 1, 2) else сезони[0] if месец <= 5 else сезони[1] if месец <= 8 else сезони[2]

    def _ново_време(self):
        вер = self.ферма_данни.get("време", {}).get(self.сезон(), {"слънце": 1})
        с = self.случаен.uniform(0, sum(вер.values()))
        for вид, в in вер.items():
            с -= в
            if с <= 0:
                return вид
        return "слънце"

    def _абс_минута(self):
        return self.ден * 24 * 60 + self.минути

    # ---------- пазарът ----------
    def цена_единица(self, к):
        """Цената на 1 порция на пазара. Местните неща поскъпват, когато са малко."""
        п = self.склад_данни["продукти"].get(к)
        if not п:
            return 0.0
        база = п["цена"] / float(п["пакет"])
        if к in self.пазар_стока:
            цел = self.ферма_данни.get("пазар", {}).get("цел", 30)
            база *= max(0.6, min(3.0, (цел / max(1.0, self.пазар_стока[к])) ** 0.5))
        return база

    def купи_от_пазара(self, к, брой):
        """Купува до брой порции от пазара. Връща (купени, цена). Местните - само каквото има."""
        if к in self.пазар_стока:
            брой = min(брой, int(self.пазар_стока[к]))
        if брой < 1:
            return 0, 0
        цена = int(math.ceil(брой * self.цена_единица(к)))
        if к in self.пазар_стока:
            self.пазар_стока[к] -= брой
        return брой, цена

    def продай_на_пазара(self, п):
        """Селянинът продава реколтата на пазара: стоката отива там, парите - при него."""
        if not п.реколта:
            return False, "Нямаш какво да продадеш"
        изкупува = self.ферма_данни.get("пазар", {}).get("изкупува", 0.7)
        общо, имена = 0, []
        for к, брой in п.реколта.items():
            цена = int(round(брой * self.цена_единица(к) * изкупува))
            общо += цена
            self.пазар_стока[к] = self.пазар_стока.get(к, 0) + брой
            имена.append("%d %s" % (брой, self.склад_данни["продукти"].get(к, {}).get("име", к).lower()))
        п.пари += общо
        п.реколта = {}
        self._носи_ферма(п)
        return True, "Продаде %s за %d" % (", ".join(имена), общо)

    # ---------- всяка минута и всяка нощ ----------
    def _ферма_минута(self):
        д = self.ферма_данни
        суша = self.време_днес == "суша"
        дъжд = self.време_днес == "дъжд"
        сезон = self.сезон()
        for н in self.ниви.values():
            if not н["к"] or н["мъртво"] or н["р"] >= 1:
                continue
            if дъжд:
                н["в"] = 1.0
            култура = д["култури"].get(н["к"], {})
            if н["в"] > 0:
                if сезон in култура.get("сезони", []):
                    н["р"] = min(1.0, н["р"] + 1.0 / (култура.get("расте_часа", 5) * 60))
                н["в"] = max(0.0, н["в"] - д.get("вода_на_час", 0.3) / 60 * (д.get("суша_вода", 2) if суша else 1))
                н["сухо"] = 0.0
            else:
                н["сухо"] += 1 / 60.0
                н["стрес"] += 1 / 60.0
                if н["сухо"] >= д.get("увяхва_след_часа", 3):
                    н["мъртво"] = True
        if self.минути % 60 == 0:
            к = д.get("кокошки", {})
            self.яйца = min(к.get("най_много", 8), self.яйца + к.get("яйца_на_час", 1))

    def _ферма_нощ(self):
        """Сутринта: ново време, нощта е поляла/изсушила нивите, внос от града, доход на жителите."""
        д = self.ферма_данни
        for н in self.ниви.values():                     # нощем растенията растат малко, ако имат вода
            if н["к"] and not н["мъртво"] and н["р"] < 1 and н["в"] > 0 and self.сезон() in д["култури"].get(н["к"], {}).get("сезони", []):
                н["р"] = min(1.0, н["р"] + 0.25)
                н["в"] = max(0.0, н["в"] - 0.4)
        self.време_днес = self._ново_време()
        if self.време_днес == "дъжд":
            for н in self.ниви.values():
                н["в"] = 1.0
        внос = д.get("пазар", {}).get("внос_на_ден", 6)
        for к in self.пазар_стока:                        # от града идва малко от всичко
            if к in ("yaytse", "mlyako"):
                continue
            self.пазар_стока[к] += внос
        if self.сезон() == "зима":                       # зимата всичко зеленчуково е от града и е малко
            for к in self.пазар_стока:
                self.пазар_стока[к] = max(0.0, self.пазар_стока[к] * 0.8)
        for п in self.персони.values():                   # жителите получават пари (пенсия, заплата в града)
            if self.гост(п):
                п.пари += д.get("доход_на_ден", 15)

    # ---------- селянинът ----------
    def _носи_ферма(self, п):
        п.носи = "kofa" if п.кофа > 0 else ("kosnitsa" if п.реколта else None)

    def _нива_до(self, п, разстояние=70):
        if п.карта != "selo" or not self.ниви:
            return None
        к = min(self.ниви, key=lambda к: math.hypot(self.център(к)[0] - п.x, self.център(к)[1] - п.y))
        ц = self.център(к)
        return к if math.hypot(ц[0] - п.x, ц[1] - п.y) <= разстояние else None

    def култури_сега(self):
        сезон = self.сезон()
        return [к for к, в in self.ферма_данни.get("култури", {}).items() if сезон in в.get("сезони", [])]

    def крава_готова(self):
        return self._абс_минута() - self.доено >= self.ферма_данни.get("крава", {}).get("доене_през_часа", 5) * 60

    def издои(self, п, качество=0.7):
        if not self.до_точка(п, "крава", 100):
            return False, "Иди до кравата"
        if not self.крава_готова():
            return False, "Кравата вече е издоена - след малко пак"
        брой = max(1, int(round(self.ферма_данни.get("крава", {}).get("мляко", 4) * max(0.0, min(1.0, качество)))))
        self.доено = self._абс_минута()
        п.реколта["mlyako"] = п.реколта.get("mlyako", 0) + брой
        self._носи_ферма(п)
        return True, "Издои %d мляко" % брой

    def доене_клиент(self, клиент, качество):
        п = next((п for п in self.персони.values() if п.контролер == клиент), None)
        if п is None or п.роля not in ФЕРМЕРИ:
            return False, ""
        return self.издои(п, качество)

    def _ферма_действие(self, п, семе=None):
        """E на селянина. None = нищо от фермата наблизо."""
        if п.роля not in ФЕРМЕРИ or п.карта != "selo":
            return None
        д = self.ферма_данни
        if п.реколта and self.до_пазара(п):
            return self.продай_на_пазара(п)
        if self.до_точка(п, "кладенец", 90):
            п.кофа = д.get("кофа", 4)
            self._носи_ферма(п)
            return True, "Напълни кофата с вода (%d поливания)" % п.кофа
        if self.до_точка(п, "кокошарник", 100):
            if self.яйца < 1:
                return False, "Още няма яйца"
            брой, self.яйца = self.яйца, 0
            п.реколта["yaytse"] = п.реколта.get("yaytse", 0) + брой
            self._носи_ферма(п)
            return True, "Събра %d яйца" % брой
        if self.до_точка(п, "крава", 100) and п.контролер is None:
            return self.издои(п, 0.7)
        к = self._нива_до(п)
        if к is None:
            return None
        н = self.ниви[к]
        if н["мъртво"]:
            self.ниви[к] = self._празна_нива()
            return True, "Изчисти изсъхналото"
        if н["к"] and н["р"] >= 1:
            култура = д["култури"].get(н["к"], {})
            брой = max(1, int(култура.get("добив", 3) - int(н["стрес"])))
            п.реколта[н["к"]] = п.реколта.get(н["к"], 0) + брой
            име = култура.get("име", н["к"])
            self.ниви[к] = self._празна_нива()
            self._носи_ферма(п)
            return True, "Набра %d %s%s" % (брой, име.lower(), " (беше жадно - по-малко)" if брой < култура.get("добив", 3) else "")
        if not н["к"]:
            сега = self.култури_сега()
            if not сега:
                return False, "Зима е - нищо не расте"
            семе = семе if семе in сега else сега[0]
            н.update(self._празна_нива())
            н["к"] = семе
            return True, "Засади %s" % д["култури"][семе]["име"].lower()
        if п.кофа > 0 and н["в"] < 0.95:
            н["в"] = 1.0
            п.кофа -= 1
            self._носи_ферма(п)
            return True, "Поля (в кофата остават %d)" % п.кофа
        if п.кофа <= 0 and н["в"] < 0.5:
            return False, "Нивата е жадна - напълни кофата на кладенеца"
        return False, "%s расте: %d%%, вода %d%%" % (д["култури"].get(н["к"], {}).get("име", ""), н["р"] * 100, н["в"] * 100)

    def _npc_селянин(self, п, време):
        """NPC селянинът сам работи на нивите и продава на пазара."""
        if п.карта != "selo":
            self._иди(п, "selo", None, време)
            return True
        if п.почивка > 0:
            п.почивка -= време
            п.върви = False
            return True

        def отиди_и(точка, семе=None):
            if точка is None:
                return False
            if self._иди(п, "selo", точка, време) or math.hypot(точка[0] - п.x, точка[1] - п.y) < 20:
                self._ферма_действие(п, семе)
                п.почивка = 0.6
            return True

        реколта = sum(п.реколта.values())
        if реколта >= 10:
            return отиди_и(self._пазар_точка(п))
        узрели = [к for к, н in self.ниви.items() if (н["к"] and н["р"] >= 1) or н["мъртво"]]
        if узрели:
            к = min(узрели, key=lambda к: math.hypot(self.център(к)[0] - п.x, self.център(к)[1] - п.y))
            return отиди_и(self.център(к))
        жадни = [к for к, н in self.ниви.items() if н["к"] and not н["мъртво"] and н["р"] < 1 and н["в"] < 0.35]
        if жадни and self.време_днес != "дъжд":
            if п.кофа <= 0:
                return отиди_и(self._селска_точка("кладенец"))
            к = min(жадни, key=lambda к: math.hypot(self.център(к)[0] - п.x, self.център(к)[1] - п.y))
            return отиди_и(self.център(к))
        сега = self.култури_сега()
        празни = [к for к, н in self.ниви.items() if not н["к"]]
        if празни and сега:
            семе = min(сега, key=lambda к: self.пазар_стока.get(к, 0))   # сее това, което липсва на пазара
            к = min(празни, key=lambda к: math.hypot(self.център(к)[0] - п.x, self.център(к)[1] - п.y))
            return отиди_и(self.център(к), семе)
        if self.яйца >= 3:
            return отиди_и(self._селска_точка("кокошарник"))
        if self.крава_готова() and self.село_инфо.get("крава"):
            return отиди_и(self._селска_точка("крава"))
        if реколта:
            return отиди_и(self._пазар_точка(п))
        п.почивка = 3.0
        return False

    # ---------- за мрежата ----------
    def ферма_за_клиента(self):
        return {"plots": [[к[0], к[1], н["к"] or "", (3 if н["р"] >= 1 else int(н["р"] * 3)) if н["к"] else 0,
                           н["в"] < 0.2 and bool(н["к"]) and н["р"] < 1, н["мъртво"]] for к, н in self.ниви.items()],
                "eggs": self.яйца, "cow": self.крава_готова(), "season": self.сезон(), "weather": self.време_днес,
                "market": {к: [round(в, 1), round(self.цена_единица(к), 2)] for к, в in self.пазар_стока.items()},
                "seeds": self.култури_сега()}

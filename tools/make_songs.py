# Прави примерни песни за минииграта "Свирене" (докато класът запише истински).
# Пускане от папката "Real Life":   python tools/make_songs.py
# Всяка песен е data/songs/<име>.json:
#   name, kind, meter ("2/4", "7/8"), groups (групи осмини в такта: 2/4 = [2,2], 7/8 = [2,2,3]),
#   eighth_ms (колко милисекунди е една осмина), instrument, lanes, length_s,
#   base_hz (тоника), scale (полутонове от тониката),
#   notes: [време_в_секунди, лента, степен_от_гамата]
import json
import os
import random

ПАПКА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
МИНОР = [0, 2, 3, 5, 7, 9, 10, 12, 14, 15, 17]            # ре дорийски (два октава)
ХИДЖАЗ = [0, 1, 4, 5, 7, 8, 10, 12, 13, 16, 17]            # "ориенталски" лад


def фраза(сл, ритми, дължина, лад_нагоре=True):
    """Една фраза: списък тактове, всеки такт = [(осмина, степен), ...]."""
    степен = сл.choice((2, 3, 4))
    тактове = []
    for т in range(дължина):
        ритъм = сл.choice(ритми)
        такт = []
        for позиция in ритъм:
            стъпка = сл.choice((-1, -1, 1, 1, 1, 0, 2, -2)) if лад_нагоре else сл.choice((-1, 1, 0, -2, 2))
            степен = степен + стъпка
            if степен < 0 or степен > 9:              # отскача от краищата, вместо да залепне
                степен = степен - 2 * стъпка
            степен = max(0, min(9, степен))
            такт.append((позиция, степен))
        тактове.append(такт)
    # краят на фразата: към тониката
    последен = тактове[-1]
    тактове[-1] = последен[:-1] + [(последен[-1][0], сл.choice((0, 0, 4)))]
    return тактове


def вариант(сл, тактове):
    """Повторение с малка разлика в края (A -> A')."""
    нови = [list(т) for т in тактове]
    т = нови[-2]
    нови[-2] = [(п, max(0, min(9, с + сл.choice((-1, 1))))) for п, с in т]
    return нови


def лента(степен, ленти):
    return min(ленти - 1, степен * ленти // 10)


def направи(име, вид, размер, групи, осмина_ms, дължина_s, тоника, лад, ритми_лесни, ритми_трудни, семе, ленти=3):
    сл = random.Random(семе)
    осмина = осмина_ms / 1000.0
    в_такт = sum(групи)
    такт_s = в_такт * осмина
    ноти = []
    t0 = 3.0                                     # първата нота след 3 секунди (броене)
    време = t0
    раздел = 0
    while време < дължина_s - 4 * такт_s:
        трудно = раздел % 4 == 3 or раздел >= 6    # всеки четвърти раздел и краят са по-гъсти
        ритми = ритми_трудни if трудно else ритми_лесни
        A = фраза(сл, ритми, 4)
        B = фраза(сл, ритми, 4, лад_нагоре=False)
        for фр in (A, вариант(сл, A), B, вариант(сл, B)):
            for такт in фр:
                for позиция, степен in такт:
                    t = време + позиция * осмина
                    if t < дължина_s - 2 * такт_s:
                        ноти.append([round(t, 3), лента(степен, ленти), степен])
                време += такт_s
        раздел += 1
    # финал: дълга тоника
    ноти.append([round(време, 3), 0, 0])
    # лентите следват височината на тона (ниско = вляво, високо = вдясно),
    # но границите са избрани така, че лентите да имат почти еднакво много ноти
    брой = {}
    for н in ноти:
        брой[н[2]] = брой.get(н[2], 0) + 1
    граници, натрупано, общо = {}, 0, len(ноти)
    for ст in sorted(брой):
        граници[ст] = min(ленти - 1, int(ленти * (натрупано + брой[ст] / 2) / общо))
        натрупано += брой[ст]
    for н in ноти:
        н[1] = граници[н[2]]
    песен = {"name": име, "kind": вид, "meter": размер, "groups": групи, "eighth_ms": осмина_ms,
             "instrument": "kaval", "lanes": ленти, "length_s": round(време + 2 * такт_s, 1),
             "base_hz": тоника, "scale": лад, "notes": ноти,
             "made_by": "tools/make_songs.py (примерна мелодия, докато класът запише истинска)"}
    файл = os.path.join(ПАПКА, "data", "songs", име_на_файл(име))
    with open(файл, "w", encoding="utf-8") as f:
        json.dump(песен, f, ensure_ascii=False, indent=0)
    print("%s: %d ноти, %d:%02d мин" % (име, len(ноти), песен["length_s"] // 60, песен["length_s"] % 60))


def име_на_файл(име):
    return {"Право хоро": "pravo_horo.json", "Ръченица": "rachenitsa.json"}[име]


if __name__ == "__main__":
    os.makedirs(os.path.join(ПАПКА, "data", "songs"), exist_ok=True)
    # Право хоро: 2/4, лесно (осмини и четвъртини)
    направи("Право хоро", "хоро", "2/4", [2, 2], 240, 180, 293.66, МИНОР,
            ритми_лесни=[[0, 2], [0, 1, 2], [0, 2, 3], [0, 2]],
            ритми_трудни=[[0, 1, 2, 3], [0, 1, 2], [0, 2, 3], [0, 1, 2, 3]], семе=7)
    # Ръченица: 7/8 (2+2+3), по-трудна и по-дълга
    направи("Ръченица", "ръченица", "7/8", [2, 2, 3], 150, 240, 293.66, ХИДЖАЗ,
            ритми_лесни=[[0, 2, 4], [0, 4], [0, 2, 4, 6]],
            ритми_трудни=[[0, 2, 4, 5, 6], [0, 1, 2, 4, 6], [0, 2, 3, 4, 6]], семе=11)

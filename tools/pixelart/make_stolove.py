# Рисува столовете и пейката за кръчмата (Claude), в стила на масата (table.png).
# Пускане от папката "Real Life":   python tools/pixelart/make_stolove.py
#   assets/chair_down.png   64x64   седналият гледа надолу: облегалката е отзад (горе)
#   assets/chair_up.png     64x64   седналият гледа нагоре: виждаме облегалката отзад (долу)
#   assets/chair_right.png  64x64   седналият гледа надясно: облегалката е вляво
#   assets/bench.png        128x64  дълга пейка без облегалка (двама сядат, гледат надолу: зад масата)
#   assets/bench_up.png     128x64  същата пейка, но седналите гледат нагоре (пред масата, с гръб към нас)
#   assets/table_big.png    128x64  дълга маса за 4 души
#   assets/table_big_v.png  64x128  същата дълга маса, но изправена (отгоре надолу)
#   assets/chair_left.png   64x64   седналият гледа наляво (огледало на chair_right)
#   assets/bench_right.png  64x128  изправена пейка вляво от масата: седналите гледат надясно
#   assets/bench_left.png   64x128  изправена пейка вдясно от масата: седналите гледат наляво
# Облегалката има издълбано сърце (народен мотив). Светлина горе вляво.
import os

os.environ.setdefault("PYGAME_HIDE_SUPPORT_PROMPT", "1")
os.environ.setdefault("SDL_VIDEODRIVER", "dummy")
import pygame

ИГРА = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def hx(h):
    return (int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16), 255)


СВЕТЛО, СРЕДНО, ТЪМНО, ПО_ТЪМНО = hx("#d9a066"), hx("#b0743d"), hx("#7a4a24"), hx("#4a2c1a")
БЛЯСЪК, КОНТУР = hx("#ecc48a"), hx("#2a1d16")


class Платно:
    def __init__(с, w, h):
        с.w, с.h = w, h
        с.п = [[None] * w for _ in range(h)]

    def т(с, x, y, ц):
        if 0 <= x < с.w and 0 <= y < с.h:
            с.п[y][x] = ц

    def пр(с, x0, y0, x1, y1, ц):
        for y in range(y0, y1):
            for x in range(x0, x1):
                с.т(x, y, ц)

    def крак(с, x0, y0, x1, y1):
        """Крак/стойка: светло вляво, тъмно вдясно."""
        с.пр(x0, y0, x1, y1, СРЕДНО)
        for y in range(y0, y1):
            с.т(x0, y, СВЕТЛО)
            с.т(x1 - 1, y, ТЪМНО)

    def дъски(с, x0, y0, x1, y1, ширина=5, шев=None):
        """Хоризонтални дъски отгоре (седалката): светъл ръб горе, тъмен шев между дъските."""
        с.пр(x0, y0, x1, y1, СРЕДНО)
        for y in range(y0, y1):
            if (y - y0) % ширина == 0:
                for x in range(x0, x1):
                    с.т(x, y, ТЪМНО if y > y0 else СВЕТЛО)
            elif (y - y0) % ширина == 1:
                for x in range(x0, x1):
                    с.т(x, y, СВЕТЛО)
        for y in range(y0, y1):
            с.т(x0, y, СВЕТЛО)
        if шев:
            for y in range(y0 + 1, y1):
                с.т(шев, y, ТЪМНО)
        for (x, y) in ((x0 + 2, y0 + 2), (x1 - 3, y0 + 2), (x0 + 2, y1 - 3), (x1 - 3, y1 - 3)):
            с.т(x, y, ПО_ТЪМНО)                          # гвоздейчета
        с.т(x0 + 1, y0 + 1, БЛЯСЪК)

    def ръб(с, x0, y0, x1, y1):
        """Предният ръб на седалката (тъмен, гледаме го отстрани)."""
        с.пр(x0, y0, x1, y1, ТЪМНО)
        for x in range(x0, x1):
            с.т(x, y1 - 1, ПО_ТЪМНО)

    def сърце(с, cx, cy):
        """Издълбано сърце: прозрачно, ръбът му се оцветява после като контур."""
        for (dx, dy) in ((-2, 0), (-1, 0), (1, 0), (2, 0), (-2, 1), (-1, 1), (0, 1), (1, 1), (2, 1),
                         (-1, 2), (0, 2), (1, 2), (0, 3), (-1, -1), (1, -1)):
            с.п[cy + dy][cx + dx] = "дупка"

    def контур(с):
        out = [ред[:] for ред in с.п]
        for y in range(с.h):
            for x in range(с.w):
                if с.п[y][x] in (None, "дупка"):
                    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                        X, Y = x + dx, y + dy
                        if 0 <= X < с.w and 0 <= Y < с.h and с.п[Y][X] not in (None, "дупка"):
                            out[y][x] = КОНТУР if с.п[y][x] is None else ПО_ТЪМНО
                            break
                    else:
                        out[y][x] = None
        с.п = out

    def повърхност(с):
        s = pygame.Surface((с.w, с.h), pygame.SRCALPHA)
        for y in range(с.h):
            for x in range(с.w):
                if с.п[y][x] and с.п[y][x] != "дупка":
                    s.set_at((x, y), с.п[y][x])
        return s


def облегалка(п, x0, x1, y0, y1):
    """Облегалка, гледана отпред/отзад: две стойки, горна напречна дъска със сърце, пречки."""
    п.крак(x0, y0, x0 + 4, y1)
    п.крак(x1 - 4, y0, x1, y1)
    п.пр(x0, y0, x1, y0 + 9, СРЕДНО)                      # горната дъска
    for x in range(x0, x1):
        п.т(x, y0, СВЕТЛО)
        п.т(x, y0 + 8, ТЪМНО)
    п.т(x0 + 1, y0 + 1, БЛЯСЪК)
    п.сърце((x0 + x1) // 2, y0 + 3)
    for y in [y for y in (y0 + 12, y0 + 17, y0 + 22) if y + 3 < y1]:   # пречки (колкото се събират)
        п.пр(x0 + 4, y, x1 - 4, y + 3, СРЕДНО)
        for x in range(x0 + 4, x1 - 4):
            п.т(x, y, СВЕТЛО)
            п.т(x, y + 2, ТЪМНО)


def стол_надолу():
    п = Платно(64, 64)
    облегалка(п, 18, 46, 24, 42)                         # отзад (горе): стига до врата на седналия
    п.дъски(17, 38, 47, 48)                              # седалката (по-ниско)
    п.ръб(17, 48, 47, 51)
    п.крак(18, 51, 22, 62)                               # предни крака
    п.крак(42, 51, 46, 62)
    п.пр(22, 57, 42, 59, ТЪМНО)                          # напречна пречка между краката
    п.контур()
    return п.повърхност()


def стол_нагоре():
    п = Платно(64, 64)
    п.крак(20, 34, 23, 48)                               # далечните (предни) крака, под седалката
    п.крак(41, 34, 44, 48)
    п.дъски(17, 22, 47, 34)                              # седалката (почти скрита зад облегалката)
    п.ръб(17, 34, 47, 37)
    облегалка(п, 18, 46, 18, 62)                         # облегалката е към нас: до врата, после краката
    п.контур()
    return п.повърхност()


def стол_надясно():
    п = Платно(64, 64)
    # столът е опрян до масата (вдясно в съседната клетка)
    п.крак(58, 48, 62, 62)                               # преден крак (вдясно, до масата)
    п.дъски(43, 38, 63, 45, ширина=4)                    # седалката отстрани: тясна, по-ниско
    п.ръб(43, 45, 63, 48)
    п.крак(41, 22, 46, 62)                               # облегалката отстрани: стойка до пода, до врата
    for y in range(22, 38, 2):
        п.т(43, y, БЛЯСЪК if y < 27 else СРЕДНО)
    п.пр(40, 21, 48, 27, СРЕДНО)                         # главата на облегалката
    for x in range(40, 48):
        п.т(x, 21, СВЕТЛО)
        п.т(x, 26, ТЪМНО)
    п.пр(46, 55, 58, 57, ТЪМНО)                          # пречка между краката
    п.контур()
    return п.повърхност()


def пейка():
    п = Платно(128, 64)
    п.дъски(6, 40, 122, 50, ширина=5, шев=64)            # дълга седалка от две дъски (ниска)
    п.ръб(6, 50, 122, 53)
    for x in (10, 60, 112):                              # крака (среден за здравина)
        п.крак(x, 53, x + 5, 62)
    п.пр(15, 57, 112, 59, ТЪМНО)                         # дълга пречка
    п.контур()
    return п.повърхност()


def маса_дълга():
    """Дълга маса 128x64 (за 4 души, с пейки от двете страни), в стила на table.png."""
    п = Платно(128, 64)
    x0, x1, y0, y1 = 3, 125, 6, 44
    п.пр(x0, y0, x1, y1, СРЕДНО)
    редове = [(y0, y0 + 9, (40, 92)), (y0 + 9, y0 + 19, (22, 70, 108)), (y0 + 19, y0 + 28, (55, 98)), (y0 + 28, y1, (30, 84))]
    for (а, б, шевове) in редове:                       # дъски по дължината, с разминати шевове
        for x in range(x0, x1):
            п.т(x, а, ТЪМНО if а > y0 else СВЕТЛО)
            п.т(x, а + 1, СВЕТЛО)
        for ш in шевове:
            for y in range(а + 1, б):
                п.т(ш, y, ТЪМНО)
                п.т(ш + 1, y, СВЕТЛО)
        for (x, y) in ((x0 + 3, а + 3), (x1 - 4, а + 3)):
            п.т(x, y, ПО_ТЪМНО)
            п.т(x + 1, y, ПО_ТЪМНО)
        for k, ш in enumerate(шевове):                  # жилки в дървото
            xx = ш - 14 + k * 3
            for d in range(6):
                п.т(xx + d, (а + б) // 2, ТЪМНО)
    for y in range(y0, y1):
        п.т(x0, y, СВЕТЛО)
    п.т(x0 + 1, y0 + 1, БЛЯСЪК)
    п.ръб(x0, y1, x1, y1 + 6)                           # предният ръб (по-дебел - голяма маса)
    for x in (6, 116):                                  # предни крака
        п.крак(x, y1 + 6, x + 6, 62)
    for x in (14, 108):                                 # задни крака (в сянка)
        п.пр(x, y1 + 6, x + 5, 58, ПО_ТЪМНО)
    п.контур()
    return п.повърхност()


def маса_дълга_изправена():
    """Дълга маса 64x128, изправена: дъските вървят отгоре надолу, виждаме долния ѝ ръб и краката."""
    п = Платно(64, 128)
    x0, x1, y0, y1 = 6, 58, 4, 108
    п.пр(x0, y0, x1, y1, СРЕДНО)
    колони = [(x0, x0 + 13, (30, 74)), (x0 + 13, x0 + 26, (14, 58, 92)), (x0 + 26, x0 + 39, (40, 84)), (x0 + 39, x1, (22, 66))]
    for (а, б, шевове) in колони:                       # дъски по дължината, с разминати шевове
        for y in range(y0, y1):
            п.т(а, y, ТЪМНО if а > x0 else СВЕТЛО)
            п.т(а + 1, y, СВЕТЛО)
        for ш in шевове:
            for x in range(а + 1, б):
                п.т(x, ш, ТЪМНО)
                п.т(x, ш + 1, СВЕТЛО)
        for (x, y) in ((а + 3, y0 + 3), (а + 3, y1 - 4)):
            п.т(x, y, ПО_ТЪМНО)
            п.т(x, y + 1, ПО_ТЪМНО)
        for k, ш in enumerate(шевове):                  # жилки в дървото
            yy = ш - 12 + k * 3
            for d in range(5):
                п.т((а + б) // 2, yy + d, ТЪМНО)
    for x in range(x0, x1):
        п.т(x, y0, СВЕТЛО)
    п.т(x0 + 1, y0 + 1, БЛЯСЪК)
    п.ръб(x0, y1, x1, y1 + 6)                           # предният (долен) ръб
    for x in (x0 + 2, x1 - 8):                          # предни крака
        п.крак(x, y1 + 6, x + 6, 126)
    for x in (x0 + 9, x1 - 14):                         # задни крака (в сянка)
        п.пр(x, y1 + 6, x + 5, 121, ПО_ТЪМНО)
    п.контур()
    return п.повърхност()


def пейка_отстрани():
    """Изправена пейка 64x128 (вляво от масата, седналите гледат надясно): тясна седалка
    по дължината, опряна до масата вдясно; виждаме долния ѝ край и краката отстрани."""
    п = Платно(64, 128)
    x0, x1, y0, y1 = 44, 62, 10, 116
    п.пр(x0, y0, x1, y1, СРЕДНО)
    for x in range(x0, x1):                             # две дъски по дължината
        п.т(x, y0, СВЕТЛО)
    for y in range(y0, y1):
        п.т(x0, y, СВЕТЛО)
        п.т(x0 + 1, y, СВЕТЛО)
        п.т(x0 + 9, y, ТЪМНО)
        п.т(x0 + 10, y, СВЕТЛО)
    for (x, y) in ((x0 + 3, y0 + 3), (x0 + 13, y0 + 3), (x0 + 3, 62), (x0 + 13, 62), (x0 + 3, y1 - 4), (x0 + 13, y1 - 4)):
        п.т(x, y, ПО_ТЪМНО)                             # гвоздейчета
    п.т(x0 + 2, y0 + 1, БЛЯСЪК)
    п.ръб(x0, y1, x1, y1 + 3)                           # долният край на седалката
    for y in (y0 + 6, 60):                              # крака под седалката (отстрани)
        п.пр(x0 - 3, y + 4, x0, y + 12, ТЪМНО)
    п.крак(x0 + 1, y1 + 3, x0 + 5, 127)                 # предните крака
    п.крак(x1 - 5, y1 + 3, x1 - 1, 127)
    п.контур()
    return п.повърхност()


def огледало(s):
    return pygame.transform.flip(s, True, False)


def главна():
    pygame.init()
    pygame.display.set_mode((1, 1))
    for име, s in (("chair_down", стол_надолу()), ("chair_up", стол_нагоре()),
                   ("chair_right", стол_надясно()), ("bench", пейка()), ("bench_up", пейка()),
                   ("table_big", маса_дълга()), ("table_big_v", маса_дълга_изправена()),
                   ("chair_left", огледало(стол_надясно())), ("bench_right", пейка_отстрани()),
                   ("bench_left", огледало(пейка_отстрани()))):
        pygame.image.save(s, os.path.join(ИГРА, "assets", име + ".png"))
        print("assets/%s.png" % име)


if __name__ == "__main__":
    главна()

class Платно:
    def __init__(с, w, h):
        с.w, с.h = w, h
        с.п = [[None] * w for _ in range(h)]

    def т(с, x, y, ц, обвий=False):
        if обвий:
            x %= с.w
            y %= с.h
        if 0 <= x < с.w and 0 <= y < с.h:
            с.п[y][x] = ц

    def правоъгълник(с, x0, y0, x1, y1, ц, обвий=False):
        for y in range(y0, y1):
            for x in range(x0, x1):
                с.т(x, y, ц, обвий)

    def повърхност(с):
        s = pygame.Surface((с.w, с.h), pygame.SRCALPHA)
        for y in range(с.h):
            for x in range(с.w):
                if с.п[y][x]:
                    s.set_at((x, y), с.п[y][x])
        return s


def камъни(пл, x0, y0, w, h, тонове, фуга, сл, мин_ш=11, макс_ш=19, вис=(9, 13), обвий=False):
    """Каменна зидария: редове камъни с фуги, светло горе вляво, тъмно долу вдясно."""
    y = y0
    отм = сл.randint(0, 8)
    while y < y0 + h:
        вр = min(сл.randint(*вис), y0 + h - y) if not обвий else сл.randint(*вис)
        if обвий and y + вр > y0 + h:
            вр = y0 + h - y
        x = x0 - отм
        while x < x0 + w:
            шир = сл.randint(мин_ш, макс_ш)
            основен = тонове[1] if сл.random() < 0.7 else (тонове[2] if сл.random() < 0.6 else тонове[0])
            for yy in range(y, y + вр):
                for xx in range(x, x + шир):
                    if not обвий and not (x0 <= xx < x0 + w):
                        continue
                    ръб_г = yy == y
                    ръб_л = xx == x
                    ръб_д = yy == y + вр - 1
                    ръб_дс = xx == x + шир - 1
                    if ръб_д or ръб_дс:
                        ц = фуга
                    elif ръб_г or ръб_л:
                        ц = тонове[0]
                    elif yy == y + вр - 2 or xx == x + шир - 2:
                        ц = тонове[2]
                    else:
                        ц = основен
                    пл.т(xx, yy, ц, обвий)
            # петънце за текстура
            if шир > 6 and вр > 5:
                пл.т(x + сл.randint(2, шир - 3), y + сл.randint(2, вр - 3), тонове[2], обвий)
            x += шир
        отм = (отм + сл.randint(5, 10)) % 16
        y += вр


def ръб_отгоре(сл=None):
    """64x64 бесшевна каменна корона на стена, гледана отгоре."""
    сл = сл or random.Random(7)
    пл = Платно(64, 64)
    пл.правоъгълник(0, 0, 64, 64, ТОП[1])
    камъни(пл, 0, 0, 64, 64, ТОП, ФУГА, сл, 12, 20, (10, 13), обвий=True)
    return пл


def основа_лице(пл, сл, горе=32):
    """Лицето на стената: греда под ръба, мазилка с подпори, каменен цокъл."""
    д = горе + 64
    # корона (горните 32 px) = горната половина на ръба отгоре -> слепва се със страничните стени
    т = ръб_отгоре()
    for y in range(горе):
        for x in range(64):
            пл.т(x, y, т.п[y + 16][x])
    for x in range(64):
        пл.т(x, горе - 1, КОНТУР)                        # тъмен ръб на короната
    # мазилка
    пл.правоъгълник(0, горе, 64, д, МАЗ[1])
    for y in range(горе, д):                              # лека сянка под гредата и към цокъла
        for x in range(64):
            if y < горе + 10:
                пл.т(x, y, МАЗ[2])
    for _ in range(26):                                   # неравна мазилка
        x, y = сл.randint(0, 63), сл.randint(горе + 10, д - 22)
        пл.т(x, y, МАЗ[0] if сл.random() < 0.5 else МАЗ[2])
    # пукнатинка
    x, y = 41, горе + 22
    for k in range(6):
        пл.т(x, y, МАЗ[3])
        x += сл.choice((0, 1))
        y += 1
    # хоризонтална греда под короната
    пл.правоъгълник(0, горе, 64, горе + 7, ДЪРВО[1])
    for x in range(64):
        пл.т(x, горе, ДЪРВО[0])
        пл.т(x, горе + 5, ДЪРВО[2])
        пл.т(x, горе + 6, ДЪРВО[3])
        if x % 9 == 3:
            пл.т(x, горе + 2, ДЪРВО[2])                   # жилки
            пл.т(x + 1, горе + 3, ДЪРВО[2])
    # вертикална подпора на ръба на всяка плочка (две половинки по 3 px -> 6 px при съседите)
    for y in range(горе + 7, д - 18):
        for x, ц in ((0, ДЪРВО[1]), (1, ДЪРВО[1]), (2, ДЪРВО[2]), (61, ДЪРВО[0]), (62, ДЪРВО[1]), (63, ДЪРВО[1])):
            пл.т(x, y, ц)
        if y % 7 == 0:
            пл.т(1, y, ДЪРВО[2])
            пл.т(62, y, ДЪРВО[2])
    # каменен цокъл
    камъни(пл, 0, д - 18, 64, 18, КАМ, КАМ[3], random.Random(3), 10, 17, (8, 10))
    for x in range(64):
        пл.т(x, д - 19, ДЪРВО[3])                         # тъмна линия над цокъла
        пл.т(x, д - 1, КАМ[3])
    return пл


def стена():
    return основа_лице(Платно(64, 96), random.Random(11))


def прозорец():
    пл = основа_лице(Платно(64, 96), random.Random(11))
    x0, y0, x1, y1 = 17, 44, 47, 70                       # рамка
    пл.правоъгълник(x0 - 1, y0 - 1, x1 + 1, y1 + 1, КОНТУР)
    пл.правоъгълник(x0, y0, x1, y1, ДЪРВО[1])
    пл.правоъгълник(x0 + 2, y0 + 2, x1 - 2, y1 - 2, СТЪКЛО[1])
    for y in range(y0 + 2, y1 - 2):                       # стъкло: по-тъмно долу
        for x in range(x0 + 2, x1 - 2):
            if y > y0 + 13:
                пл.т(x, y, СТЪКЛО[2])
    for k in range(6):                                    # отблясък
        пл.т(x0 + 4 + k, y0 + 9 - k, СТЪКЛО[0])
        пл.т(x0 + 19 + k, y0 + 9 - k, СТЪКЛО[0])
    пл.правоъгълник((x0 + x1) // 2 - 1, y0, (x0 + x1) // 2 + 1, y1, ДЪРВО[2])   # кръст
    пл.правоъгълник(x0, (y0 + y1) // 2 - 1, x1, (y0 + y1) // 2 + 1, ДЪРВО[2])
    for x in range(x0, x1):
        пл.т(x, y0, ДЪРВО[0])
    # перваз
    пл.правоъгълник(x0 - 3, y1 + 1, x1 + 3, y1 + 4, ДЪРВО[1])
    for x in range(x0 - 3, x1 + 3):
        пл.т(x, y1 + 1, ДЪРВО[0])
        пл.т(x, y1 + 4, КОНТУР)
    пл.т(x0 - 4, y1 + 2, КОНТУР); пл.т(x0 - 4, y1 + 3, КОНТУР)
    пл.т(x1 + 3, y1 + 2, КОНТУР); пл.т(x1 + 3, y1 + 3, КОНТУР)
    # саксия с мушкато
    пл.правоъгълник(26, y1 - 4, 38, y1 + 1, hx("#b4643c"))
    for x in range(26, 38):
        пл.т(x, y1 - 4, hx("#d07a4a"))
        пл.т(x, y1, hx("#8a4a2c"))
    for (x, y) in ((25, y1 - 4), (38, y1 - 4), (25, y1 - 3), (38, y1 - 3), (26, y1 + 1), (37, y1 + 1)):
        пл.т(x, y, КОНТУР)
    for (x, y, ц) in ((27, y1 - 6, ЗЕЛЕНО[1]), (29, y1 - 7, ЗЕЛЕНО[0]), (35, y1 - 6, ЗЕЛЕНО[1]), (33, y1 - 7, ЗЕЛЕНО[2]),
                      (31, y1 - 6, ЗЕЛЕНО[1]), (28, y1 - 5, ЗЕЛЕНО[2]), (36, y1 - 5, ЗЕЛЕНО[2])):
        пл.т(x, y, ц)
        пл.т(x + 1, y, ц)
    for (cx, cy) in ((28, y1 - 9), (32, y1 - 11), (36, y1 - 9)):   # цветове
        for (dx, dy, ц) in ((0, 0, ЧЕРВЕНО[1]), (1, 0, ЧЕРВЕНО[0]), (-1, 0, ЧЕРВЕНО[1]), (0, -1, ЧЕРВЕНО[0]),
                            (0, 1, ЧЕРВЕНО[2]), (1, 1, ЧЕРВЕНО[2]), (-1, 1, ЧЕРВЕНО[2])):
            пл.т(cx + dx, cy + dy, ц)
    return пл


def врата():
    пл = основа_лице(Платно(64, 96), random.Random(11))
    x0, x1, y0, y1 = 16, 48, 42, 96                        # отвор с полукръгла арка
    cx, r = 32, 16
    for y in range(y0 - 6, y1):
        for x in range(x0 - 3, x1 + 3):
            вътре_рамка = y >= y0 + 6 or (x - cx + 0.5) ** 2 + (y - (y0 + 6) + 0.5) ** 2 <= (r + 3) ** 2
            вътре = y >= y0 + 6 or (x - cx + 0.5) ** 2 + (y - (y0 + 6) + 0.5) ** 2 <= r ** 2
            if x0 <= x < x1 and вътре:
                # дъски на вратата
                л = (x - x0) % 8
                ц = ДЪРВО[1] if л not in (0, 7) else (ДЪРВО[3] if л == 7 else ДЪРВО[0])
                if x > cx + 8:
                    ц = ДЪРВО[2] if л not in (0, 7) else ДЪРВО[3]
                пл.т(x, y, ц)
            elif вътре_рамка and x0 - 3 <= x < x1 + 3:
                пл.т(x, y, КАМ[1] if (x + y) % 5 else КАМ[2])
    # контур на арката
    for y in range(y0 - 7, y1):
        for x in range(x0 - 4, x1 + 4):
            if пл.п[y][x] in (КАМ[1], КАМ[2]):
                for dx, dy in ((1, 0), (-1, 0), (0, -1)):
                    X, Y = x + dx, y + dy
                    if 0 <= X < 64 and пл.п[Y][X] not in (КАМ[1], КАМ[2], ДЪРВО[0], ДЪРВО[1], ДЪРВО[2], ДЪРВО[3]):
                        пл.т(X, Y, КОНТУР)
    # железни обкови и халка
    ЖЕЛ, ЖЕЛ2 = hx("#3a3a40"), hx("#6a6a74")
    for y in (y0 + 14, y0 + 38):
        for x in range(x0 + 1, x1 - 6):
            пл.т(x, y, ЖЕЛ)
            пл.т(x, y - 1, ЖЕЛ2)
        пл.т(x0 + 3, y + 1, ЖЕЛ)
    for (dx, dy) in ((0, 0), (1, 0), (-1, 1), (2, 1), (-1, 2), (2, 2), (0, 3), (1, 3)):
        пл.т(x1 - 9 + dx, y0 + 26 + dy, hx("#c9a24a") if dy < 2 else hx("#8a6a2a"))
    # праг
    пл.правоъгълник(x0 - 3, 93, x1 + 3, 96, КАМ[0])
    for x in range(x0 - 3, x1 + 3):
        пл.т(x, 95, КАМ[3])
    return пл


def вход_отгоре():
    """Вход в стена, гледан отгоре: дъсчен под, каменен праг, черга."""
    пл = Платно(64, 64)
    # под (дъски надолу)
    for y in range(64):
        for x in range(64):
            л = x % 16
            ц = ПОД[1] if л not in (0, 15) else (ПОД[3] if л == 15 else ПОД[0])
            if (y + (x // 16) * 23) % 40 == 0:
                ц = ПОД[3]
            пл.т(x, y, ц)
    # дървени каси отстрани
    for y in range(64):
        for x, ц in ((0, КОНТУР), (1, ДЪРВО[1]), (2, ДЪРВО[1]), (3, ДЪРВО[2]), (4, КОНТУР),
                     (59, КОНТУР), (60, ДЪРВО[0]), (61, ДЪРВО[1]), (62, ДЪРВО[1]), (63, КОНТУР)):
            пл.т(x, y, ц)
    # каменен праг по средата
    пл.правоъгълник(5, 26, 59, 38, КАМ[1])
    for x in range(5, 59):
        пл.т(x, 26, КАМ[0])
        пл.т(x, 37, КАМ[3])
        пл.т(x, 25, КОНТУР)
        пл.т(x, 38, КОНТУР)
    for x in (22, 41):
        for y in range(27, 37):
            пл.т(x, y, КАМ[3])
    # черга (шарена, червено-черна) към вътрешността
    for y in range(4, 22):
        for x in range(12, 52):
            ряд = (y - 4) // 3
            ц = (ЧЕРВЕНО[1], hx("#2a2230"), ЧЕРВЕНО[0], hx("#e8d6a8"), ЧЕРВЕНО[1], hx("#2a2230"))[ряд % 6]
            if ряд % 6 == 3 and (x // 3) % 2:
                ц = ЧЕРВЕНО[2]
            пл.т(x, y, ц)
        пл.т(11, y, КОНТУР)
        пл.т(52, y, КОНТУР)
    for x in range(12, 52, 2):                            # ресни
        пл.т(x, 3, hx("#e8d6a8"))
        пл.т(x, 22, hx("#e8d6a8"))
    return пл


def главна():
    pygame.init()
    pygame.display.set_mode((1, 1))
    for име, пл in (("wall", стена()), ("window", прозорец()), ("door", врата()),
                    ("wall_top", ръб_отгоре()), ("door_top", вход_отгоре())):
        pygame.image.save(пл.повърхност(), os.path.join(АСЕТИ, име + ".png"))
        print("assets/%s.png" % име)


if __name__ == "__main__":
    главна()

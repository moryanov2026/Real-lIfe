# Прерисува предмет "от другата страна" (завъртян на 90 градуса).
# Работи добре за мебели-кутии: маса, пейка, легло, сандък, тезгях.
# За стол, герой или сложни предмети дава само ЧЕРНОВА, която се довършва в Piskel.
#
# Как работи: картинката се дели на ПЛОТ (горе) и КРАКА/ПРЕДНА СТЕНА (долу).
#   - плотът се "транспонира" (завърта се на 90° и се огледва), за да остане
#     светлината горе вляво, както е по правилата;
#   - краката се свиват/разтягат до новата ширина;
#   - размерът се сменя: 128x64 става 64x128, 64x64 остава 64x64.
#
# Пускане:  python tools/rotate.py assets/table.png
#           python tools/rotate.py assets/bench.png --legs 20   (ако краката не са разпознати добре)
# Резултат: drafts/<име>_right.png и drafts/<име>_preview.png (уголемено, за преглед)
import argparse
import os
import sys

os.environ.setdefault("PYGAME_HIDE_SUPPORT_PROMPT", "1")
os.environ.setdefault("SDL_VIDEODRIVER", "dummy")
import pygame

ПЛОЧКА = 64
ЦВЯТ_КОНТУР = (25, 20, 30)


def ред_плътност(с, y, x0, x1):
    return sum(1 for x in range(x0, x1) if с.get_at((x, y)).a >= 128)


def намери_краката(с, рамка):
    """Краката започват там, където редът става чувствително по-тесен от плота."""
    макс = max(ред_плътност(с, y, рамка.left, рамка.right) for y in range(рамка.top, рамка.bottom))
    for y in range(рамка.top + рамка.height // 3, рамка.bottom):
        if ред_плътност(с, y, рамка.left, рамка.right) < макс * 0.7:
            return y
    return рамка.bottom - max(1, рамка.height // 4)    # не намерихме: последната четвърт


def транспонирай(с):
    """Завъртане на 90° + огледало = смяна на редове и колони. Горе-вляво остава горе-вляво."""
    return pygame.transform.flip(pygame.transform.rotate(с, -90), True, False)


def яркост(ц):
    return ц.r * 0.3 + ц.g * 0.59 + ц.b * 0.11


def средна_яркост(с, y, x0, x1):
    стойности = [яркост(с.get_at((x, y))) for x in range(x0, x1) if с.get_at((x, y)).a >= 128]
    return sum(стойности) / len(стойности) if стойности else 0


def намери_предната_стена(с, рамка, граница):
    """Предната стена (тъмната дъска под плота) е група тъмни редове точно над краката.
    Тя НЕ се завърта: остава отпред, под плота."""
    редове = list(range(рамка.top, граница))
    if len(редове) < 6:
        return граница
    горни = sorted(средна_яркост(с, y, рамка.left, рамка.right) for y in редове[: len(редове) * 3 // 5])
    плот = горни[len(горни) // 2]                     # средна яркост на дъските
    y = граница
    while y - 1 > рамка.top + len(редове) * 3 // 5 and \
            средна_яркост(с, y - 1, рамка.left, рамка.right) < плот * 0.8:
        y -= 1
    return y


def завърти(път, крака=None):
    с = pygame.image.load(път).convert_alpha()
    W, H = с.get_size()
    рамка = с.get_bounding_rect(min_alpha=128)
    граница = рамка.bottom - крака if крака else намери_краката(с, рамка)
    стена_y = намери_предната_стена(с, рамка, граница)
    плот = с.subsurface((рамка.left, рамка.top, рамка.width, стена_y - рамка.top)).copy()
    долу = с.subsurface((рамка.left, стена_y, рамка.width, рамка.bottom - стена_y)).copy()

    # Новото платно: заемането в клетки се разменя (2x1 -> 1x2)
    кл_ш, кл_в = max(1, W // ПЛОЧКА), max(1, H // ПЛОЧКА)
    нов_W, нов_H = кл_в * ПЛОЧКА, кл_ш * ПЛОЧКА
    # Плотът е "сплескан" от гледането под ъгъл: k = видима дълбочина / истинска дълбочина.
    # Истинската дълбочина приемаме по клетките (1 клетка дълбок, кл_ш клетки широк).
    w, t = рамка.width, плот.get_height()
    истинска_дълбочина = w * кл_в / кл_ш
    k = t / истинска_дълбочина
    нова_ш = round(t / k)            # новата ширина = старата дълбочина
    нов_плот_в = round(w * k)        # новата видима дълбочина = старата ширина, сплескана
    височина_долу = долу.get_height()
    # да се побере в платното, с 2 px празно отстрани и отгоре
    нова_ш = max(8, min(нова_ш, нов_W - 4))
    нов_плот_в = max(4, min(нов_плот_в, нов_H - височина_долу - 2))

    нов_плот = pygame.transform.scale(транспонирай(плот), (нова_ш, нов_плот_в))   # scale = без размазване
    нов_долу = pygame.transform.scale(долу, (нова_ш, височина_долу))

    изход = pygame.Surface((нов_W, нов_H), pygame.SRCALPHA)
    x = (нов_W - нова_ш) // 2
    дъно = нов_H - (H - рамка.bottom)          # същото празно място отдолу като в оригинала
    изход.blit(нов_долу, (x, дъно - височина_долу))
    изход.blit(нов_плот, (x, дъно - височина_долу - нов_плот_в))
    return дорисувай_контур(изход), t, височина_долу


def дорисувай_контур(с):
    """След завъртането една страна остава без тъмен контур: слагаме го наново (1 px)."""
    w, h = с.get_size()
    изход = с.copy()
    for y in range(h):
        for x in range(w):
            if с.get_at((x, y)).a >= 128:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < w and 0 <= ny < h and с.get_at((nx, ny)).a >= 128 \
                        and с.get_at((nx, ny))[:3] != ЦВЯТ_КОНТУР:
                    изход.set_at((x, y), (*ЦВЯТ_КОНТУР, 255))
                    break
    return изход


def главна():
    п = argparse.ArgumentParser(description="Завърта мебел на 90° (чернова за другата посока)")
    п.add_argument("картинка")
    п.add_argument("--legs", type=int, default=None, help="височина на краката в пиксели (ако автоматичното не става)")
    п.add_argument("--out", default="drafts")
    а = п.parse_args()
    pygame.init()
    pygame.display.set_mode((1, 1))
    os.makedirs(а.out, exist_ok=True)
    име = os.path.splitext(os.path.basename(а.картинка))[0]
    for наставка in ("_down", "_up", "_right", "_left"):
        if име.endswith(наставка):
            име = име[: -len(наставка)]
    резултат, плот_в, долу_в = завърти(а.картинка, а.legs)
    път = os.path.join(а.out, име + "_right.png")
    pygame.image.save(резултат, път)
    # преглед: оригинал и завъртян един до друг, уголемени x4 върху сив фон
    ориг = pygame.image.load(а.картинка)
    ш = (ориг.get_width() + резултат.get_width() + 16) * 4
    в = max(ориг.get_height(), резултат.get_height()) * 4
    преглед = pygame.Surface((ш, в))
    преглед.fill((150, 110, 70))
    преглед.blit(pygame.transform.scale(ориг, (ориг.get_width() * 4, ориг.get_height() * 4)), (0, в - ориг.get_height() * 4))
    преглед.blit(pygame.transform.scale(резултат, (резултат.get_width() * 4, резултат.get_height() * 4)),
                 ((ориг.get_width() + 16) * 4, в - резултат.get_height() * 4))
    pygame.image.save(преглед, os.path.join(а.out, име + "_preview.png"))
    print("OK  %s -> %s  (%dx%d), плот %d px, предна стена и крака %d px" % (
        а.картинка, път, *резултат.get_size(), плот_в, долу_в))
    print("Провери %s. Ако краката са сбъркани, пусни пак с --legs <число>." % os.path.join(а.out, име + "_preview.png"))
    return 0


if __name__ == "__main__":
    sys.exit(главна())

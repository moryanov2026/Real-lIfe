class Персона:
    """Един човек в играта. Управлява го или играч (контролер = номер на клиента), или NPC (None)."""

    def __init__(self, данни):
        self.id = данни["id"]
        self.име = данни.get("name", self.id)
        self.роля = данни.get("role", "жител")
        self.цвят = данни.get("color", [200, 200, 200])
        self.старт = данни.get("start")
        self.данни = данни                      # характер, предпочитания (за следващите етапи)
        self.x = self.y = 0.0                   # средата на долния ръб (краката)
        self.енергия = float(МАКС_ЕНЕРГИЯ)
        self.пари = данни.get("money", НАЧАЛНИ_ПАРИ)
        self.контролер = None
        self.играч = ""
        self.dx = self.dy = 0.0
        self.върви = False
        self.посока = "down"
        self.свири = False                      # музикантът свири (миниигра "Свирене")
        self.настроение = 0.0                   # колко добре свири (0-1), праща го минииграта
        self.фаза_хоро = 0.0                    # докъде се е завъртяло хорото около музиканта
        self.хоро = 0.0                         # NPC играе хоро: силата (0 = не играе)
        self.песен = None                       # NPC музикантът свири тази песен (име на файла), поръчана от собственика
        self.песен_време = 0.0                  # от колко секунди свири поръчаната песен
        self.песен_дължина = 0.0
        self.до_хоро = 0.0                      # след колко секунди започва хорото около него
        # поръчки
        self.иска = None                        # гост: какво е поръчал (ключ от data/items.json)
        self.търпение = 0.0                     # гост: колко секунди още ще чака
        self.поръчка_след = 0.0                 # гост: след колко секунди ще поръча (току-що седна)
        self.яде = None                         # гост: какво яде / пие в момента
        self.яде_време = 0.0
        self.ядосан = 0.0                       # гост: чака твърде дълго и си тръгна ядосан (секунди)
        self.носи = None                        # персонал: какво носи в ръцете
        self.качество = 0.6                     # колко хубаво е това, което носи (0-1, от мини играта при готвене)
        self.задача = None                      # NPC персонал: (вид, цел)
        self.път = []                           # NPC персонал: точките по пътя до целта (около масите)
        self.път_до = None
        self.седи = None                        # номер на мястото (стол/пейка), на което седи
        self.преди_сядане = None                # откъде е седнал (там става)
        self.към_място = None                   # NPC отива да седне на това място
        # само за NPC
        self.цел = None
        self.почивка = 0.0
        self.заседнал = 0.0

    def кутия(self, x=None, y=None):
        x = self.x if x is None else x
        y = self.y if y is None else y
        return pygame.Rect(int(x - СБЛЪСЪК_ШИРИНА / 2), int(y - СБЛЪСЪК_ВИСОЧИНА),
                           СБЛЪСЪК_ШИРИНА, СБЛЪСЪК_ВИСОЧИНА)

    def мръдни(self, dx, dy, препятствия, време, скорост):
        """Движим по една ос, за да може да се плъзга покрай стените."""
        дължина = math.hypot(dx, dy)
        self.върви = дължина > 0.01
        if not self.върви:
            return
        if дължина > 1:                          # по диагонал да не е по-бърз
            dx, dy = dx / дължина, dy / дължина
        if abs(dx) > abs(dy):
            self.посока = "right" if dx > 0 else "left"
        else:
            self.посока = "down" if dy > 0 else "up"
        нов_x = self.x + dx * скорост * време
        if not any(self.кутия(нов_x, self.y).colliderect(о) for о in препятствия):
            self.x = нов_x
        нов_y = self.y + dy * скорост * време
        if not any(self.кутия(self.x, нов_y).colliderect(о) for о in препятствия):
            self.y = нов_y

    def описание(self):
        """Неща, които не се менят: пращат се веднъж."""
        return {"id": self.id, "name": self.име, "role": self.роля, "color": self.цвят}

    def състояние(self):
        """Неща, които се менят: пращат се всеки тик."""
        return {"id": self.id, "x": round(self.x, 1), "y": round(self.y, 1),
                "ctrl": "human" if self.контролер is not None else "npc", "player": self.играч,
                "walk": self.върви, "dir": self.посока, "play": self.свири, "dance": self.хоро,
                "sit": self.посока if self.седи is not None else "",
                "energy": round(self.енергия), "money": self.пари,
                "song": self.песен or "", "song_t": round(self.песен_време, 2),
                "hold": self.носи or "", "want": self.иска or "", "eat": self.яде or "",
                "wait": round(self.търпение, 1), "angry": self.ядосан > 0}


class Свят:
    def __init__(self, път_карта=ПЪТ_КАРТА, папка_персони=ПАПКА_ПЕРСОНИ, семе=None):
        self.случаен = random.Random(семе)
        self.плочки = tiles.зареди_плочки()
        self.карта = tiles.зареди_карта(път_карта)
        self.цени, self.разширяване = зареди_каталог()
        try:
            self.меню = poruchki.зареди()
        except (OSError, ValueError):
            self.меню = {"предмети": {}, "сервират": [], "гости": [], "търпение": 90,
                         "поръчва_след": [2, 5], "яде": [12, 20], "бакшиш": [0, 3]}
        self.станции = {}                       # (x, y) -> {"предмет", "остава", "готово", "кой"}
        self._подреди()
        self.персони = {}
        for п in зареди_персони(папка_персони):
            клетка = tuple(п.старт) if п.старт and tuple(п.старт) in self.свободни else self.случайна_клетка()
            п.x, п.y = self.център(клетка)
            self.персони[п.id] = п
        self.минути = НАЧАЛЕН_ЧАС
        self.ден = 1
        self._натрупано = 0.0

    def _подреди(self):
        """Всичко, което идва от картата: препятствия, свободни клетки, места за сядане.
        Вика се при старта и след всяка промяна в режима за строене."""
        self.колони, self.редове = self.карта["width"], self.карта["height"]
        self.заети = set()                      # клетки с твърд предмет
        self.препятствия = []
        for о in self.карта["objects"]:
            д = self.плочки.get(о["name"])
            if д and д["solid"]:
                self.препятствия.append(pygame.Rect(о["x"] * ПЛОЧКА, о["y"] * ПЛОЧКА,
                                                    д["w"] * ПЛОЧКА, д["h"] * ПЛОЧКА))
                for yy in range(о["y"], о["y"] + д["h"]):
                    for xx in range(о["x"], о["x"] + д["w"]):
                        self.заети.add((xx, yy))
        ш, в = self.колони * ПЛОЧКА, self.редове * ПЛОЧКА
        self.препятствия += [pygame.Rect(-ПЛОЧКА, 0, ПЛОЧКА, в), pygame.Rect(ш, 0, ПЛОЧКА, в),
                             pygame.Rect(0, -ПЛОЧКА, ш, ПЛОЧКА), pygame.Rect(0, в, ш, ПЛОЧКА)]
        self.свободни = [(x, y) for y in range(self.редове) for x in range(self.колони)
                         if (x, y) not in self.заети and self.карта["floor"][y][x]]
        # мебели, на които се приготвя храна и пиене (data/items.json)
        self.станции_списък = poruchki.станции_на_карта(self.карта, getattr(self, "меню", {"предмети": {}}))
        if hasattr(self, "станции"):
            има = {(с[0], с[1]) for с in self.станции_списък}
            self.станции = {к: в for к, в in self.станции.items() if к in има}
        # места за сядане: всеки стол е едно място, пейката (2 клетки) - две
        self.места = []
        for о in self.карта["objects"]:
            посока = СТОЛОВЕ.get(о["name"])
            if посока is None:
                continue
            д = self.плочки.get(о["name"], {})
            мx, мy = МЕСТЕНЕ_НА_СТОЛА.get(о["name"], (0, 0))
            for к in range(д.get("w", 1)):          # широка пейка: място на всяка клетка надясно
                for р in range(д.get("h", 1)):      # изправена пейка: място на всяка клетка надолу
                    self.места.append({"x": (о["x"] + к) * ПЛОЧКА + ПЛОЧКА / 2 + мx,
                                       "y": (о["y"] + р + 1) * ПЛОЧКА - 12 + мy, "dir": посока})

    # ---------- помощни ----------
    def център(self, клетка):
        return клетка[0] * ПЛОЧКА + ПЛОЧКА / 2, (клетка[1] + 1) * ПЛОЧКА - 8

    def случайна_клетка(self):
        return self.случаен.choice(self.свободни)

    # ---------- кой управлява коя персона ----------
    def вземи(self, пид, клиент, име):
        п = self.персони.get(пид)
        if п is None or п.контролер is not None:
            return False
        self.освободи(клиент)                   # един клиент = една персона
        self.спри_песен(п)                      # поръчаната песен спира: вече го управлява играч
        п.контролер, п.играч = клиент, име
        п.dx = п.dy = 0.0
        п.цел = None
        return True

    def освободи(self, клиент):
        """Играчът излезе: NPC поема персоната му (GAME_RULES, раздел 3а)."""
        for п in self.персони.values():
            if п.контролер == клиент:
                п.контролер, п.играч = None, ""
                п.dx = п.dy = 0.0
                п.свири = False
                п.почивка = max(п.почивка, 1.0)
                п.почивка = 1.0

    # ---------- режим за строене (B) ----------
    def _строител(self, клиент):
        for п in self.персони.values():
            if п.контролер == клиент:
                return п if п.роля in СТРОИТЕЛИ else None
        return None

    def _предмет_в(self, x, y):
        for о in reversed(self.карта["objects"]):
            д = self.плочки.get(о["name"], {"w": 1, "h": 1})
            if о["x"] <= x < о["x"] + д["w"] and о["y"] <= y < о["y"] + д["h"]:
                return о
        return None

    def провери_място(self, име, x, y):
        """None = може да се сложи, иначе причината."""
        д = self.плочки.get(име)
        if not д:
            return "Няма такава мебел"
        for yy in range(y, y + д["h"]):
            for xx in range(x, x + д["w"]):
                if not (0 <= xx < self.колони and 0 <= yy < self.редове) or not self.карта["floor"][yy][xx]:
                    return "Извън кръчмата"
                if self._предмет_в(xx, yy):
                    return "Мястото е заето"
        if д["solid"]:
            кутия = pygame.Rect(x * ПЛОЧКА, y * ПЛОЧКА, д["w"] * ПЛОЧКА, д["h"] * ПЛОЧКА)
            if any(п.кутия().colliderect(кутия) for п in self.персони.values()):
                return "Някой стои там"
        return None

    def _след_промяна(self):
        for п in self.персони.values():            # местата се номерират наново: всички стават
            self.стани(п)
            п.към_място, п.цел = None, None
        self._подреди()

    def строй(self, клиент, действие, име=None, x=0, y=0, страна=None):
        """Връща (успех, текст). действие: "place", "remove", "expand"."""
        п = self._строител(клиент)
        if п is None:
            return False, "Само собственикът и кръчмарят могат да строят"
        x, y = int(x), int(y)
        if действие == "place":
            if име not in self.цени:
                return False, "Това не се продава"
            наименование, цена, _ = self.цени[име]
            if п.пари < цена:
                return False, "Нямаш достатъчно пари (%s струва %d)" % (наименование, цена)
            причина = self.провери_място(име, x, y)
            if причина:
                return False, причина
            п.пари -= цена
            self.карта["objects"].append({"name": име, "x": x, "y": y})
            self._след_промяна()
            return True, "%s: -%d" % (наименование, цена)
        if действие == "remove":
            о = self._предмет_в(x, y)
            if о is None or о["name"] in tiles.СТЕНИ:
                return False, "Тук няма мебел"
            наименование, цена, _ = self.цени.get(о["name"], (о["name"], 0, None))
            self.карта["objects"].remove(о)
            п.пари += цена                              # вдигната мебел връща парите (може да се сложи другаде)
            self._след_промяна()
            return True, "%s: +%d" % (наименование, цена)
        if действие == "expand":
            р = self.разширяване
            цена = р.get("цена", 200)
            if п.пари < цена:
                return False, "Разширяването струва %d" % цена
            if страна == "right":
                if self.колони + р.get("надясно", 4) > р.get("най_широко", 40):
                    return False, "Кръчмата не може да е по-широка"
                self._разшири_надясно(р.get("надясно", 4))
            elif страна == "down":
                if self.редове + р.get("надолу", 3) > р.get("най_високо", 24):
                    return False, "Кръчмата не може да е по-дълга"
                self._разшири_надолу(р.get("надолу", 3))
            else:
                return False, "Непозната посока"
            п.пари -= цена
            self._след_промяна()
            return True, "Кръчмата е по-голяма: -%d" % цена
        return False, "Непознато действие"

    def _разшири_надясно(self, n):
        к = self.карта
        W, H = к["width"], к["height"]
        for о in к["objects"]:
            if о["x"] == W - 1:                       # дясната стена (и ъглите) отиват навън
                о["x"] += n
        for y in (0, H - 1):                          # горната и долната стена продължават
            for x in range(W - 1, W - 1 + n):
                к["objects"].append({"name": "wall", "x": x, "y": y})
        к["floor"] = [ред + ["floor"] * n for ред in к["floor"]]
        к["width"] = W + n

    def _разшири_надолу(self, n):
        к = self.карта
        W, H = к["width"], к["height"]
        for о in к["objects"]:
            if о["y"] == H - 1:                       # долната стена (с вратите) слиза надолу
                о["y"] += n
        for x in (0, W - 1):
            for y in range(H - 1, H - 1 + n):
                к["objects"].append({"name": "wall", "x": x, "y": y})
        к["floor"] = к["floor"] + [["floor"] * W for _ in range(n)]
        к["height"] = H + n

    # ---------- сядане ----------
    def заето(self, място):
        return any(п.седи == място for п in self.персони.values())

    def седни(self, п, място):
        м = self.места[място]
        п.преди_сядане = (п.x, п.y)
        п.x, п.y = м["x"], м["y"]
        п.седи, п.посока, п.върви = място, м["dir"], False
        п.dx = п.dy = 0.0
        п.към_място = None
        if п.контролер is None and self.гост(п) and self.налични():
            п.поръчка_след = self.случаен.uniform(*self.меню["поръчва_след"])

    def стани(self, п):
        if п.седи is None:
            return
        п.седи = None
        п.иска = п.яде = None                   # стана: поръчката се отменя
        п.поръчка_след = п.търпение = п.яде_време = 0.0
        if п.преди_сядане:
            п.x, п.y = п.преди_сядане
        п.преди_сядане = None

    def сядане(self, клиент):
        """F: седни на най-близкия свободен стол или стани."""
        for п in self.персони.values():
            if п.контролер != клиент or п.свири:
                continue
            if п.седи is not None:
                self.стани(п)
                return True
            свободни = [(math.hypot(м["x"] - п.x, м["y"] - п.y), и) for и, м in enumerate(self.места)
                        if not self.заето(и)]
            свободни = [с for с in свободни if с[0] <= ДО_СТОЛА]
            if свободни:
                self.седни(п, min(свободни)[1])
                return True
        return False

    def вход(self, клиент, dx, dy):
        for п in self.персони.values():
            if п.контролер == клиент:
                п.dx = max(-1.0, min(1.0, float(dx)))
                п.dy = max(-1.0, min(1.0, float(dy)))

    def свирене(self, клиент, пуснато, резултат=None):
        """Музикантът започна или свърши песен. Връща бакшиша (пари) след песента."""
        for п in self.персони.values():
            if п.контролер != клиент:
                continue
            п.свири = bool(пуснато)
            п.dx = п.dy = 0.0
            п.настроение = 0.6 if пуснато else 0.0
            if пуснато or not isinstance(резултат, dict):
                return 0
            процент = max(0.0, min(100.0, float(резултат.get("percent", 0))))
            част = max(0.0, min(1.0, float(резултат.get("tip_factor", 1.0))))   # лесно ниво = по-малък бакшиш
            бакшиш = int(round(процент * БАКШИШ_ЗА_100 / 100.0 * част))
            п.пари += бакшиш
            п.енергия = max(0.0, п.енергия - ЕНЕРГИЯ_ПЕСЕН)
            return бакшиш
        return 0

    def ново_настроение(self, клиент, стойност):
        """Минииграта казва колко добре свири музикантът (0-1)."""
        for п in self.персони.values():
            if п.контролер == клиент and п.свири:
                п.настроение = max(0.0, min(1.0, float(стойност)))

    # ---------- поръчки: гостите поръчват, персоналът приготвя и сервира ----------
    def гост(self, п):
        return poruchki.гост(п.роля, self.меню)

    def налични(self):
        """Какво може да се поръча: само неща, чиято мебел я има в кръчмата."""
        return sorted({с[3] for с in self.станции_списък})

    def име_на(self, предмет):
        return self.меню["предмети"].get(предмет, {}).get("име", предмет)

    def _поръчай(self, п):
        налични = self.налични()
        if not налични:
            return False
        п.иска = self.случаен.choice(налични)
        п.търпение = float(self.меню["търпение"])
        п.поръчка_след = 0.0
        return True

    def _гост_седи(self, п, време):
        """Гост на маса: поръчва, чака, яде. Връща True, докато е зает (NPC остава седнал)."""
        if п.яде:
            п.яде_време -= време
            п.върви = False
            if п.яде_време <= 0:
                п.яде = None
                if п.контролер is None:          # NPC: изял е, става и си тръгва
                    self.стани(п)
                    п.почивка = self.случаен.uniform(NPC_ПОЧИВКА_ОТ, NPC_ПОЧИВКА_ДО)
                return False
            return True
        if п.иска:
            п.търпение -= време
            п.върви = False
            if п.търпение <= 0:                  # чака твърде дълго: тръгва си ядосан
                п.ядосан = 4.0
                if п.контролер is None:
                    self.стани(п)
                    п.почивка = 1.0
                else:
                    п.иска = None
                return False
            return True
        if п.поръчка_след > 0:
            п.поръчка_след -= време
            п.върви = False
            if п.поръчка_след <= 0:
                self._поръчай(п)
            return True
        return False

    def _търсено(self, предмет, без=None):
        """Колко още трябва да се приготвят: искани - (в ръце + готови + в приготвяне)."""
        искани = sum(1 for п in self.персони.values() if п.иска == предмет and п.седи is not None)
        вече = sum(1 for п in self.персони.values() if п.носи == предмет)
        вече += sum(1 for ст in self.станции.values() if ст["предмет"] == предмет)
        return искани - вече

    def _станция(self, ключ):
        return next((с for с in self.станции_списък if (с[0], с[1]) == ключ), None)

    def _сервирай(self, п, г):
        предмет = п.носи
        г.иска, г.яде = None, предмет
        г.яде_време = self.случаен.uniform(*self.меню["яде"])
        п.носи = None
        цена = int(self.меню["предмети"].get(предмет, {}).get("цена", 0))
        собственик = next((с for с in self.персони.values() if с.роля == "собственик"), None)
        if собственик:
            собственик.пари += цена                # парите отиват в кръчмата (при собственика)
        бакшиш = self.случаен.randint(*self.меню["бакшиш"])
        бакшиш += max(0, int(round((п.качество - 0.5) * 8)))   # хубаво сготвено = по-голям бакшиш (до +4)
        п.пари += бакшиш
        п.качество = 0.6
        return цена, бакшиш

    def използвай(self, клиент):
        """E: гостът поръчва; персоналът приготвя, взима, сервира. Връща (успех, текст)."""
        аз = next((п for п in self.персони.values() if п.контролер == клиент), None)
        if аз is None:
            return False, ""
        if self.гост(аз):
            if аз.седи is None:
                return False, "Седни на маса (F) и поръчай с E"
            if аз.иска or аз.яде:
                return False, "Вече поръча: %s" % self.име_на(аз.иска or аз.яде)
            if not self._поръчай(аз):
                return False, "Кръчмата още няма тезгях, бъчва или печка"
            return True, "Поръча: %s" % self.име_на(аз.иска)
        if аз.роля not in self.меню["сервират"]:
            return False, ""
        return self._действие(аз)

    def _действие(self, п, ключ=None, гост_id=None, предмет=None):
        """Едно действие на персонала (играч с E или NPC): сервира, взима или приготвя."""
        if п.носи:
            гости = [(math.hypot(г.x - п.x, г.y - п.y), г.id, г) for г in self.персони.values()
                     if г.иска == п.носи and г.седи is not None and (гост_id is None or г.id == гост_id)]
            гости = [г for г in гости if г[0] <= poruchki.ДО_ГОСТ]
            if гости:
                г = min(гости)[2]
                име = self.име_на(п.носи)
                цена, бакшиш = self._сервирай(п, г)
                return True, "%s за %s: +%d в касата, бакшиш +%d" % (име, г.име, цена, бакшиш)
            return False, "Никой наблизо не иска %s" % self.име_на(п.носи).lower()
        близки = [(poruchki.до_станция(п.x, п.y, с[0], с[1]), с) for с in self.станции_списък
                  if ключ is None or (с[0], с[1]) == ключ]
        близки = [б for б in близки if б[0] <= poruchki.ДО_СТАНЦИЯ]
        if not близки:
            return False, "Иди до тезгяха, бъчвата, дъската или печката"
        # първо мебел с готово нещо, после свободна, после която и да е
        def ред(б):
            ст = self.станции.get((б[1][0], б[1][1]))
            return (0 if ст and ст["готово"] else 1 if not ст else 2, б[0])
        с = min(близки, key=ред)[1]
        к = (с[0], с[1])
        ст = self.станции.get(к)
        if ст and ст["готово"]:
            п.носи = ст["предмет"]
            п.качество = ст.get("качество", 0.6)
            del self.станции[к]
            return True, "Взе: %s" % self.име_на(п.носи)
        if ст:
            return False, "%s ще е готово след %d с" % (self.име_на(ст["предмет"]), math.ceil(ст["остава"]))
        може = [в[3] for в in self.станции_списък if (в[0], в[1]) == к]       # какво се прави на тази мебел
        мои = [в for в in може if п.роля in self.меню["предмети"][в]["кой"]]
        if предмет not in мои:
            търсени = [в for в in мои if self._търсено(в) > 0]               # първо това, което гостите чакат
            предмет = (търсени or мои or може)[0]
        данни = self.меню["предмети"][предмет]
        if п.роля not in данни["кой"]:
            return False, "%s го приготвя %s" % (данни["име"], " или ".join(данни["кой"]))
        self.станции[к] = {"предмет": предмет, "остава": float(данни["време"]), "готово": False, "кой": п.id,
                           "качество": 0.6}
        return True, "Приготвяш: %s" % данни["име"]

    def сготви(self, клиент, предмет, качество):
        """Ученик изигра мини играта при готвенето (gotvene.py): нещото е готово веднага,
        с качеството от играта. Връща (успех, текст)."""
        аз = next((п for п in self.персони.values() if п.контролер == клиент), None)
        данни = self.меню["предмети"].get(предмет)
        if аз is None or данни is None:
            return False, ""
        if аз.роля not in данни["кой"]:
            return False, "%s го приготвя %s" % (данни["име"], " или ".join(данни["кой"]))
        близки = [(poruchki.до_станция(аз.x, аз.y, с[0], с[1]), (с[0], с[1])) for с in self.станции_списък
                  if с[3] == предмет and (с[0], с[1]) not in self.станции]
        близки = [б for б in близки if б[0] <= poruchki.ДО_СТАНЦИЯ]
        if not близки:
            return False, "Някой друг вече ползва мястото"
        качество = max(0.0, min(1.0, float(качество)))
        self.станции[min(близки)[1]] = {"предмет": предмет, "остава": 0.0, "готово": True, "кой": аз.id,
                                         "качество": качество}
        звезди = 3 if качество >= 0.85 else 2 if качество >= 0.55 else 1 if качество > 0.2 else 0
        return True, "Готово: %s %s" % (данни["име"], "★" * звезди + "☆" * (3 - звезди))

    # ---------- NPC персонал ----------
    def _пред_станция(self, сx, сy, п):
        """Точка, в която NPC застава до мебелта (свободна съседна клетка, най-близо до него)."""
        клетки = [(сx, сy + 1), (сx, сy - 1), (сx - 1, сy), (сx + 1, сy)]
        клетки = [к for к in клетки if 0 <= к[0] < self.колони and 0 <= к[1] < self.редове
                  and self.карта["floor"][к[1]][к[0]] and к not in self.заети]
        if not клетки:
            return None
        return min((self.център(к) for к in клетки), key=lambda т: math.hypot(т[0] - п.x, т[1] - п.y))

    def _намери_път(self, п, точка):
        """Път по клетките (обикаля масите и тезгяха): търсене в ширина от клетката на NPC
        до свободната клетка, най-близо до точката. Връща списък от точки."""
        от = (int(п.x // ПЛОЧКА), int((п.y - 1) // ПЛОЧКА))
        if not (0 <= от[0] < self.колони and 0 <= от[1] < self.редове):
            return []
        мин_к = (int(точка[0] // ПЛОЧКА), int((точка[1] - 1) // ПЛОЧКА))
        откъде = {от: None}
        опашка = [от]
        for к in опашка:
            for дx, дy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                н = (к[0] + дx, к[1] + дy)
                if (н not in откъде and 0 <= н[0] < self.колони and 0 <= н[1] < self.редове
                        and self.карта["floor"][н[1]][н[0]] and н not in self.заети):
                    откъде[н] = к
                    опашка.append(н)
        най = min(откъде, key=lambda к: (abs(к[0] - мин_к[0]) + abs(к[1] - мин_к[1]), к))
        път = []
        while най is not None and най != от:
            път.append(self.център(най))
            най = откъде[най]
        път.reverse()
        return път

    @staticmethod
    def _пред_гост(г):
        отм = {"down": (0, -80), "up": (0, 80), "right": (-80, 0), "left": (80, 0)}.get(г.посока, (0, 80))
        return г.x + отм[0], г.y + отм[1]

    def _заети_цели(self, п, вид):
        return {д.задача[1] for д in self.персони.values() if д is not п and д.задача and д.задача[0] == вид}

    def _избери_задача(self, п):
        if п.носи:
            заети = self._заети_цели(п, "сервирай")
            гости = [(math.hypot(г.x - п.x, г.y - п.y), г.id) for г in self.персони.values()
                     if г.иска == п.носи and г.седи is not None and г.id not in заети]
            if гости:
                return ("сервирай", min(гости)[1])
            п.носи = None                        # никой вече не го иска (изпиха го в кухнята :)
            return None
        def вземи():
            заети = self._заети_цели(п, "вземи")
            кандидати = []
            for к, ст in self.станции.items():
                if ст["готово"] and к not in заети:
                    чакат = sum(1 for г in self.персони.values() if г.иска == ст["предмет"] and г.седи is not None)
                    носят = sum(1 for д in self.персони.values() if д.носи == ст["предмет"])
                    if чакат - носят > 0:
                        кандидати.append((math.hypot(к[0] * ПЛОЧКА - п.x, к[1] * ПЛОЧКА - п.y), к))
            return ("вземи", min(кандидати)[1]) if кандидати else None
        def готви():
            заети = self._заети_цели(п, "готви")
            кандидати = []
            for (x, y, _, предмет) in self.станции_списък:
                if (x, y) in self.станции or (x, y) in заети:
                    continue
                if п.роля not in self.меню["предмети"][предмет]["кой"]:
                    continue
                други = sum(1 for д in self.персони.values() if д is not п and д.задача and д.задача[0] == "готви"
                            and д.задача[2] == предмет)
                if self._търсено(предмет) - други > 0:
                    кандидати.append((math.hypot(x * ПЛОЧКА - п.x, y * ПЛОЧКА - п.y), (x, y), предмет))
            if not кандидати:
                return None
            най = min(кандидати)
            return ("готви", най[1], най[2])
        ред = (вземи, готви) if п.роля == "сервитьор" else (готви, вземи)
        for избор in ред:
            з = избор()
            if з:
                return з
        return None

    def _npc_работа(self, п, време):
        """NPC кръчмар, готвач и сервитьор вършат работата сами. Връща False, ако няма работа."""
        if п.задача is None:
            if п.почивка > 0 and not п.носи:
                return False
            п.задача = self._избери_задача(п)
            if п.задача is None:
                return False
        вид, цел = п.задача[0], п.задача[1]
        if п.седи is not None:
            self.стани(п)
        п.цел, п.към_място = None, None
        # целта още ли е валидна?
        if вид == "сервирай":
            г = self.персони.get(цел)
            if not г or г.иска != п.носи or г.седи is None:
                п.задача = None
                return True
            точка, близо = self._пред_гост(г), (lambda: math.hypot(г.x - п.x, г.y - п.y) <= poruchki.ДО_ГОСТ - 10)
        else:
            ст = self.станции.get(цел)
            if (вид == "вземи" and not (ст and ст["готово"])) or (вид == "готви" and ст):
                п.задача = None
                return True
            точка = self._пред_станция(цел[0], цел[1], п)
            if точка is None:
                п.задача = None
                return False
            близо = lambda: poruchki.до_станция(п.x, п.y, цел[0], цел[1]) <= poruchki.ДО_СТАНЦИЯ - 6
        if близо():
            п.върви = False
            self._действие(п, ключ=цел if вид != "сервирай" else None, гост_id=цел if вид == "сервирай" else None,
                           предмет=п.задача[2] if вид == "готви" else None)
            п.задача, п.заседнал, п.почивка = None, 0.0, 0.4
            п.път, п.път_до = [], None
            return True
        if п.път_до is None or math.hypot(п.път_до[0] - точка[0], п.път_до[1] - точка[1]) > 24:
            п.път, п.път_до = self._намери_път(п, точка), точка   # нова цел: нов път
        while п.път and math.hypot(п.път[0][0] - п.x, п.път[0][1] - п.y) < 4:
            п.път.pop(0)
        if п.път:
            точка = п.път[0]
        dx, dy = точка[0] - п.x, точка[1] - п.y
        разстояние = math.hypot(dx, dy)
        if разстояние < 3:                      # стигна точката: още малко към мебелта / госта
            if вид == "сервирай":
                dx, dy = г.x - п.x, г.y - п.y
            else:
                dx, dy = цел[0] * ПЛОЧКА + 32 - п.x, цел[1] * ПЛОЧКА + 32 - п.y
            разстояние = max(math.hypot(dx, dy), 1e-3)
        преди = (п.x, п.y)
        скорост = min(СКОРОСТ_РАБОТА, разстояние / max(време, 1e-3))   # не прескача целта
        п.мръдни(dx / разстояние, dy / разстояние, self.препятствия, време, скорост)
        if math.hypot(п.x - преди[0], п.y - преди[1]) < скорост * време * 0.3:
            п.заседнал += време
            if п.заседнал > 1.2:                # опря някъде: пробва отстрани, после търси нов път
                п.път_до = None
                п.мръдни(-dy / разстояние, dx / разстояние, self.препятствия, 0.25, СКОРОСТ_РАБОТА)
                if п.заседнал > 3.0:
                    п.задача, п.заседнал, п.почивка = None, 0.0, 1.0
        else:
            п.заседнал = 0.0
        return True

    # ---------- поръчка на песен (собственикът казва на NPC музиканта да свири) ----------
    def _песни(self):
        """Песните, които NPC музикантът може да свири: [(файл, име, дължина)].
        Първо тези с истински запис (assets/music/<песен>.ogg), за да се чуват."""
        всички = []
        for път in sorted(glob.glob(os.path.join(ПАПКА_ПЕСНИ, "*.json"))):
            try:
                with open(път, encoding="utf-8") as f:
                    д = json.load(f)
            except (OSError, ValueError):
                continue
            файл = os.path.splitext(os.path.basename(път))[0]
            всички.append((файл, д.get("name", файл), float(д.get("length_s", 120)),
                           os.path.exists(os.path.join(ПАПКА_МУЗИКА, файл + ".ogg"))))
        със_запис = [п[:3] for п in всички if п[3]]
        return със_запис or [п[:3] for п in всички]

    def спри_песен(self, м):
        if м.песен:
            м.песен, м.свири, м.настроение = None, False, 0.0
            м.песен_време = м.песен_дължина = м.до_хоро = 0.0
            м.почивка = 2.0

    def поръчай_песен(self, клиент):
        """E до музиканта: собственикът му казва да свири (или да спре). Връща (успех, текст)."""
        аз = next((п for п in self.персони.values() if п.контролер == клиент), None)
        if аз is None or аз.роля not in ПОРЪЧВАТ_МУЗИКА:
            return False, "Само собственикът може да поръчва музика"
        близки = [(math.hypot(п.x - аз.x, п.y - аз.y), п.id, п) for п in self.персони.values()
                  if п.роля == "музикант" and п is not аз]
        близки = [б for б in близки if б[0] <= ДО_МУЗИКАНТА]
        if not близки:
            return False, "Иди по-близо до музиканта"
        м = min(близки)[2]
        if м.контролер is not None:
            return False, "%s го управлява играч - кажи му сам" % м.име
        if м.песен:
            self.спри_песен(м)
            return True, "%s спря да свири" % м.име
        песни = self._песни()
        if not песни:
            return False, "Няма песни в data/songs"
        файл, име, дължина = self.случаен.choice(песни)
        if м.седи is not None:
            self.стани(м)
        м.цел, м.към_място, м.върви, м.посока = None, None, False, "down"
        м.свири, м.настроение = True, НАСТРОЕНИЕ_NPC
        м.песен, м.песен_време, м.песен_дължина, м.до_хоро = файл, 0.0, дължина, ХОРО_СЛЕД
        return True, "%s засвири „%s“" % (м.име, име)

    def _npc_свири(self, м, време):
        """NPC музикантът свири поръчаната песен, докато свърши."""
        м.върви = False
        м.песен_време += време
        м.до_хоро = max(0.0, м.до_хоро - време)
        if м.песен_време >= м.песен_дължина:
            self.спри_песен(м)

    def _хорa(self, време):
        """Кой NPC на кое хоро играе: {id на играч: (музикант, място, брой)}."""
        музиканти = [п for п in self.персони.values() if п.свири and п.настроение >= НАСТРОЕНИЕ_ЗА_ХОРО
                     and п.до_хоро <= 0]          # поръчана песен: хорото тръгва след малко
        хора = {}
        for м in музиканти:
            м.фаза_хоро += време * (0.25 + 0.6 * м.настроение)     # хорото се върти по-бързо, когато свири добре
            играчи = sorted(п.id for п in self.персони.values()
                            if п.контролер is None and п is not м and not п.свири
                            and not п.иска and not п.яде and not п.носи and not п.задача
                            and math.hypot(п.x - м.x, п.y - м.y) < РАДИУС_ХОРО
                            and п.id not in хора)
            for място, пид in enumerate(играчи):
                хора[пид] = (м, място, len(играчи))
        return хора

    def _хоро(self, п, м, място, брой, време):
        if п.седи is not None:
            self.стани(п)                       # музиката тръгна: става и отива на хорото
        R = min(150.0, 44.0 + 12.0 * брой)                    # повече хора = по-голям кръг (стегнат, да се хванат)
        ъгъл = м.фаза_хоро + 2 * math.pi * място / брой
        цx = м.x + R * math.cos(ъгъл)
        цy = м.y + R * 0.62 * math.sin(ъгъл)                   # кръгът е сплеснат (гледаме отгоре под ъгъл)
        dx, dy = цx - п.x, цy - п.y
        разстояние = math.hypot(dx, dy)
        п.хоро = round(м.настроение, 2)
        п.цел = None
        п.почивка = 0.0
        if разстояние < 3:
            п.върви = False
            return
        скорост = min(СКОРОСТ_NPC * СКОРОСТ_ХОРО, разстояние / max(време, 1e-3))
        п.мръдни(dx / разстояние, dy / разстояние, self.препятствия, време, скорост)

    # ---------- един тик ----------
    def обнови(self, време):
        хора = self._хорa(време)
        for ст in self.станции.values():        # храната и пиенето се приготвят сами
            if not ст["готово"]:
                ст["остава"] -= време
                if ст["остава"] <= 0:
                    ст["готово"], ст["остава"] = True, 0.0
        for п in self.персони.values():
            п.ядосан = max(0.0, п.ядосан - време)
            if п.седи is not None and self.гост(п) and self._гост_седи(п, време):
                continue                        # гостът чака поръчката си / яде
            if п.контролер is None and п.роля in РАБОТЯТ_NPC and п.id not in хора and self._npc_работа(п, време):
                continue
            if п.контролер is None and п.песен:
                self._npc_свири(п, време)
            elif п.контролер is None and п.id in хора:
                self._хоро(п, *хора[п.id], време)
            elif п.контролер is None:
                if п.хоро:                       # музиката спря: хорото се разваля
                    п.хоро, п.цел, п.почивка = 0.0, None, 1.0
                self._npc(п, време)
            elif п.свири:
                п.върви = False                 # докато свири, стои на място
            elif п.седи is not None:
                if abs(п.dx) > 0.01 or abs(п.dy) > 0.01:
                    self.стани(п)               # тръгне ли, става
                    п.мръдни(п.dx, п.dy, self.препятствия, време, СКОРОСТ)
                else:
                    п.върви = False
            else:
                п.мръдни(п.dx, п.dy, self.препятствия, време, СКОРОСТ)
        self._натрупано += време
        while self._натрупано >= СЕКУНДИ_ЗА_МИНУТА:
            self._натрупано -= СЕКУНДИ_ЗА_МИНУТА
            self.минути += 1
            for п in self.персони.values():
                загуба = ЕНЕРГИЯ_НА_МИНУТА + (ЕНЕРГИЯ_ХОДЕНЕ if п.върви else 0)
                п.енергия = max(0.0, п.енергия - загуба)
            if self.минути >= 24 * 60:
                self.минути -= 24 * 60
                self.ден += 1

    def _npc(self, п, време):
        """Засега NPC се разхождат и понякога сядат (задачите идват в Етап 4)."""
        if п.седи is not None:                 # седи: почива си, после става
            п.почивка -= време
            п.върви = False
            if п.почивка <= 0:
                self.стани(п)
                п.почивка = self.случаен.uniform(NPC_ПОЧИВКА_ОТ, NPC_ПОЧИВКА_ДО)
            return
        if п.почивка > 0:
            п.почивка -= време
            п.върви = False
            return
        if п.цел is None:
            свободни = [и for и in range(len(self.места)) if not self.заето(и)
                        and not any(д.към_място == и for д in self.персони.values())]
            шанс = NPC_СЯДА_ГОСТ if self.гост(п) else 0.0   # сядат само гостите; персоналът не сяда
            if свободни and self.случаен.random() < шанс:
                п.към_място = self.случаен.choice(свободни)
                м = self.места[п.към_място]
                п.цел = (м["x"], м["y"])
            else:
                п.към_място = None
                п.цел = self.център(self.случайна_клетка())
        цx, цy = п.цел
        dx, dy = цx - п.x, цy - п.y
        разстояние = math.hypot(dx, dy)
        if разстояние < 6 or (п.към_място is not None and разстояние < 30):
            п.цел = None
            п.върви = False
            if п.към_място is not None and not self.заето(п.към_място):
                self.седни(п, п.към_място)
                п.почивка = self.случаен.uniform(NPC_СЕДИ_ОТ, NPC_СЕДИ_ДО)
                return
            п.към_място = None
            п.почивка = self.случаен.uniform(NPC_ПОЧИВКА_ОТ, NPC_ПОЧИВКА_ДО)
            return
        преди = (п.x, п.y)
        п.мръдни(dx / разстояние, dy / разстояние, self.препятствия, време, СКОРОСТ_NPC)
        if math.hypot(п.x - преди[0], п.y - преди[1]) < СКОРОСТ_NPC * време * 0.3:
            п.заседнал += време
            if п.заседнал > 0.6:                # опря в маса: избира друго място
                if п.към_място is not None and разстояние < 70 and not self.заето(п.към_място):
                    self.седни(п, п.към_място)   # стига до стола покрай масата
                    п.почивка = self.случаен.uniform(NPC_СЕДИ_ОТ, NPC_СЕДИ_ДО)
                п.цел, п.заседнал, п.към_място = None, 0.0, None
        else:
            п.заседнал = 0.0

    # ---------- за мрежата ----------
    def описания(self):
        return [п.описание() for п in self.персони.values()]

    def състояние(self):
        станции = []
        for (x, y), ст in self.станции.items():
            време = float(self.меню["предмети"].get(ст["предмет"], {}).get("време", 1)) or 1.0
            станции.append({"x": x, "y": y, "item": ст["предмет"], "ready": ст["готово"],
                            "p": round(1.0 - ст["остава"] / време, 2)})
        return {"day": self.ден, "minutes": self.минути, "stations": станции,
                "persons": [п.състояние() for п in self.персони.values()]}

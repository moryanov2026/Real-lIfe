    def _нов_отчет(self):
        return {"продажби": {}, "приходи": 0, "бакшиши": 0, "продукти": 0, "обслужени": 0, "ядосани": 0}

    def собственик(self):
        return next((с for с in self.персони.values() if с.роля == "собственик"), None)

    def _мебели(self, имена):
        if isinstance(имена, str):
            имена = [имена]
        return [(о["x"], о["y"]) for о in self.карта["objects"] if о["name"] in имена]

    def _до_мебел(self, п, имена, разстояние=None):
        """Най-близката мебел от тези имена, ако е до персоната: (x, y) или None."""
        разстояние = разстояние or self.склад_данни.get("до_мебел", 80)
        if п.карта != "krachma":
            return None
        близки = [(poruchki.до_станция(п.x, п.y, x, y), (x, y)) for (x, y) in self._мебели(имена)]
        близки = [б for б in близки if б[0] <= разстояние]
        return min(близки)[1] if близки else None

    def липсват(self, предмет):
        """Защо не може да се сготви: списък с имена на липсващите продукти (+ чиниите)."""
        липса = [self.склад_данни["продукти"][к]["име"] for к in sklad.липсват(предмет, self.склад_данни, self.рецепти, self.склад)]
        if предмет in self.склад_данни.get("с_чиния", []) and self.чисти_чинии < 1:
            липса.append("чисти чинии")
        return липса

    def _похарчи(self, предмет):
        """Взима продуктите (и чиния) за едно ястие. Връща текст с причината, ако не може."""
        липса = self.липсват(предмет)
        if липса:
            return "Няма %s - %s" % (", ".join(липса).lower(),
                                     "чистачът да измие" if липса == ["чисти чинии"] else "снабдителят да донесе")
        for к in sklad.нужни(предмет, self.склад_данни, self.рецепти):
            self.склад[к] -= 1
        if предмет in self.склад_данни.get("с_чиния", []):
            self.чисти_чинии -= 1
        return None

    def _мръсно(self, място):
        return any(ч["място"] == място for ч in self.мръсни)

    def за_пазар(self):
        """Какво трябва да купи снабдителят: продуктите на кръчмата, които са под прага."""
        if not hasattr(self, "_нужни_кръчма"):
            self._нужни_кръчма = set()
            for к in self.меню["предмети"]:
                self._нужни_кръчма.update(sklad.нужни(к, self.склад_данни, self.рецепти))
        return [к for к in sklad.за_пазар(self.склад_данни, self.склад) if к in self._нужни_кръчма]

    def пазарувай(self, п):
        """Снабдителят на вратата: купува всичко, което е под прага; плаща собственикът."""
        if п.товар:
            return False, "Вече носиш щайга - занеси я в склада"
        списък = {к: self.настройки["пакети"].get(к, 1) for к in self.за_пазар()}
        if not списък:
            return False, "В склада има от всичко"
        с = self.собственик()
        каса = с.пари if с else 0
        купено, харч, няма = {}, 0, []
        for к, брой in sorted(списък.items(), key=lambda т: self.склад.get(т[0], 0)):   # първо празните
            порции = брой * self.склад_данни["продукти"][к]["пакет"]
            if к in getattr(self, "пазар_стока", {}):  # местно: колкото има на пазара, по цената днес
                цена = int(math.ceil(min(порции, int(self.пазар_стока[к])) * self.цена_единица(к)))
                if харч + цена > каса:
                    continue
                порции, цена = self.купи_от_пазара(к, порции)
                if not порции:
                    няма.append(self.склад_данни["продукти"][к]["име"].lower())
                    continue
            else:
                цена = self.склад_данни["продукти"][к]["цена"] * брой
                if харч + цена > каса:
                    continue
            купено[к] = порции
            харч += цена
        if not купено:
            return False, ("На пазара няма: %s" % ", ".join(няма)) if няма else "Собственикът няма пари за продукти"
        if с:
            с.пари -= харч
        self.днес["продукти"] += харч
        п.товар, п.носи = купено, "shtayga"
        имена = ", ".join(self.склад_данни["продукти"][к]["име"].lower() for к in купено)
        return True, "Купи: %s (-%d от касата)" % (имена, харч)

    def разтовари(self, п):
        for к, брой in п.товар.items():
            self.склад[к] = self.склад.get(к, 0) + брой            # в щайгата са порции
        брой = len(п.товар)
        п.товар, п.носи = {}, None
        return True, "Сложи в склада %d вида продукти" % брой

    def _вземи_чиния(self, п):
        if п.карта != "krachma":
            return False, ""
        близки = [(math.hypot(ч["x"] - п.x, ч["y"] - п.y), и) for и, ч in enumerate(self.мръсни)]
        близки = [б for б in близки if б[0] <= poruchki.ДО_ГОСТ]
        if not близки:
            return False, ""
        if п.чинии >= self.склад_данни.get("носи_чинии", 4):
            return False, "Ръцете ти са пълни - занеси чиниите на мивката"
        self.мръсни.pop(min(близки)[1])
        п.чинии += 1
        п.носи = "chiniya_mrasna"
        return True, "Взе мръсна чиния (носиш %d)" % п.чинии

    def измий(self, клиент, качество=0.6):
        """Чистачът изигра мини играта на мивката (или NPC изми): чиниите стават чисти."""
        аз = next((п for п in self.персони.values() if п.контролер == клиент), None) if клиент is not None else None
        if аз is None:
            return False, ""
        if not аз.чинии:
            return False, "Нямаш мръсни чинии"
        if not self._до_мебел(аз, self.склад_данни.get("мивка", "sink")):
            return False, "Иди до мивката"
        брой = аз.чинии
        self.чисти_чинии += брой
        аз.чинии, аз.носи = 0, None
        качество = max(0.0, min(1.0, float(качество)))
        звезди = 3 if качество >= 0.85 else 2 if качество >= 0.55 else 1 if качество > 0.2 else 0
        return True, "Изми %d чинии %s" % (брой, "★" * звезди + "☆" * (3 - звезди))

    def _помощник_действие(self, аз):
        """E за снабдителя и чистача (и собственика). None = нищо от тези (продължи с поръчките)."""
        if аз.товар:
            if self._до_мебел(аз, self.склад_данни.get("склад", ["shelf"])):
                return self.разтовари(аз)
            return False, "Занеси щайгата в склада (рафта)"
        if аз.роля in ЧИСТЯТ and not (аз.носи and аз.носи != "chiniya_mrasna"):
            успех, текст = self._вземи_чиния(аз)
            if текст:
                return успех, текст
            if аз.чинии and not self._до_мебел(аз, self.склад_данни.get("мивка", "sink")):
                return False, "Занеси чиниите на мивката"
        if аз.роля in ПАЗАРУВАТ and not аз.носи and (self.до_пазара(аз) or (not self.село and self._до_мебел(аз, "door"))):
            return self.пазарувай(аз)
        if аз.роля not in self.меню["сервират"]:
            if аз.роля == "снабдител":
                return False, ("Пазарът е в селото - излез през вратата" if self.село and аз.карта == "krachma"
                               else "Иди до сергиите на пазара" if аз.карта == "selo" else "Иди до вратата (пазара) или до склада")
            if аз.роля == "чистач":
                return False, "Иди до мръсна чиния или до мивката"
        return None

    def _край_на_деня(self):
        """Кръчмата затваря: собственикът плаща заплатите, пишем отчета, започва нов ден."""
        с = self.собственик()
        заплати, неплатени = {}, []
        for п in self.персони.values():
            сума = self.настройки["заплати"].get(п.роля)
            if not сума or п is с or п.уволнен:
                continue
            if с and с.пари >= сума:
                с.пари -= сума
                п.пари += сума
                заплати[п.име + " (" + п.роля + ")"] = сума
            else:
                неплатени.append(п.име)
        д = self.днес
        отчет = dict(д)
        отчет.update({"ден": self.ден, "заплати": заплати, "неплатени": неплатени, "репутация": round(self.репутация, 1),
                      "заплати_общо": sum(заплати.values()),
                      "печалба": д["приходи"] - д["продукти"] - sum(заплати.values()),
                      "каса": с.пари if с else 0})
        if self.село:
            отчет["магазин"] = self._магазин_нощ()
        self.последен_отчет, self.нов_отчет = отчет, True
        if self.село and self.гощавка:
            self._край_гощавка(False)
        if self.село:
            self.обред = None
        self.днес = self._нов_отчет()
        self.ден += 1
        self.минути = self.склад_данни.get("отваря", НАЧАЛЕН_ЧАС)
        if self.село:                               # новата сутрин: времето, пазарът, празникът
            self._ферма_нощ()
            празник = self.празник()
            отчет["утре"] = {"сезон": self.сезон(), "време": self.време_днес}
            if празник:
                отчет["утре"]["празник"] = празник.get("име", "")
            self._празник_сутрин()
        for п in self.персони.values():             # гостите си тръгват, кухнята се разчиства
            п.иска, п.яде, п.ядосан = None, None, 0.0
            if п.седи is not None and п.контролер is None:
                self.стани(п)
            if п.контролер is None and self.гост(п) and not п.вкъщи:
                self._прибери(п)
        self.станции = {}
        self.нощ = 4.0                              # всички спят: клиентите показват нощта
        for п in self.персони.values():             # нощем всеки спи: енергията се връща
            п.енергия = float(МАКС_ЕНЕРГИЯ)
            if п.контролер is None and not п.вкъщи and п.карта == "selo" and п.роля in РАБОТЯТ_NPC + ПОМАГАТ_NPC:
                self._прехвърли(п, "krachma")       # персоналът е на работа сутринта
        for п in self.персони.values():             # недоядената храна се прибира, чиниите отиват за миене
            if п.носи in self.склад_данни.get("с_чиния", []):
                п.носи = None
        всички = self.склад_данни.get("чинии", 8)
        self.чисти_чинии = max(0, всички - len(self.мръсни) - sum(п.чинии for п in self.персони.values()))


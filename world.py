    def зареди_запис(self, път):
        if not os.path.exists(път):
            return False
        try:
            with open(път, encoding="utf-8") as f:
                д = json.load(f)
        except (OSError, ValueError):
            return False
        self.ден, self.минути = д.get("ден", 1), д.get("минути", НАЧАЛЕН_ЧАС)
        try:
            self.начална_дата = datetime.date.fromisoformat(д.get("начална_дата", ""))
        except ValueError:
            self.начална_дата = datetime.date.today() - datetime.timedelta(days=self.ден - 1)
        for к, брой in д.get("склад", {}).items():
            if к in self.склад:
                self.склад[к] = брой
        self.чисти_чинии = д.get("чисти_чинии", self.чисти_чинии)
        self.мръсни = [ч for ч in д.get("мръсни", []) if ч.get("място", 0) < len(self.места)]
        self.днес = д.get("днес") or self._нов_отчет()
        self.последен_отчет = д.get("последен_отчет")
        for к, в in д.get("настройки", {}).items():
            if к in self.настройки and isinstance(в, type(self.настройки[к])):
                if isinstance(в, dict):
                    self.настройки[к].update({кк: вв for кк, вв in в.items() if кк in self.настройки[к]})
                else:
                    self.настройки[к] = list(в)
        self.репутация = д.get("репутация", self.репутация)
        ф = д.get("ферма", {})
        for x, y, н in ф.get("ниви", []):
            if (x, y) in self.ниви:
                self.ниви[(x, y)] = н
        self.яйца, self.доено = ф.get("яйца", self.яйца), ф.get("доено", self.доено)
        self.пазар_стока.update({к: в for к, в in ф.get("пазар", {}).items() if к in self.пазар_стока})
        self.време_днес = ф.get("време", self.време_днес)
        м = д.get("магазин", {})
        self.маг_стока.update({к: в for к, в in м.get("стока", {}).items() if к in self.маг_стока})
        self.маг_каса = м.get("каса", self.маг_каса)
        ц = д.get("църква", {})
        self.гощавка, self.обред = ц.get("гощавка"), ц.get("обред")
        self.свещи_ден = ц.get("свещи_ден", 0)
        self.мнения = д.get("мнения", [])
        for пид, гд in д.get("гости", {}).items():
            if пид in self.персони:
                self.персони[пид].нужди.update(гд.get("нужди", {}))
                self.персони[пид].сърдит_до = гд.get("сърдит_до", 0)
        for пид in self.настройки["уволнени"]:
            if пид in self.персони:
                self.персони[пид].уволнен = True
                self._прибери(self.персони[пид])
        ш, в = self.колони * ПЛОЧКА, self.редове * ПЛОЧКА
        for пид, пд in д.get("персони", {}).items():
            п = self.персони.get(пид)
            if not п:
                continue
            п.пари = пд.get("пари", п.пари)
            п.енергия = пд.get("енергия", п.енергия)
            x, y = пд.get("x", п.x), пд.get("y", п.y)
            if п.вкъщи:
                continue
            карта = пд.get("карта", "krachma") if self.село else "krachma"
            кр, _, преп = self._на_карта(карта)
            ш, в = кр["width"] * ПЛОЧКА, кр["height"] * ПЛОЧКА
            if 0 < x < ш and 0 < y < в and not any(п.кутия(x, y).colliderect(о) for о in преп):
                п.карта = карта
                п.x, п.y = x, y
        return True

    # ---------- NPC чистач и снабдител ----------
    def _върви(self, п, точка, време):
        """Една стъпка към точката по пътя около масите. True = стигна."""
        if п.седи is not None:
            self.стани(п)
        п.цел, п.към_място = None, None
        if п.път_до is None or math.hypot(п.път_до[0] - точка[0], п.път_до[1] - точка[1]) > 24:
            п.път, п.път_до = self._намери_път(п, точка), точка
        while п.път and math.hypot(п.път[0][0] - п.x, п.път[0][1] - п.y) < 4:
            п.път.pop(0)
        цел = п.път[0] if п.път else точка
        dx, dy = цел[0] - п.x, цел[1] - п.y
        разстояние = math.hypot(dx, dy)
        if разстояние < 4 and not п.път:
            п.върви = False
            return True
        if разстояние < 1e-3:
            return False
        преди = (п.x, п.y)
        скорост = min(СКОРОСТ_РАБОТА * (self._усърдие(п) if not self.гост(п) else 0.8), разстояние / max(време, 1e-3))
        п.мръдни(dx / разстояние, dy / разстояние, self._преп(п), време, скорост)
        if math.hypot(п.x - преди[0], п.y - преди[1]) < скорост * време * 0.3:
            п.заседнал += време
            if п.заседнал > 1.2:
                п.път_до = None
                п.мръдни(-dy / разстояние, dx / разстояние, self._преп(п), 0.25, СКОРОСТ_РАБОТА)
            if п.заседнал > 4.0:                    # не може да стигне: стига му толкова близо
                п.заседнал = 0.0
                return True
        else:
            п.заседнал = 0.0
        return False

    def _към_мебел(self, п, мебел, време):
        точка = self._пред_станция(мебел[0], мебел[1], п)
        if точка is None:
            return True
        близо = poruchki.до_станция(п.x, п.y, мебел[0], мебел[1]) <= self.склад_данни.get("до_мебел", 80) - 6
        return близо or self._върви(п, точка, време)

    def _npc_помощник(self, п, време):
        """NPC чистачът прибира и мие чиниите, NPC снабдителят пазарува. False = няма работа."""
        if п.роля == "чистач":
            if п.мие > 0:
                п.мие -= време
                п.върви = False
                if п.мие <= 0:
                    self.чисти_чинии += п.чинии
                    п.чинии, п.носи = 0, None
                return True
            заети = {д.задача[1] for д in self.персони.values() if д is not п and д.задача and д.задача[0] == "чиния"}
            if п.чинии < self.склад_данни.get("носи_чинии", 4) and self.мръсни:
                ч = min(self.мръсни, key=lambda ч: math.hypot(ч["x"] - п.x, ч["y"] - п.y))
                if math.hypot(ч["x"] - п.x, ч["y"] - п.y) <= poruchki.ДО_ГОСТ - 20:
                    self._вземи_чиния(п)
                    return True
                м = self.места[ч["място"]] if ч["място"] < len(self.места) else ч
                self._върви(п, (м["x"], м["y"]), време)
                return True
            мивки = self._мебели(self.склад_данни.get("мивка", "sink"))
            if п.чинии and мивки:
                мивка = min(мивки, key=lambda м: math.hypot(м[0] * ПЛОЧКА - п.x, м[1] * ПЛОЧКА - п.y))
                if self._към_мебел(п, мивка, време):
                    п.мие = self.склад_данни.get("мие_за", 2.5) * п.чинии
                return True
            return False
        if п.роля == "снабдител":
            if п.пазарува > 0:
                п.пазарува -= време
                п.върви = False
                if п.пазарува <= 0:
                    self.пазарувай(п)
                return True
            if п.товар:
                складове = self._мебели(self.склад_данни.get("склад", ["shelf"]))
                if not складове:
                    return False
                if п.карта != "krachma":
                    self._иди(п, "krachma", None, време)
                    return True
                с = min(складове, key=lambda м: math.hypot(м[0] * ПЛОЧКА - п.x, м[1] * ПЛОЧКА - п.y))
                if self._към_мебел(п, с, време):
                    self.разтовари(п)
                return True
            списък = self.за_пазар()
            собственик = self.собственик()
            if п.карта == "selo" and (not списък or not собственик):
                self._иди(п, "krachma", None, време)
                return True
            if not списък or not собственик or собственик.пари < min(
                    self.склад_данни["продукти"][к]["цена"] for к in списък):
                return False
            if self.село:                               # пазарът е в селото: през вратата до сергиите
                if п.карта == "selo" and self._пазар_точка(п) and self._иди(п, "selo", self._пазар_точка(п), време):
                    п.пазарува = self.склад_данни.get("пазаруване", 4)
                elif п.карта != "selo":
                    self._иди(п, "selo", None, време)
                return True
            врати = self._мебели("door")
            if not врати:
                return False
            врата = min(врати, key=lambda м: math.hypot(м[0] * ПЛОЧКА - п.x, м[1] * ПЛОЧКА - п.y))
            if poruchki.до_станция(п.x, п.y, врата[0], врата[1]) <= self.склад_данни.get("до_мебел", 80) - 6 \
                    or self._върви(п, self.център((врата[0], врата[1] - 1)), време):
                п.пазарува = self.склад_данни.get("пазаруване", 4)
            return True
        return False

    # ---------- NPC персонал ----------
    def _пред_станция(self, сx, сy, п):
        """Точка, в която NPC застава до мебелта (свободна съседна клетка, най-близо до него)."""
        клетки = [(сx, сy + 1), (сx, сy - 1), (сx - 1, сy), (сx + 1, сy)]
        клетки = [к for к in клетки if 0 <= к[0] < self.колони and 0 <= к[1] < self.редове
                  and self.карта["floor"][к[1]][к[0]] and к not in self.заети]
        if not клетки:
            return None
        return min((self.център(к) for к in клетки), key=lambda т: math.hypot(т[0] - п.x, т[1] - п.y))

    def _намери_път(self, п, точка):
        """Път по клетките (обикаля масите и тезгяха): търсене в ширина от клетката на NPC
        до свободната клетка, най-близо до точката. Връща списък от точки."""
        карта, заети, _ = self._на_карта(п.карта)
        колони, редове = карта["width"], карта["height"]
        от = (int(п.x // ПЛОЧКА), int((п.y - 1) // ПЛОЧКА))
        if not (0 <= от[0] < колони and 0 <= от[1] < редове):
            return []
        мин_к = (int(точка[0] // ПЛОЧКА), int((точка[1] - 1) // ПЛОЧКА))
        откъде = {от: None}
        опашка = [от]
        for к in опашка:
            for дx, дy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                н = (к[0] + дx, к[1] + дy)
                if (н not in откъде and 0 <= н[0] < колони and 0 <= н[1] < редове
                        and карта["floor"][н[1]][н[0]] and н not in заети):
                    откъде[н] = к
                    опашка.append(н)
        най = min(откъде, key=lambda к: (abs(к[0] - мин_к[0]) + abs(к[1] - мин_к[1]), к))
        път = []
        while най is not None and най != от:
            път.append(self.център(най))
            най = откъде[най]
        път.reverse()
        return път

    @staticmethod
    def _пред_гост(г):
        отм = {"down": (0, -80), "up": (0, 80), "right": (-80, 0), "left": (80, 0)}.get(г.посока, (0, 80))
        return г.x + отм[0], г.y + отм[1]

    def _заети_цели(self, п, вид):
        return {д.задача[1] for д in self.персони.values() if д is not п and д.задача and д.задача[0] == вид}

    def _избери_задача(self, п):
        if п.носи:
            заети = self._заети_цели(п, "сервирай")
            гости = [(math.hypot(г.x - п.x, г.y - п.y), г.id) for г in self.персони.values()
                     if г.иска == п.носи and г.седи is not None and г.id not in заети]
            if гости:
                return ("сервирай", min(гости)[1])
            if self.село and self.гощавка_трябва(п.носи) > 0:
                return ("гощавка", "трапеза")       # носи го на трапезата
            п.носи = None                        # никой вече не го иска (изпиха го в кухнята :)
            return None
        def вземи():
            заети = self._заети_цели(п, "вземи")
            кандидати = []
            for к, ст in self.станции.items():
                if ст["готово"] and к not in заети:
                    чакат = sum(1 for г in self.персони.values() if г.иска == ст["предмет"] and г.седи is not None)
                    чакат += max(0, self.гощавка_трябва(ст["предмет"])) if self.село else 0
                    носят = sum(1 for д in self.персони.values() if д.носи == ст["предмет"])
                    if чакат - носят > 0:
                        кандидати.append((math.hypot(к[0] * ПЛОЧКА - п.x, к[1] * ПЛОЧКА - п.y), к))
            return ("вземи", min(кандидати)[1]) if кандидати else None
        def готви():
            заети = self._заети_цели(п, "готви")
            кандидати = []
            for (x, y, _, предмет) in self.станции_списък:
                if (x, y) in self.станции or (x, y) in заети:
                    continue
                if п.роля not in self.меню["предмети"][предмет]["кой"]:
                    continue
                if self.липсват(предмет):
                    continue
                други = sum(1 for д in self.персони.values() if д is not п and д.задача and д.задача[0] == "готви"
                            and д.задача[2] == предмет)
                if self._търсено(предмет) - други > 0:
                    кандидати.append((math.hypot(x * ПЛОЧКА - п.x, y * ПЛОЧКА - п.y), (x, y), предмет))
            if not кандидати:
                return None
            най = min(кандидати)
            return ("готви", най[1], най[2])
        ред = (вземи, готви) if п.роля == "сервитьор" else (готви, вземи)
        for избор in ред:
            з = избор()
            if з:
                return з
        return None

    def _npc_работа(self, п, време):
        """NPC кръчмар, готвач и сервитьор вършат работата сами. Връща False, ако няма работа."""
        if п.задача is None:
            if п.почивка > 0 and not п.носи:
                return False
            п.задача = self._избери_задача(п)
            if п.задача is None:
                return False
        вид, цел = п.задача[0], п.задача[1]
        if п.седи is not None:
            self.стани(п)
        п.цел, п.към_място = None, None
        # целта още ли е валидна?
        if вид == "гощавка":
            маса = self.маса_гощавка()
            if not маса or self.гощавка_трябва(п.носи) <= 0:
                п.задача = None
                return True
            if self.до_трапезата(п):
                п.върви = False
                self.гощавка_дай(п)
                п.задача, п.заседнал, п.почивка = None, 0.0, 0.4
                п.път, п.път_до = [], None
                return True
            точка = self._пред_станция(маса[2], маса[3], п) or (маса[0], маса[1] + 80)
            if not self._върви(п, точка, време) or not self.до_трапезата(п):
                if п.заседнал > 3.5:
                    п.задача, п.заседнал = None, 0.0
            return True
        if вид == "сервирай":
            г = self.персони.get(цел)
            if not г or г.иска != п.носи or г.седи is None:
                п.задача = None
                return True
            точка, близо = self._пред_гост(г), (lambda: math.hypot(г.x - п.x, г.y - п.y) <= poruchki.ДО_ГОСТ - 10)
        else:
            ст = self.станции.get(цел)
            if (вид == "вземи" and not (ст and ст["готово"])) or (вид == "готви" and ст):
                п.задача = None
                return True
            точка = self._пред_станция(цел[0], цел[1], п)
            if точка is None:
                п.задача = None
                return False
            близо = lambda: poruchki.до_станция(п.x, п.y, цел[0], цел[1]) <= poruchki.ДО_СТАНЦИЯ - 6
        if близо():
            п.върви = False
            self._действие(п, ключ=цел if вид != "сервирай" else None, гост_id=цел if вид == "сервирай" else None,
                           предмет=п.задача[2] if вид == "готви" else None)
            п.задача, п.заседнал, п.почивка = None, 0.0, 0.4
            п.път, п.път_до = [], None
            return True
        if п.път_до is None or math.hypot(п.път_до[0] - точка[0], п.път_до[1] - точка[1]) > 24:
            п.път, п.път_до = self._намери_път(п, точка), точка   # нова цел: нов път
        while п.път and math.hypot(п.път[0][0] - п.x, п.път[0][1] - п.y) < 4:
            п.път.pop(0)
        if п.път:
            точка = п.път[0]
        dx, dy = точка[0] - п.x, точка[1] - п.y
        разстояние = math.hypot(dx, dy)
        if разстояние < 3:                      # стигна точката: още малко към мебелта / госта
            if вид == "сервирай":
                dx, dy = г.x - п.x, г.y - п.y
            else:
                dx, dy = цел[0] * ПЛОЧКА + 32 - п.x, цел[1] * ПЛОЧКА + 32 - п.y
            разстояние = max(math.hypot(dx, dy), 1e-3)
        преди = (п.x, п.y)
        скорост = min(СКОРОСТ_РАБОТА * self._усърдие(п), разстояние / max(време, 1e-3))   # не прескача целта
        п.мръдни(dx / разстояние, dy / разстояние, self._преп(п), време, скорост)
        if math.hypot(п.x - преди[0], п.y - преди[1]) < скорост * време * 0.3:
            п.заседнал += време
            if п.заседнал > 1.2:                # опря някъде: пробва отстрани, после търси нов път
                п.път_до = None
                п.мръдни(-dy / разстояние, dx / разстояние, self._преп(п), 0.25, СКОРОСТ_РАБОТА)
                if п.заседнал > 3.0:
                    п.задача, п.заседнал, п.почивка = None, 0.0, 1.0
        else:
            п.заседнал = 0.0
        return True

    # ---------- поръчка на песен (собственикът казва на NPC музиканта да свири) ----------
    def _песни(self):
        """Песните, които NPC музикантът може да свири: [(файл, име, дължина)].
        Първо тези с истински запис (assets/music/<песен>.ogg), за да се чуват."""
        всички = []
        for път in sorted(glob.glob(os.path.join(ПАПКА_ПЕСНИ, "*.json"))):
            try:
                with open(път, encoding="utf-8") as f:
                    д = json.load(f)
            except (OSError, ValueError):
                continue
            файл = os.path.splitext(os.path.basename(път))[0]
            всички.append((файл, д.get("name", файл), float(д.get("length_s", 120)),
                           os.path.exists(os.path.join(ПАПКА_МУЗИКА, файл + ".ogg"))))
        със_запис = [п[:3] for п in всички if п[3]]
        return със_запис or [п[:3] for п in всички]

    def спри_песен(self, м):
        if м.песен:
            м.песен, м.свири, м.настроение = None, False, 0.0
            м.песен_време = м.песен_дължина = м.до_хоро = 0.0
            м.почивка = 2.0

    def поръчай_песен(self, клиент):
        """E до музиканта: собственикът му казва да свири (или да спре). Връща (успех, текст)."""
        аз = next((п for п in self.персони.values() if п.контролер == клиент), None)
        if аз is None or аз.роля not in ПОРЪЧВАТ_МУЗИКА:
            return False, "Само собственикът може да поръчва музика"
        близки = [(math.hypot(п.x - аз.x, п.y - аз.y), п.id, п) for п in self.персони.values()
                  if п.роля == "музикант" and п is not аз]
        близки = [б for б in близки if б[0] <= ДО_МУЗИКАНТА]
        if not близки:
            return False, "Иди по-близо до музиканта"
        м = min(близки)[2]
        if м.контролер is not None:
            return False, "%s го управлява играч - кажи му сам" % м.име
        if м.песен:
            self.спри_песен(м)
            return True, "%s спря да свири" % м.име
        песни = self._песни()
        if not песни:
            return False, "Няма песни в data/songs"
        файл, име, дължина = self.случаен.choice(песни)
        if м.седи is not None:
            self.стани(м)
        м.цел, м.към_място, м.върви, м.посока = None, None, False, "down"
        м.свири, м.настроение = True, НАСТРОЕНИЕ_NPC
        м.песен, м.песен_време, м.песен_дължина, м.до_хоро = файл, 0.0, дължина, ХОРО_СЛЕД
        return True, "%s засвири „%s“" % (м.име, име)

    def _npc_свири(self, м, време):
        """NPC музикантът свири поръчаната песен, докато свърши."""
        м.върви = False
        м.песен_време += време
        м.до_хоро = max(0.0, м.до_хоро - време)
        if м.песен_време >= м.песен_дължина:
            self.спри_песен(м)

    def _хорa(self, време):
        """Кой NPC на кое хоро играе: {id на играч: (музикант, място, брой)}."""
        музиканти = [п for п in self.персони.values() if п.свири and п.настроение >= НАСТРОЕНИЕ_ЗА_ХОРО
                     and п.до_хоро <= 0]          # поръчана песен: хорото тръгва след малко
        хора = {}
        for м in музиканти:
            м.фаза_хоро += време * (0.25 + 0.6 * м.настроение)     # хорото се върти по-бързо, когато свири добре
            играчи = sorted(п.id for п in self.персони.values()
                            if п.контролер is None and п is not м and not п.свири
                            and not п.иска and not п.яде and not п.носи and not п.задача
                            and п.карта == м.карта and not п.вкъщи
                            and math.hypot(п.x - м.x, п.y - м.y) < РАДИУС_ХОРО
                            and п.id not in хора)
            for място, пид in enumerate(играчи):
                хора[пид] = (м, място, len(играчи))
        return хора

    def _хоро(self, п, м, място, брой, време):
        if п.седи is not None:
            self.стани(п)                       # музиката тръгна: става и отива на хорото
        R = min(150.0, 44.0 + 12.0 * брой)                    # повече хора = по-голям кръг (стегнат, да се хванат)
        ъгъл = м.фаза_хоро + 2 * math.pi * място / брой
        цx = м.x + R * math.cos(ъгъл)
        цy = м.y + R * 0.62 * math.sin(ъгъл)                   # кръгът е сплеснат (гледаме отгоре под ъгъл)
        dx, dy = цx - п.x, цy - п.y
        разстояние = math.hypot(dx, dy)
        п.хоро = round(м.настроение, 2)
        п.цел = None
        п.почивка = 0.0
        if разстояние < 3:
            п.върви = False
            return
        скорост = min(СКОРОСТ_NPC * СКОРОСТ_ХОРО, разстояние / max(време, 1e-3))
        п.мръдни(dx / разстояние, dy / разстояние, self._преп(п), време, скорост)

    # ---------- един тик ----------
    def обнови(self, време):
        хора = self._хорa(време)
        self.нощ = max(0.0, self.нощ - време)
        for ст in self.станции.values():        # храната и пиенето се приготвят сами
            if not ст["готово"]:
                ст["остава"] -= време
                if ст["остава"] <= 0:
                    ст["готово"], ст["остава"] = True, 0.0
        for п in self.персони.values():
            п.ядосан = max(0.0, п.ядосан - време)
            if п.мнение:
                п.мнение = (п.мнение[0], п.мнение[1] - време) if п.мнение[1] > време else None
            if п.вкъщи:
                if п.контролер is None and self.гост(п) and not п.уволнен:
                    self._гост_вкъщи(п, време)
                continue                        # вкъщи е (или уволнен): не е в кръчмата
            п.преход = max(0.0, п.преход - време)
            if п.контролер is None and self.гост(п) and п.отива and not п.тръгва:   # гост на път към кръчмата
                if self._иди(п, п.отива, None, време) or п.карта == п.отива:
                    п.отива = None
                continue
            if п.контролер is None and п.карта == "magazin" and self.гост(п):
                self._клиент_магазин(п, време)         # жител на опашката в магазина
                continue
            if п.контролер is None and п.роля == "селянин" and п.id not in хора:
                if not self._npc_селянин(п, време):
                    self._npc_навън(п, време)
                continue
            if п.контролер is None and п.роля in ("продавач", "касиер") and self._npc_магазин(п, време):
                continue
            if п.контролер is None and п.роля in ("свещеник", "звънар") and self._npc_църква(п, време):
                continue
            if п.контролер is None and п.карта == "selo" and not self.гост(п) and п.роля not in ПОМАГАТ_NPC:
                self._иди(п, "krachma", None, време)     # NPC от персонала, оставен навън: връща се на работа
                continue
            if п.контролер is None and self.гост(п) and п.седи is None:
                if п.тръгва or (not self.отворено() and not п.иска):
                    self._тръгни(п, време)
                    continue
                if п.остава > 0:
                    п.остава -= време
                    if п.остава <= 0:
                        п.тръгва = True
                elif п.цел is None and п.почивка <= 0:
                    п.без_място += време
                    if п.без_място > 30:         # няма къде да седне: отива си
                        self._мнение(п, 0.3, "Нямаше къде да седна.")
                        п.тръгва = True
                        continue
            if п.седи is not None and self.гост(п) and self._гост_седи(п, време):
                п.без_място = 0.0
                continue                        # гостът чака поръчката си / яде
            if п.контролер is None and п.роля in РАБОТЯТ_NPC and п.id not in хора and self._npc_работа(п, време):
                continue
            if п.контролер is None and п.роля in ПОМАГАТ_NPC and п.id not in хора and self._npc_помощник(п, време):
                continue
            if п.контролер is None and п.песен:
                self._npc_свири(п, време)
            elif п.контролер is None and п.id in хора:
                self._хоро(п, *хора[п.id], време)
            elif п.контролер is None:
                if п.хоро:                       # музиката спря: хорото се разваля
                    п.хоро, п.цел, п.почивка = 0.0, None, 1.0
                self._npc(п, време)
            elif п.свири:
                п.върви = False                 # докато свири, стои на място
            elif п.седи is not None:
                if abs(п.dx) > 0.01 or abs(п.dy) > 0.01:
                    self.стани(п)               # тръгне ли, става
                    п.мръдни(п.dx, п.dy, self._преп(п), време, СКОРОСТ)
                else:
                    п.върви = False
            else:
                п.мръдни(п.dx, п.dy, self._преп(п), време, СКОРОСТ)
                self._провери_врата(п)
        self._натрупано += време
        while self._натрупано >= СЕКУНДИ_ЗА_МИНУТА:
            self._натрупано -= СЕКУНДИ_ЗА_МИНУТА
            self.минути += 1
            if self.село:
                self._ферма_минута()
                self._църква_минута()
            for п in self.персони.values():
                if п.седи is not None and not п.яде:
                    п.енергия = min(float(МАКС_ЕНЕРГИЯ), п.енергия + ПОЧИВКА_НА_МИНУТА)   # седнал: почива
                    continue
                загуба = ЕНЕРГИЯ_НА_МИНУТА + (ЕНЕРГИЯ_ХОДЕНЕ if п.върви else 0)
                if п.роля in РАБОТЯТ_NPC + ПОМАГАТ_NPC + ("собственик",) and (п.задача or п.носи or п.върви):
                    загуба += ЕНЕРГИЯ_НА_МИНУТА           # работата уморява повече
                п.енергия = max(0.0, п.енергия - загуба)
            if self.минути >= self.склад_данни.get("затваря", 22 * 60):
                self._край_на_деня()
                break
            if self.минути >= 24 * 60:
                self.минути -= 24 * 60
                self.ден += 1

    def _npc_навън(self, п, време):
        """NPC в селото без работа: стои си (почивка)."""
        п.върви = False

    def _npc(self, п, време):
        """Засега NPC се разхождат и понякога сядат (задачите идват в Етап 4)."""
        if п.седи is not None:                 # седи: почива си, после става
            п.почивка -= време
            п.върви = False
            if п.почивка <= 0:
                self.стани(п)
                п.почивка = self.случаен.uniform(NPC_ПОЧИВКА_ОТ, NPC_ПОЧИВКА_ДО)
            return
        if п.почивка > 0:
            п.почивка -= време
            п.върви = False
            return
        if п.цел is None:
            свободни = [и for и in range(len(self.места)) if not self.заето(и) and not self._мръсно(и)
                        and not any(д.към_място == и for д in self.персони.values())]
            шанс = (1.0 if п.остава <= 0 else NPC_СЯДА_ГОСТ) if self.гост(п) else 0.0   # сядат само гостите
            if свободни and self.случаен.random() < шанс:
                п.към_място = self.случаен.choice(свободни)
                м = self.места[п.към_място]
                п.цел = (м["x"], м["y"])
            else:
                п.към_място = None
                п.цел = self.център(self.случайна_клетка())
        цx, цy = п.цел
        dx, dy = цx - п.x, цy - п.y
        разстояние = math.hypot(dx, dy)
        if разстояние < 6 or (п.към_място is not None and разстояние < 30):
            п.цел = None
            п.върви = False
            if п.към_място is not None and not self.заето(п.към_място):
                self.седни(п, п.към_място)
                п.почивка = self.случаен.uniform(NPC_СЕДИ_ОТ, NPC_СЕДИ_ДО)
                return
            п.към_място = None
            п.почивка = self.случаен.uniform(NPC_ПОЧИВКА_ОТ, NPC_ПОЧИВКА_ДО)
            return
        преди = (п.x, п.y)
        п.мръдни(dx / разстояние, dy / разстояние, self._преп(п), време, СКОРОСТ_NPC)
        if math.hypot(п.x - преди[0], п.y - преди[1]) < СКОРОСТ_NPC * време * 0.3:
            п.заседнал += време
            if п.заседнал > 0.6:                # опря в маса: избира друго място
                if п.към_място is not None and разстояние < 70 and not self.заето(п.към_място):
                    self.седни(п, п.към_място)   # стига до стола покрай масата
                    п.почивка = self.случаен.uniform(NPC_СЕДИ_ОТ, NPC_СЕДИ_ДО)
                п.цел, п.заседнал, п.към_място = None, 0.0, None
        else:
            п.заседнал = 0.0

    # ---------- за мрежата ----------
    def описания(self):
        return [п.описание() for п in self.персони.values()]

    def състояние(self):
        станции = []
        for (x, y), ст in self.станции.items():
            време = float(self.меню["предмети"].get(ст["предмет"], {}).get("време", 1)) or 1.0
            станции.append({"x": x, "y": y, "item": ст["предмет"], "ready": ст["готово"],
                            "p": round(1.0 - ст["остава"] / време, 2)})
        return {"day": self.ден, "minutes": self.минути, "stations": станции, "night": round(self.нощ, 1),
                "farm": self.ферма_за_клиента() if self.село else {},
                "shop": self.магазин_за_клиента() if self.магазин_карта else {},
                "church": self.църква_за_клиента() if self.село else {},
                "stock": self.склад, "plates": self.чисти_чинии,
                "manage": {"prices": self.настройки["цени"], "wages": self.настройки["заплати"],
                           "packs": self.настройки["пакети"], "fired": self.настройки["уволнени"],
                           "rep": round(self.репутация, 2), "opinions": self.мнения[-6:]},
                "dirty": [[ч["x"], ч["y"]] for ч in self.мръсни], "today": {к: в for к, в in self.днес.items() if к != "продажби"},
                "persons": [п.състояние() for п in self.персони.values()]}

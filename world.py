def зареди_каталог():
    """Мебелите за строене: {име на плочка: (име, цена, варианти)}."""
    if not os.path.exists(ПЪТ_КАТАЛОГ):
        return {}, {}
    with open(ПЪТ_КАТАЛОГ, encoding="utf-8") as f:
        д = json.load(f)
    цени = {}
    for раздел in д.get("раздели", []):
        for м in раздел["мебели"]:
            for в in м["варианти"]:
                цени[в] = (м["име"], м["цена"], м["варианти"])
    return цени, д.get("разширяване", {})

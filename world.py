    def _селски_врати(self):
        """[(x, y, към)] - вратите на сградите в селото (стар запис [x, y] = кръчмата)."""
        врати = []
        for в in self.село_инфо.get("врати", []):
            if isinstance(в, dict):
                врати.append((в["x"], в["y"], в.get("към", "krachma")))
            else:
                врати.append((в[0], в[1], "krachma"))
        return врати

    def _прехвърли(self, п, карта):
        """Минава през вратата: от сграда в селото или от селото в сграда."""
        от = п.карта
        if карта == "selo" and self.село:
            входове = self.село_инфо.get("входове", {})
            вход = входове.get(от) or self.село_инфо.get("вход") or self.село.get("start", [1, 1])
            п.x, п.y = self.център(tuple(вход))
            п.посока = "down"
        else:
            if (карта == "magazin" and not self.магазин_карта) or (карта == "tsarkva" and not self.църква_карта):
                карта = "krachma"
            врати = self._врати_на(карта)
            if врати:
                в = врати[len(врати) // 2 - 1 if len(врати) > 1 else 0]
                п.x, п.y = self.център((в[0], в[1] - 1))
            п.посока = "up"
        п.карта, п.преход = карта, ПРЕХОД_ПАУЗА
        п.път, п.път_до, п.цел, п.заседнал = [], None, None, 0.0

    def _провери_врата(self, п):
        """Играч стъпи на вратата: минава от другата страна."""
        if п.преход > 0 or not self.село:
            return
        клетка = (int(п.x // ПЛОЧКА), int((п.y - 1) // ПЛОЧКА))
        if п.карта != "selo":
            if клетка in self._врати_на(п.карта) and п.dy >= 0:
                self._прехвърли(п, "selo")
            return
        for (x, y, към) in self._селски_врати():
            if клетка == (x, y) and п.dy <= 0:
                self._прехвърли(п, към)
                return

    def _точка_врата(self, п, към="krachma"):
        """Точката, от която се минава: вратата на сградата отвътре или вратата на сградата "към" в селото."""
        if п.карта == "selo":
            врати = [в for в in self._селски_врати() if в[2] == към] or self._селски_врати()
            в = min(врати, key=lambda к: math.hypot(к[0] * ПЛОЧКА - п.x, к[1] * ПЛОЧКА - п.y))
            return self.център((в[0], в[1]))
        врати = self._врати_на(п.карта)
        в = min(врати, key=lambda к: math.hypot(к[0] * ПЛОЧКА - п.x, к[1] * ПЛОЧКА - п.y))
        return self.център((в[0], в[1] - 1))

    def _иди(self, п, карта, точка, време):
        """NPC върви до точка на картата; ако е на друга карта - през вратите (сграда -> село -> сграда).
        True = стигна."""
        if not self.село:
            карта = "krachma"
        if п.карта != карта:
            следваща = "selo" if п.карта != "selo" else карта
            врата = self._точка_врата(п, карта)
            if math.hypot(врата[0] - п.x, врата[1] - п.y) < 14 or self._върви(п, врата, време):
                self._прехвърли(п, следваща)
            return False
        if точка is None or math.hypot(точка[0] - п.x, точка[1] - п.y) < 8:
            п.върви = False
            return True
        return self._върви(п, точка, време)

    def _селска_точка(self, ключ, п=None):
        """Точка в селото от data/selo.json (кладенец, кокошарник...) или най-близката от списък (пазар, ниви)."""
        к = self.село_инфо.get(ключ)
        if not к:
            return None
        if isinstance(к[0], list):
            к = min(к, key=lambda к: math.hypot(к[0] * ПЛОЧКА - п.x, к[1] * ПЛОЧКА - п.y)) if п else к[0]
        return self.център(tuple(к))

    def _пазар_точка(self, п):
        return self._селска_точка("пазар", п)

    def до_точка(self, п, ключ, разстояние=90):
        if п.карта != "selo" or not self.село:
            return False
        к = self.село_инфо.get(ключ)
        if not к:
            return False
        точки = к if isinstance(к[0], list) else [к]
        return any(math.hypot(self.център(tuple(т))[0] - п.x, self.център(tuple(т))[1] - п.y) <= разстояние
                   for т in точки)

    def до_пазара(self, п):
        return self.до_точка(п, "пазар")

    # ---------- гостите: идват, когато им се яде, пие или иска веселба ----------
    def цена(self, предмет):
        return int(self.настройки["цени"].get(предмет, self.база_цени.get(предмет, 0)))

    def ниво_цени(self):
        """Колко пъти по-скъпо е менюто от нормалното (1.0 = нормални цени)."""
        менюто = [к for к in self.база_цени if self.база_цени[к]]
        if not менюто:
            return 1.0
        return sum(self.цена(к) / float(self.база_цени[к]) for к in менюто) / len(менюто)

    def _гост_данни(self, п):
        return self.гости_данни.get("гости", {}).get(п.id, {})

    def _врата(self, п):
        врати = self._мебели(self.склад_данни.get("пазар", "door"))
        if not врати:
            return None
        в = min(врати, key=lambda м: math.hypot(м[0] * ПЛОЧКА - п.x, м[1] * ПЛОЧКА - п.y))
        return self.център((в[0], в[1] - 1)) if 0 <= в[1] - 1 else self.център(в)

    def _прибери(self, п):
        """Гостът (или уволненият) излиза от кръчмата."""
        if п.седи is not None:
            self.стани(п)
        п.вкъщи, п.тръгва, п.отива = True, False, None
        п.x, п.y = ДАЛЕЧ
        п.карта = "krachma"
        п.иска = п.яде = None
        п.цел = п.към_място = None
        п.задача, п.носи, п.път, п.път_до = None, None, [], None
        п.без_място = п.остава = 0.0
        п.върви, п.хоро = False, 0.0

    def _доведи(self, п, в_кръчмата=False):
        """Гостът излиза от къщата си в селото и тръгва към кръчмата (нает отново - влиза направо)."""
        дом = self.село_инфо.get("домове", {}).get(п.id) if self.село else None
        if дом and not в_кръчмата:
            п.x, п.y = self.център(tuple(дом))
            за_покупки = (п.нужди.get("покупки", 0) >= max(п.нужди["глад"], п.нужди["жажда"], п.нужди["забава"])
                          and self.магазин_отворен())
            п.карта, п.отива = "selo", ("magazin" if за_покупки else "krachma")
            п.вкъщи, п.тръгва = False, False
            п.цел, п.почивка, п.заседнал, п.без_място = None, 0.0, 0.0, 0.0
            п.път, п.път_до = [], None
            return
        п.карта, п.отива = "krachma", None
        врати = self._врати_кръчма()
        if врати:
            в = self.случаен.choice(врати)
            п.x, п.y = self.център((в[0], в[1] - 1))
        else:
            п.x, п.y = self.център(self.случайна_клетка())
        п.вкъщи, п.тръгва = False, False
        п.цел, п.почивка, п.заседнал, п.без_място = None, 0.0, 0.0, 0.0

    def отворено(self):
        return self.склад_данни.get("отваря", НАЧАЛЕН_ЧАС) <= self.минути < self.склад_данни.get("затваря", 22 * 60) - 30

    def _гост_вкъщи(self, п, време):
        """Гостът е вкъщи: нуждите растат; ако някоя е голяма, идва (по-често при добро име на кръчмата)."""
        час = 60 * СЕКУНДИ_ЗА_МИНУТА
        за_час = self.гости_данни.get("нужди_на_час", {})
        for к in п.нужди:
            п.нужди[к] = min(100.0, п.нужди[к] + за_час.get(к, 10) * време / час)
        if not self.отворено() or п.сърдит_до > self.ден:
            return
        if max(п.нужди.values()) < self.гости_данни.get("идва_над", 55):
            return
        шанс = self.гости_данни.get("идва_на_секунда", 0.06) * (0.3 + self.репутация / 3.0)
        шанс *= min(1.3, 1.0 / max(0.5, self.ниво_цени()) ** 1.5)      # скъпа кръчма = идват по-рядко
        if self.село:
            шанс *= self.празничен_множител()                              # празник, камбани
        if self.случаен.random() < шанс * време:
            self._доведи(п)

    def _тръгни(self, п, време):
        """Гостът си тръгва: до вратата, през селото, до къщата си."""
        дом = self.село_инфо.get("домове", {}).get(п.id) if self.село else None
        if дом:
            if self._иди(п, "selo", self.център(tuple(дом)), време):
                self._прибери(п)
            return
        точка = self._врата(п)
        if точка is None or math.hypot(точка[0] - п.x, точка[1] - п.y) < 20 or self._върви(п, точка, време):
            self._прибери(п)

    def _мнение(self, п, доволство, текст):
        """Гостът казва какво мисли; името на кръчмата (звездите) се мени малко по малко."""
        доволство = max(0.0, min(1.0, доволство))
        self.репутация = round(self.репутация * 0.9 + доволство * 5 * 0.1, 3)
        п.мнение = (доволство, 4.0)
        звезди = 3 if доволство >= 0.8 else 2 if доволство >= 0.55 else 1 if доволство >= 0.3 else 0
        self.мнения.append({"име": п.име, "текст": текст, "звезди": звезди, "ден": self.ден,
                            "час": "%02d:%02d" % (self.минути // 60, self.минути % 60)})
        self.мнения = self.мнения[-8:]

    def _усърдие(self, п):
        """Колко бързо работи: заплата под нормалната = по-бавно, над нея = малко по-бързо."""
        база = self.база_заплати.get(п.роля)
        if not база:
            return 1.0
        return max(0.6, min(1.25, 0.5 + 0.5 * self.настройки["заплати"].get(п.роля, база) / база))

    def управлявай(self, клиент, оп, ключ, стойност=0):
        """Прозорецът на собственика (M): цени, заплати, пакети, наемане и уволнение."""
        аз = next((п for п in self.персони.values() if п.контролер == клиент), None)
        if аз is None or аз.роля != "собственик":
            return False, "Само собственикът може да управлява кръчмата"
        н = self.настройки
        if оп == "price" and ключ in н["цени"]:
            н["цени"][ключ] = max(1, min(99, int(стойност)))
            return True, "%s струва %d" % (self.име_на(ключ), н["цени"][ключ])
        if оп == "wage" and ключ in н["заплати"]:
            н["заплати"][ключ] = max(0, min(99, int(стойност)))
            return True, "Заплата на %s: %d на ден" % (ключ, н["заплати"][ключ])
        if оп == "pack" and ключ in н["пакети"]:
            н["пакети"][ключ] = max(1, min(9, int(стойност)))
            return True, "%s: по %d пакета" % (self.склад_данни["продукти"][ключ]["име"], н["пакети"][ключ])
        п = self.персони.get(ключ)
        if оп in ("fire", "hire") and п and п.роля in н["заплати"] and п is not аз:
            if оп == "fire":
                if п.контролер is not None:
                    return False, "%s в момента го играе %s - не можеш да го уволниш" % (п.име, п.играч)
                if п.уволнен:
                    return False, "%s вече е уволнен" % п.име
                п.уволнен = True
                н["уволнени"].append(п.id)
                self._прибери(п)
                return True, "Уволни %s (%s)" % (п.име, п.роля)
            if not п.уволнен:
                return False, "%s вече работи тук" % п.име
            п.уволнен = False
            н["уволнени"] = [и for и in н["уволнени"] if и != п.id]
            self._доведи(п, в_кръчмата=True)
            return True, "Нае отново %s (%s)" % (п.име, п.роля)
        return False, "Не стана"


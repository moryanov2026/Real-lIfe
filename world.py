def създай_начални_персони(папка=ПАПКА_ПЕРСОНИ):
    """Пише по един файл за всяка начална персона (по rules/PERSONI.md, раздел 6)."""
    os.makedirs(папка, exist_ok=True)
    for пид, име, роля, цвят, старт in ПЕРСОНИ_ПО_ПОДРАЗБИРАНЕ:
        данни = {"id": пид, "name": име, "role": роля, "color": цвят, "start": старт,
                 "age": 30, "traits": [], "likes": {"food": "", "music": "", "hobby": ""}}
        with open(os.path.join(папка, пид + ".json"), "w", encoding="utf-8") as f:
            json.dump(данни, f, ensure_ascii=False, indent=2)


def зареди_персони(папка=ПАПКА_ПЕРСОНИ):
    if not glob.glob(os.path.join(папка, "*.json")):
        създай_начални_персони(папка)
    персони = []
    for път in sorted(glob.glob(os.path.join(папка, "*.json"))):
        with open(път, encoding="utf-8") as f:
            персони.append(Персона(json.load(f)))
    return персони


class Персона:
    """Един човек в играта. Управлява го или играч (контролер = номер на клиента), или NPC (None)."""

    def __init__(self, данни):
        self.id = данни["id"]
        self.име = данни.get("name", self.id)
        self.роля = данни.get("role", "жител")
        self.цвят = данни.get("color", [200, 200, 200])
        self.старт = данни.get("start")
        self.данни = данни                      # характер, предпочитания (за следващите етапи)
        self.x = self.y = 0.0                   # средата на долния ръб (краката)
        self.енергия = float(МАКС_ЕНЕРГИЯ)
        self.пари = НАЧАЛНИ_ПАРИ
        self.контролер = None
        self.играч = ""
        self.dx = self.dy = 0.0
        self.върви = False
        self.посока = "down"
        self.свири = False                      # музикантът свири (миниигра "Свирене")
        # само за NPC
        self.цел = None
        self.почивка = 0.0
        self.заседнал = 0.0

    def кутия(self, x=None, y=None):
        x = self.x if x is None else x
        y = self.y if y is None else y
        return pygame.Rect(int(x - СБЛЪСЪК_ШИРИНА / 2), int(y - СБЛЪСЪК_ВИСОЧИНА),
                           СБЛЪСЪК_ШИРИНА, СБЛЪСЪК_ВИСОЧИНА)

    def мръдни(self, dx, dy, препятствия, време, скорост):
        """Движим по една ос, за да може да се плъзга покрай стените."""
        дължина = math.hypot(dx, dy)
        self.върви = дължина > 0.01
        if not self.върви:
            return
        if дължина > 1:                          # по диагонал да не е по-бърз
            dx, dy = dx / дължина, dy / дължина
        if abs(dx) > abs(dy):
            self.посока = "right" if dx > 0 else "left"
        else:
            self.посока = "down" if dy > 0 else "up"
        нов_x = self.x + dx * скорост * време
        if not any(self.кутия(нов_x, self.y).colliderect(о) for о in препятствия):
            self.x = нов_x
        нов_y = self.y + dy * скорост * време
        if not any(self.кутия(self.x, нов_y).colliderect(о) for о in препятствия):
            self.y = нов_y

    def описание(self):
        """Неща, които не се менят: пращат се веднъж."""
        return {"id": self.id, "name": self.име, "role": self.роля, "color": self.цвят}

    def състояние(self):
        """Неща, които се менят: пращат се всеки тик."""
        return {"id": self.id, "x": round(self.x, 1), "y": round(self.y, 1),
                "ctrl": "human" if self.контролер is not None else "npc", "player": self.играч,
                "walk": self.върви, "dir": self.посока, "play": self.свири,
                "energy": round(self.енергия), "money": self.пари}


class Свят:
    def __init__(self, път_карта=ПЪТ_КАРТА, папка_персони=ПАПКА_ПЕРСОНИ, семе=None):
        self.случаен = random.Random(семе)
        self.плочки = tiles.зареди_плочки()
        self.карта = tiles.зареди_карта(път_карта)
        self.колони, self.редове = self.карта["width"], self.карта["height"]
        self.заети = set()                      # клетки с твърд предмет
        self.препятствия = []
        for о in self.карта["objects"]:
            д = self.плочки.get(о["name"])
            if д and д["solid"]:
                self.препятствия.append(pygame.Rect(о["x"] * ПЛОЧКА, о["y"] * ПЛОЧКА,
                                                    д["w"] * ПЛОЧКА, д["h"] * ПЛОЧКА))
                for yy in range(о["y"], о["y"] + д["h"]):
                    for xx in range(о["x"], о["x"] + д["w"]):
                        self.заети.add((xx, yy))
        ш, в = self.колони * ПЛОЧКА, self.редове * ПЛОЧКА
        self.препятствия += [pygame.Rect(-ПЛОЧКА, 0, ПЛОЧКА, в), pygame.Rect(ш, 0, ПЛОЧКА, в),
                             pygame.Rect(0, -ПЛОЧКА, ш, ПЛОЧКА), pygame.Rect(0, в, ш, ПЛОЧКА)]
        self.свободни = [(x, y) for y in range(self.редове) for x in range(self.колони)
                         if (x, y) not in self.заети and self.карта["floor"][y][x]]
        self.персони = {}
        for п in зареди_персони(папка_персони):
            клетка = tuple(п.старт) if п.старт and tuple(п.старт) in self.свободни else self.случайна_клетка()
            п.x, п.y = self.център(клетка)
            self.персони[п.id] = п
        self.минути = НАЧАЛЕН_ЧАС
        self.ден = 1
        self._натрупано = 0.0

    # ---------- помощни ----------
    def център(self, клетка):
        return клетка[0] * ПЛОЧКА + ПЛОЧКА / 2, (клетка[1] + 1) * ПЛОЧКА - 8

    def случайна_клетка(self):
        return self.случаен.choice(self.свободни)

    # ---------- кой управлява коя персона ----------
    def вземи(self, пид, клиент, име):
        п = self.персони.get(пид)
        if п is None or п.контролер is not None:
            return False
        self.освободи(клиент)                   # един клиент = една персона
        п.контролер, п.играч = клиент, име
        п.dx = п.dy = 0.0
        п.цел = None
        return True

    def освободи(self, клиент):
        """Играчът излезе: NPC поема персоната му (GAME_RULES, раздел 3а)."""
        for п in self.персони.values():
            if п.контролер == клиент:
                п.контролер, п.играч = None, ""
                п.dx = п.dy = 0.0
                п.свири = False
                п.почивка = 1.0

    def вход(self, клиент, dx, dy):
        for п in self.персони.values():
            if п.контролер == клиент:
                п.dx = max(-1.0, min(1.0, float(dx)))
                п.dy = max(-1.0, min(1.0, float(dy)))

    def свирене(self, клиент, пуснато, резултат=None):
        """Музикантът започна или свърши песен. Връща бакшиша (пари) след песента."""
        for п in self.персони.values():
            if п.контролер != клиент:
                continue
            п.свири = bool(пуснато)
            п.dx = п.dy = 0.0
            if пуснато or not isinstance(резултат, dict):
                return 0
            процент = max(0.0, min(100.0, float(резултат.get("percent", 0))))
            част = max(0.0, min(1.0, float(резултат.get("tip_factor", 1.0))))   # лесно ниво = по-малък бакшиш
            бакшиш = int(round(процент * БАКШИШ_ЗА_100 / 100.0 * част))
            п.пари += бакшиш
            п.енергия = max(0.0, п.енергия - ЕНЕРГИЯ_ПЕСЕН)
            return бакшиш
        return 0

    # ---------- един тик ----------
    def обнови(self, време):
        for п in self.персони.values():
            if п.контролер is None:
                self._npc(п, време)
            elif п.свири:
                п.върви = False                 # докато свири, стои на място
            else:
                п.мръдни(п.dx, п.dy, self.препятствия, време, СКОРОСТ)
        self._натрупано += време
        while self._натрупано >= СЕКУНДИ_ЗА_МИНУТА:
            self._натрупано -= СЕКУНДИ_ЗА_МИНУТА
            self.минути += 1
            for п in self.персони.values():
                загуба = ЕНЕРГИЯ_НА_МИНУТА + (ЕНЕРГИЯ_ХОДЕНЕ if п.върви else 0)
                п.енергия = max(0.0, п.енергия - загуба)
            if self.минути >= 24 * 60:
                self.минути -= 24 * 60
                self.ден += 1

    def _npc(self, п, време):
        """Засега NPC само се разхождат (задачите идват в Етап 4)."""
        if п.почивка > 0:
            п.почивка -= време
            п.върви = False
            return
        if п.цел is None:
            п.цел = self.център(self.случайна_клетка())
        цx, цy = п.цел
        dx, dy = цx - п.x, цy - п.y
        разстояние = math.hypot(dx, dy)
        if разстояние < 6:
            п.цел = None
            п.върви = False
            п.почивка = self.случаен.uniform(NPC_ПОЧИВКА_ОТ, NPC_ПОЧИВКА_ДО)
            return
        преди = (п.x, п.y)
        п.мръдни(dx / разстояние, dy / разстояние, self.препятствия, време, СКОРОСТ_NPC)
        if math.hypot(п.x - преди[0], п.y - преди[1]) < СКОРОСТ_NPC * време * 0.3:
            п.заседнал += време
            if п.заседнал > 0.6:                # опря в маса: избира друго място
                п.цел, п.заседнал = None, 0.0
        else:
            п.заседнал = 0.0

    # ---------- за мрежата ----------
    def описания(self):
        return [п.описание() for п in self.персони.values()]

    def състояние(self):
        return {"day": self.ден, "minutes": self.минути,
                "persons": [п.състояние() for п in self.персони.values()]}

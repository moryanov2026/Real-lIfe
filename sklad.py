# Складът на кръчмата: какви продукти има, колко струват и кое ястие какво харчи.
# Данните са в data/sklad.json (класът ги сменя), рецептите - в data/recipes.json.
# Ползват го и сървърът (world.py), и играта (main.py), за да знаят едно и също.
import json
import os

ПАПКА = os.path.dirname(os.path.abspath(__file__))
ПЪТ = os.path.join(ПАПКА, "data", "sklad.json")
ПЪТ_РЕЦЕПТИ = os.path.join(ПАПКА, "data", "recipes.json")


def зареди(път=ПЪТ):
    with open(път, encoding="utf-8") as f:
        return json.load(f)


def рецепти(път=ПЪТ_РЕЦЕПТИ):
    try:
        with open(път, encoding="utf-8") as f:
            return json.load(f)["рецепти"]
    except (OSError, ValueError, KeyError):
        return {}


def нужни(предмет, данни, рецепти_):
    """Кои продукти харчи едно ястие (по 1 порция от всеки). Водата и всичко, което го няма
    в склада, е безплатно. Пиенето и хлябът се пишат направо в данни["ястия"]."""
    продукти = данни.get("продукти", {})
    if предмет in данни.get("ястия", {}):
        return [к for к in данни["ястия"][предмет] if к in продукти]
    зеленчуци = данни.get("зеленчуци", [])
    нужно = []
    for стъпка in рецепти_.get(предмет, []):
        игра = стъпка.get("игра")
        ключове = []
        if игра == "рязане":
            ключове = [зеленчуци[з] for з in стъпка.get("зеленчуци", []) if 0 <= з < len(зеленчуци)]
        elif игра in ("добави", "запържване"):
            ключове = [п.get("икона", "") for п in стъпка.get("продукти", [])]
        elif игра == "боядисване":
            ключове = ["yaytse", "boya"]
        elif игра == "печене":
            ключове = [стъпка.get("продукт", "chushki" if стъпка.get("съд", "скара") == "скара" else "luk")]
        for к in ключове:
            if к in продукти and к not in нужно:
                нужно.append(к)
    return нужно


def липсват(предмет, данни, рецепти_, склад):
    """Продуктите, които ги няма в склада (празен списък = може да се готви)."""
    return [к for к in нужни(предмет, данни, рецепти_) if склад.get(к, 0) < 1]


def за_пазар(данни, склад):
    """Какво да купи снабдителят: {продукт: брой пакети} за всичко под прага."""
    праг = данни.get("праг", 3)
    return {к: 1 for к, п in данни.get("продукти", {}).items() if склад.get(к, 0) < праг}


def цена_на_пазар(данни, списък):
    return sum(данни["продукти"][к]["цена"] * брой for к, брой in списък.items())


def себестойност(предмет, данни, рецепти_):
    """Колко струват продуктите за една порция (за отчета и за учениците)."""
    продукти = данни.get("продукти", {})
    return sum(продукти[к]["цена"] / float(продукти[к]["пакет"]) for к in нужни(предмет, данни, рецепти_))

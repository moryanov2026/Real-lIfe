import json
import math
import os

import tiles

ПЪТ = os.path.join(tiles.ПАПКА, "data", "items.json")
ДО_СТАНЦИЯ = 60        # колко близо до мебелта трябва да си, за да приготвиш / вземеш (пиксела)
ДО_ГОСТ = 120          # колко близо до госта трябва да си, за да му сервираш


def зареди():
    with open(ПЪТ, encoding="utf-8") as f:
        return json.load(f)


def станции_на_карта(карта, меню):
    """Всички мебели, на които се приготвя нещо: [(x, y, име на мебелта, предмет)].
    На една мебел може да се прави повече от едно нещо (дъската: шопска и хляб) - тогава
    мебелта е в списъка веднъж за всяко нещо."""
    по_мебел = {}
    for ключ, п in меню["предмети"].items():
        for с in п["станции"]:
            по_мебел.setdefault(с, []).append(ключ)
    return [(о["x"], о["y"], о["name"], предмет) for о in карта["objects"] if о["name"] in по_мебел
            for предмет in по_мебел[о["name"]]]


def до_станция(x, y, сx, сy):
    """Разстояние от краката (x, y) до квадратчето на мебелта."""
    л, г = сx * tiles.ПЛОЧКА, сy * tiles.ПЛОЧКА
    дx = max(л - x, 0, x - (л + tiles.ПЛОЧКА))
    дy = max(г - y, 0, y - (г + tiles.ПЛОЧКА))
    return math.hypot(дx, дy)


def гост(роля, меню):
    return any(роля.startswith(г) for г in меню["гости"])

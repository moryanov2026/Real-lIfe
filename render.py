# Рисуване на картата и персоните. Ползват го играта (main.py) и редакторът (editor.py).
import math
import os
import time

import pygame

import tiles

ПЛОЧКА = tiles.ПЛОЧКА
ПАПКА_ПЕРСОНИ = os.path.join(tiles.ПАПКА_КАРТИНКИ, "persons")   # картинки на хората: assets/persons/<id>.png
ЦВЯТ_СЯНКА = (40, 30, 30)
КАДРИ_ХОДЕНЕ = 8               # кадри в един цикъл на ходене
СКОРОСТ_АНИМАЦИЯ = 8           # кадри в секунда
# Лист за ходене assets/persons/<id>_walk.png: 8 колони x 3 реда по 64x64.
# Ред 1 = надолу (към нас), ред 2 = нагоре (с гръб), ред 3 = надясно.
# Ред 4 = наляво (по желание; ако го няма, наляво = огледало на надясно).
РЕДОВЕ_ХОДЕНЕ = ("down", "up", "right")
_ШРИФТ_НОТИ = None             # нотките над музиканта, когато свири
_СТРАНА_ХОРО = {}              # накъде я води хорото (за огледалните кадри)


def зареди_картинки(плочки, персони=()):
    """Всички картинки веднъж при старта (GAME_RULES, раздел 3)."""
    картинки = tiles.зареди_картинки(плочки)
    има_прозорец = pygame.display.get_surface() is not None
    for о in персони:
        път = tiles.намери_картинка(os.path.join("persons", о["id"] + ".png"))
        if път:
            к = pygame.image.load(път)
            картинки["persona:" + о["id"]] = к.convert_alpha() if има_прозорец else к
        път = tiles.намери_картинка(os.path.join("persons", о["id"] + "_walk.png"))
        if път:
            лист = pygame.image.load(път)
            лист = лист.convert_alpha() if има_прозорец else лист
            кадри = {}
            for р, посока in enumerate(РЕДОВЕ_ХОДЕНЕ):
                кадри[посока] = [лист.subsurface((к * ПЛОЧКА, р * ПЛОЧКА, ПЛОЧКА, ПЛОЧКА)).copy()
                                 for к in range(КАДРИ_ХОДЕНЕ)]
            if лист.get_height() >= 4 * ПЛОЧКА:     # нарисуван отделен ред наляво
                кадри["left"] = [лист.subsurface((к * ПЛОЧКА, 3 * ПЛОЧКА, ПЛОЧКА, ПЛОЧКА)).copy()
                                 for к in range(КАДРИ_ХОДЕНЕ)]
            else:                                    # иначе огледало на надясно
                кадри["left"] = [pygame.transform.flip(к, True, False) for к in кадри["right"]]
            картинки["walk:" + о["id"]] = кадри
        път = tiles.намери_картинка(os.path.join("persons", о["id"] + "_sit.png"))
        if път:                                  # сядане: 3 реда (надолу, нагоре, надясно) x 4 кадъра
            лист = pygame.image.load(път)
            лист = лист.convert_alpha() if има_прозорец else лист
            седи = {}
            for р, посока in enumerate(РЕДОВЕ_ХОДЕНЕ):
                седи[посока] = [лист.subsurface((к * ПЛОЧКА, р * ПЛОЧКА, ПЛОЧКА, ПЛОЧКА)).copy() for к in range(4)]
            седи["left"] = [pygame.transform.flip(к, True, False) for к in седи["right"]]
            картинки["sit:" + о["id"]] = седи
        път = tiles.намери_картинка(os.path.join("persons", о["id"] + "_dance.png"))
        if път:                                  # танцува хоро: лист 512x64, 8 кадъра (отпред)
            лист = pygame.image.load(път)
            лист = лист.convert_alpha() if има_прозорец else лист
            картинки["dance:" + о["id"]] = [лист.subsurface((к * ПЛОЧКА, 0, ПЛОЧКА, ПЛОЧКА)).copy()
                                            for к in range(лист.get_width() // ПЛОЧКА)]
            # огледален вариант: когато хорото я води наляво, свободната ръка води напред
            картинки["dance_flip:" + о["id"]] = [pygame.transform.flip(к, True, False)
                                                 for к in картинки["dance:" + о["id"]]]
        път = tiles.намери_картинка(os.path.join("persons", о["id"] + "_play.png"))
        if път:                                  # поза "свири": лист 128x64, 2 кадъра
            лист = pygame.image.load(път)
            лист = лист.convert_alpha() if има_прозорец else лист
            картинки["play:" + о["id"]] = [лист.subsurface((к * ПЛОЧКА, 0, ПЛОЧКА, ПЛОЧКА)).copy()
                                           for к in range(лист.get_width() // ПЛОЧКА)]
    return картинки


def кадър_на_персона(п, картинки, време):
    """Кой кадър да се покаже: при ходене се сменят 8 кадъра, на място стои първият."""
    if п.get("sit") and картинки.get("sit:" + п["id"]):       # седи: 2 кадъра сядане, после 2 кадъра седене
        кадри = картинки["sit:" + п["id"]].get(п["sit"]) or картинки["sit:" + п["id"]]["down"]
        от_кога = time.perf_counter() - п.get("седна_в", 0)
        if от_кога < 0.12:
            return кадри[0]
        if от_кога < 0.24:
            return кадри[1]
        return кадри[2 + int(време * 1.2) % 2]
    if п.get("dance") and картинки.get("dance:" + п["id"]):   # хоро: собствени кадри, по-бързо при хубава музика
        посока = п.get("dir")
        if посока in ("left", "right"):          # нагоре/надолу пазим последната страна
            _СТРАНА_ХОРО[п["id"]] = посока
        наляво = _СТРАНА_ХОРО.get(п["id"]) == "left"
        хоро = картинки["dance_flip:" + п["id"]] if наляво else картинки["dance:" + п["id"]]
        return хоро[int(време * (6 + 6 * п["dance"])) % len(хоро)]
    if п.get("play") and картинки.get("play:" + п["id"]):     # свири: сменя 2 кадъра в такт
        свири = картинки["play:" + п["id"]]
        return свири[int(време * 3) % len(свири)]
    кадри = картинки.get("walk:" + п["id"])
    if not кадри:
        return картинки.get("persona:" + п["id"])
    посока = п.get("dir", "down")
    if посока not in кадри:
        посока = "down"
    if п.get("walk"):
        отместване = sum(ord(б) for б in п["id"]) % КАДРИ_ХОДЕНЕ   # да не крачат всички в такт
        индекс = (int(време * СКОРОСТ_АНИМАЦИЯ) + отместване) % КАДРИ_ХОДЕНЕ
    else:
        индекс = 0
    return кадри[посока][индекс]


def нарисувай_персона(екран, п, картинки, кам_x, кам_y):
    """п е речник с x, y (краката), id, color."""
    x, y = int(п["x"]) - кам_x, int(п["y"]) - кам_y
    if not п.get("sit"):                        # седналият няма сянка на пода (столът е под него)
        сянка = pygame.Rect(0, 0, 44, 14)      # сянката се рисува от кода, не е в картинката
        сянка.center = (x, y - 5)
        pygame.draw.ellipse(екран, ЦВЯТ_СЯНКА, сянка)
    к = кадър_на_персона(п, картинки, pygame.time.get_ticks() / 1000.0)
    if п.get("sit") and not картинки.get("sit:" + п["id"]):
        # няма нарисувано сядане: героят се снишава на стола (краката се скриват)
        if к:
            ниско = к.subsurface((0, 0, к.get_width(), к.get_height() - 12))
            екран.blit(ниско, (x - к.get_width() // 2, y - к.get_height() + 6))
            return
        y += 10
    if п.get("dance") and not картинки.get("dance:" + п["id"]):   # без кадри за хоро: поне подскача в ритъма
        т = pygame.time.get_ticks() / 1000.0
        фаза = sum(ord(б) for б in п["id"]) % 7
        y -= int(abs(math.sin(т * 6.5 + фаза * 0.4)) * (2 + 5 * п["dance"]))
    if к:
        екран.blit(к, (x - к.get_width() // 2, y - к.get_height()))
        return
    # Няма картинка: тяло и глава в цвета на персоната (правило 5)
    цвят = п.get("color", [200, 200, 200])
    тяло = pygame.Rect(x - 14, y - 40, 28, 38)
    глава = pygame.Rect(x - 11, y - 62, 22, 22)
    pygame.draw.rect(екран, цвят, тяло)
    pygame.draw.rect(екран, tiles.ЦВЯТ_КОНТУР, тяло, 1)
    pygame.draw.rect(екран, (235, 200, 170), глава)
    pygame.draw.rect(екран, tiles.ЦВЯТ_КОНТУР, глава, 1)


def _стена_отгоре(картинки):
    """Ръбът на стената отгоре (ако няма картинка: тъмно сив)."""
    if "wall_top" not in картинки:
        к = pygame.Surface((ПЛОЧКА, ПЛОЧКА))
        к.fill((84, 74, 66))
        картинки["wall_top"] = к
    return картинки["wall_top"]


def _ръбове(екран, x, y, клетки, отворени, кам_x, кам_y):
    """Тъмен контур по страните на ръба отгоре, където до стената няма стена."""
    px, py = x * ПЛОЧКА - кам_x, y * ПЛОЧКА - ПЛОЧКА // 2 - кам_y
    ц = (30, 20, 16)
    if (x - 1, y) not in клетки:
        pygame.draw.rect(екран, ц, (px, py, 2, ПЛОЧКА))
    if (x + 1, y) not in клетки:
        pygame.draw.rect(екран, ц, (px + ПЛОЧКА - 2, py, 2, ПЛОЧКА))
    if (x, y - 1) not in клетки:
        pygame.draw.rect(екран, ц, (px, py, ПЛОЧКА, 2))
    if (x, y + 1) not in клетки or (x, y + 1) in отворени:
        pygame.draw.rect(екран, ц, (px, py + ПЛОЧКА - 2, ПЛОЧКА, 2))
        # малка сянка върху пода под ръба
        сянка = pygame.Surface((ПЛОЧКА, 6), pygame.SRCALPHA)
        сянка.fill((0, 0, 0, 60))
        екран.blit(сянка, (px, py + ПЛОЧКА))


def нарисувай_карта(екран, карта, плочки, картинки, кам_x, кам_y, персони=()):
    """Подът, после предметите и персоните, подредени по долния ръб (Y-сортиране).
    Стените се показват сами по два начина (GAME_RULES 6):
      - под стената има под (не празно) -> лице (wall.png / window.png / door.png), горната стена на стаята;
      - иначе                -> ръб отгоре (wall_top.png / door_top.png), страничните и долната стена."""
    вис = карта["height"]
    стени = {(о["x"], о["y"]): о["name"] for о in карта["objects"] if о["name"] in tiles.СТЕНИ}
    for y, ред in enumerate(карта["floor"]):
        for x, име in enumerate(ред):
            if име in плочки and стени.get((x, y)) not in ("wall", "window"):   # под стените не трябва под
                tiles.нарисувай_плочка(екран, картинки[име], плочки[име], x, y, кам_x, кам_y)
    плътни = {к for к, и in стени.items() if и != "door"}      # вратите правят дупка в контура
    # лице има само стената, под която има под (вътрешността на стаята)
    лице = {к for к in стени if к[1] + 1 < вис and (к[0], к[1] + 1) not in стени
            and карта["floor"][к[1] + 1][к[0]]}
    # сянка от стените с лице върху пода под тях
    сянка = pygame.Surface((ПЛОЧКА, 10), pygame.SRCALPHA)
    for i in range(10):
        pygame.draw.line(сянка, (0, 0, 0, 70 - i * 7), (0, i), (ПЛОЧКА, i))
    for (x, y) in лице:
        екран.blit(сянка, (x * ПЛОЧКА - кам_x, (y + 1) * ПЛОЧКА - кам_y))
    за_рисуване = []
    for о in карта["objects"]:
        if о["name"] not in плочки:
            continue
        к = (о["x"], о["y"])
        if к in стени and к not in лице:
            за_рисуване.append((о["y"] * ПЛОЧКА + ПЛОЧКА // 2, 0, о))   # ръб отгоре: стърчи 32 px нагоре
        else:
            за_рисуване.append(((о["y"] + плочки[о["name"]]["h"]) * ПЛОЧКА + плочки[о["name"]].get("dy", 0), 0, о))
    for п in персони:
        # седналият на стол, обърнат нагоре, е зад облегалката; иначе е пред стола
        ключ = п["y"] + (0 if not п.get("sit") else (-14 if п["sit"] == "up" else 14))
        за_рисуване.append((ключ, 1, п))
    за_рисуване.sort(key=lambda е: (е[0], е[1]))
    for _, вид, е in за_рисуване:
        if вид == 1:
            нарисувай_персона(екран, е, картинки, кам_x, кам_y)
            continue
        к = (е["x"], е["y"])
        if к in стени and к not in лице:
            if е["name"] == "door":
                картинка = картинки.get("door_top") or _стена_отгоре(картинки)
                x, y = к
                if ((x, y - 1) in стени or (x, y + 1) in стени) and not ((x - 1, y) in стени or (x + 1, y) in стени):
                    # вход в странична стена: минава се хоризонтално -> завъртян
                    if "door_top_side" not in картинки:
                        картинки["door_top_side"] = pygame.transform.rotate(картинка, 90)
                    картинка = картинки["door_top_side"]
            else:
                картинка = _стена_отгоре(картинки)
            екран.blit(картинка, (е["x"] * ПЛОЧКА - кам_x, е["y"] * ПЛОЧКА - ПЛОЧКА // 2 - кам_y))
            if е["name"] != "door":
                _ръбове(екран, е["x"], е["y"], плътни, (), кам_x, кам_y)
        else:
            tiles.нарисувай_плочка(екран, картинки[е["name"]], плочки[е["name"]], е["x"], е["y"], кам_x, кам_y)


def нарисувай_хоро(екран, персони, кам_x, кам_y, картинки=None):
    """Хорото: всеки протяга къси ръце към двамата си съседи (ръкав в цвета на дрехата + длан).
    Който има свои кадри за хоро (persons/<id>_dance.png), си има нарисувани ръце - на него не добавяме."""
    картинки = картинки or {}
    играчи = [п for п in персони if п.get("dance")]
    if len(играчи) < 2:
        return
    сx = sum(п["x"] for п in играчи) / len(играчи)
    сy = sum(п["y"] for п in играчи) / len(играчи)
    играчи.sort(key=lambda п: math.atan2((п["y"] - сy) / 0.62, п["x"] - сx))
    for и, п in enumerate(играчи):
        if картинки.get("dance:" + п["id"]):
            continue
        for съсед in (играчи[и - 1], играчи[(и + 1) % len(играчи)]):
            dx, dy = съсед["x"] - п["x"], съсед["y"] - п["y"]
            разстояние = math.hypot(dx, dy)
            if разстояние < 1 or разстояние > 170:
                continue
            if abs(dx) < 12:                     # съседът е точно отпред/отзад: ръката би минала през тялото
                continue
            страна = 1 if dx > 0 else -1             # ръката излиза от страната към съседа
            наклон = max(-0.7, min(0.7, dy / abs(dx)))
            рамо = (int(п["x"] + страна * 14) - кам_x, int(п["y"] - 30) - кам_y)
            дължина = min(24, abs(dx) / 2 - 4)
            if дължина < 4:
                continue
            длан = (int(рамо[0] + страна * дължина), int(рамо[1] + наклон * дължина + 3))
            цвят = п.get("color", [200, 200, 200])
            pygame.draw.line(екран, (30, 20, 16), рамо, длан, 6)
            pygame.draw.line(екран, цвят, рамо, длан, 4)
            pygame.draw.circle(екран, (30, 20, 16), длан, 4)
            pygame.draw.circle(екран, (236, 196, 160), длан, 3)


def нарисувай_имена(екран, шрифт, персони, кам_x, кам_y, мое_id=None):
    """Имената над главите: жълто = играч, сиво = NPC, зелено = ти."""
    for п in персони:
        if п["id"] == мое_id:
            цвят, текст = (120, 255, 120), "%s (ти)" % п["name"]
        elif п.get("ctrl") == "human":
            цвят, текст = (255, 220, 60), "%s [%s]" % (п["name"], п.get("player", ""))
        else:
            цвят, текст = (200, 200, 200), п["name"]
        надпис = шрифт.render(текст, True, цвят)
        x = int(п["x"]) - кам_x - надпис.get_width() // 2
        y = int(п["y"]) - кам_y - 84
        фон = pygame.Surface((надпис.get_width() + 6, надпис.get_height() + 2), pygame.SRCALPHA)
        фон.fill((0, 0, 0, 140))
        екран.blit(фон, (x - 3, y - 1))
        екран.blit(надпис, (x, y))
        if п.get("play"):                       # свири: нотки се вдигат над главата
            т = pygame.time.get_ticks() / 1000.0
            for к in range(3):
                фаза = (т * 0.8 + к / 3.0) % 1.0
                нx = int(п["x"]) - кам_x + int(14 * __import__("math").sin(фаза * 6 + к)) + (к - 1) * 10
                нy = y - 6 - int(фаза * 34)
                global _ШРИФТ_НОТИ
                if _ШРИФТ_НОТИ is None:
                    _ШРИФТ_НОТИ = pygame.font.SysFont("arial", 24, bold=True)
                нота = _ШРИФТ_НОТИ.render("♪♫♪"[к], True, (255, 230, 120))
                нота.set_alpha(int(255 * (1 - фаза)))
                екран.blit(нота, (нx, нy))

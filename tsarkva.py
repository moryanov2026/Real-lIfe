МЕСЕЦИ = ("януари", "февруари", "март", "април", "май", "юни", "юли", "август", "септември", "октомври", "ноември", "декември")
ДНИ = ("понеделник", "вторник", "сряда", "четвъртък", "петък", "събота", "неделя")


def великден(година):
    """Православният Великден (алгоритъм на Меус по юлианския календар, +13 дни за 1900-2099)."""
    a, b, c = година % 4, година % 7, година % 19
    d = (19 * c + 15) % 30
    e = (2 * a + 4 * b - d + 34) % 7
    месец = (d + e + 114) // 31
    ден = (d + e + 114) % 31 + 1
    return datetime.date(година, месец, ден) + datetime.timedelta(days=13)


def съвпада(запис, дата):
    """Дали записът от календара ("дата": "ММ-ДД" или "великден": отместване) се пада на тази дата."""
    if "дата" in запис:
        return дата.strftime("%m-%d") == запис["дата"]
    if "великден" in запис:
        return дата == великден(дата.year) + datetime.timedelta(days=запис["великден"])
    return False
МАСИ = ("table_big", "table_big_v", "table", "table_right")


class ЦъркваМиксин:
    # ---------- начало ----------
    def _църква_карта_начало(self):
        self.църква_карта = None
        if self.село and os.path.exists(ПЪТ_КАРТА):
            self.църква_карта = tiles.зареди_карта(ПЪТ_КАРТА)
            self.цър_заети, self.цър_препятствия = self._геометрия(self.църква_карта)

    def _църква_начало(self):
        try:
            with open(ПЪТ, encoding="utf-8") as f:
                self.пр_данни = json.load(f)
        except (OSError, ValueError):
            self.пр_данни = {"година_дни": 12, "празници": [], "събития": [], "гощавка": {}, "камбани": []}
        self.гощавка = None                     # {"вид", "име", "ястия", "дадени", "до", "качества", "обред"}
        self.обред = None                       # {"вид", "до"}: сватбата/кръщенето чака отеца в църквата
        self.камбани_до = -1                    # до кога бият камбаните (минута от началото на играта)
        self.звъннато = True
        self.звън_бонус, self.звън_бонус_до = 0.0, -1
        self.свещи_ден = 0                      # в кой ден са запалени свещите
        self.обявления = []                     # съобщения до всички (сървърът ги праща)

    # ---------- календарът ----------
    def дата(self):
        """Истинската дата в играта: от началната (денят, в който е започната играта) нататък."""
        return self.начална_дата + datetime.timedelta(days=self.ден - 1)

    def дата_текст(self, дата=None):
        дата = дата or self.дата()
        return "%s, %d %s %d" % (ДНИ[дата.weekday()], дата.day, МЕСЕЦИ[дата.month - 1], дата.year)

    def ден_от_годината(self):
        return self.дата().timetuple().tm_yday

    def празник(self, дата=None):
        дата = дата or self.дата()
        return next((п for п in self.пр_данни.get("празници", []) if съвпада(п, дата)), None)

    def пост(self, дата=None):
        дата = дата or self.дата()
        for п in self.пр_данни.get("пости", []):
            if "от" in п:
                мд = дата.strftime("%m-%d")
                if п["от"] <= мд <= п["до"]:
                    return п
            elif "великден_от" in п:
                в = великден(дата.year)
                if в + datetime.timedelta(days=п["великден_от"]) <= дата <= в + datetime.timedelta(days=п["великден_до"]):
                    return п
        return None

    def именници(self, дата=None):
        """Кои от хората в играта имат имен ден днес (по първото име)."""
        дата = дата or self.дата()
        имена = set()
        for запис in self.пр_данни.get("именни_дни", []):
            if съвпада(запис, дата):
                имена.update(запис.get("имена", []))
        if not имена:
            return []
        return [п for п in self.персони.values() if any(дума in имена for дума in п.име.replace(",", " ").split())]

    def постно(self, предмет):
        return предмет in self.пр_данни.get("постни", [])

    def има_днес(self, предмет):
        """Празничните ястия са в менюто само в своя празник."""
        празник = self.меню["предмети"].get(предмет, {}).get("празник")
        if not празник:
            return True
        п = self.празник()
        return bool(п and п.get("име") == празник)

    def празничен_множител(self):
        """Колко пъти по-често идват гостите: празникът и камбаните."""
        п = self.празник()
        м = п.get("гости", 1.0) if п else 1.0
        if self.именници():
            м *= 1.2                            # имен ден: идват да го черпят
        if self._абс_минута() < self.звън_бонус_до:
            м *= 1 + self.звън_бонус
        return м

    # ---------- всяка минута ----------
    def _църква_минута(self):
        д = self.пр_данни
        абс = self._абс_минута()
        if self.минути in д.get("камбани", []):
            self.камбани_до = абс + д.get("камбани_минути", 25)
            self.звъннато = False
            self.обявления.append("Камбаните бият! Звънарят - на камбанарията.")
        if self.минути == 18 * 60 + 30:                       # именниците черпят в кръчмата
            self._черпене()
        for с in д.get("събития", []):
            if (с.get("ден_от_седмицата") == self.дата().weekday() and not (с["вид"] == "сватба" and self.пост())
                    and self.минути == с.get("час", 11) * 60 and not self.гощавка):
                г = д.get("гощавка", {}).get(с["вид"], {})
                self.обред = {"вид": с["вид"], "до": абс + 120}
                self.обявления.append("Днес има %s! Отецът го чака в църквата, после - гощавка в кръчмата." % г.get("име", с["вид"]).lower())
        if self.обред and абс > self.обред["до"]:          # никой не го направи: само гощавката
            self._започни_гощавка(self.обред["вид"], 0.5)
        if self.гощавка and абс > self.гощавка["до"]:
            self._край_гощавка(False)
        п = self.празник()
        if п and п.get("хоро") and self.минути in (12 * 60 + 10, 18 * 60 + 10):
            self._празнична_музика()

    def _празнична_музика(self):
        """В празник музикантът (ако е NPC) засвирва сам."""
        м = next((п for п in self.персони.values() if п.роля == "музикант" and п.контролер is None), None)
        песни = self._песни()
        if not м or м.песен or not песни or м.карта != "krachma":
            return
        файл, име, дължина = self.случаен.choice(песни)
        if м.седи is not None:
            self.стани(м)
        м.цел, м.към_място, м.върви, м.посока = None, None, False, "down"
        м.свири, м.настроение = True, 0.8
        м.песен, м.песен_време, м.песен_дължина, м.до_хоро = файл, 0.0, дължина, 5.0
        self.обявления.append("Празник е - %s засвири „%s“!" % (м.име, име))

    def _черпене(self):
        сума = self.пр_данни.get("черпи", 20)
        с = self.собственик()
        for п in self.именници():
            if п.пари < сума or п is с:
                continue
            п.пари -= сума
            if с:
                с.пари += сума
            self.днес["приходи"] += сума
            self.репутация = min(5.0, self.репутация + 0.1)
            for г in self.персони.values():
                if г.седи is not None and г.карта == "krachma":
                    г.мнение = (1.0, 4.0)
            self.обявления.append("%s черпи всички за имения си ден! (+%d в касата)" % (п.име, сума))

    def _празник_сутрин(self):
        """Сутринта: датата, именниците, празникът (пазарът - търсеното поскъпва)."""
        имена = ", ".join(п.име for п in self.именници())
        if имена:
            self.обявления.append("Днес е %s. Честит имен ден на %s!" % (self.дата_текст(), имена))
        п = self.празник()
        if not п:
            return
        for к, остава in п.get("пазар", {}).items():
            if к in self.пазар_стока:
                self.пазар_стока[к] *= остава
        self.обявления.append(п.get("текст", "Днес е %s!" % п.get("име", "")))

    # ---------- камбаните ----------
    def камбани_бият(self):
        return self._абс_минута() < self.камбани_до and not self.звъннато

    def звънни(self, п, качество=0.7):
        if not self.до_точка(п, "камбанария", 100):
            return False, "Иди на камбанарията"
        if not self.камбани_бият():
            return False, "Камбаните бият по пладне и в 18:00"
        качество = max(0.0, min(1.0, float(качество)))
        self.звъннато = True
        self.звън_бонус, self.звън_бонус_до = 0.6 * качество, self._абс_минута() + 60
        self.обявления.append("Дин-дон! Селото чу камбаните - хората тръгват към площада и кръчмата.")
        return True, "Камбаните звъннаха %s" % ("★" * (3 if качество >= 0.85 else 2 if качество >= 0.55 else 1))

    # ---------- отецът ----------
    def _до_църковна(self, п, име, разстояние=110):
        if п.карта != "tsarkva" or not self.църква_карта:
            return False
        for о in self.църква_карта["objects"]:
            if о["name"] == име:
                д = self.плочки.get(име, {"w": 1, "h": 1})
                cx, cy = (о["x"] + д["w"] / 2) * ПЛОЧКА, (о["y"] + д["h"]) * ПЛОЧКА
                if math.hypot(cx - п.x, cy - п.y) <= разстояние + д["w"] * 20:
                    return True
        return False

    def свещи(self, п, качество=0.7):
        if not self._до_църковна(п, "svechnik"):
            return False, "Иди до свещника"
        if self.свещи_ден == self.ден:
            return False, "Свещите днес вече са запалени"
        качество = max(0.0, min(1.0, float(качество)))
        self.свещи_ден = self.ден
        self.репутация = min(5.0, self.репутация + 0.2 * качество)
        return True, "Свещите горят - в селото е спокойно (+%.1f звезди)" % (0.2 * качество)

    def обред_направи(self, п, вид, качество=0.7):
        if not self.обред or self.обред["вид"] != вид:
            return False, "Днес няма %s" % вид
        if not self._до_църковна(п, "ikonostas" if вид == "сватба" else "kupel"):
            return False, "Иди до %s" % ("иконостаса" if вид == "сватба" else "купела")
        self._започни_гощавка(вид, max(0.0, min(1.0, float(качество))))
        return True, "%s е готово - гостите отиват в кръчмата за гощавката!" % ("Венчавката" if вид == "сватба" else "Кръщенето")

    def църква_клиент(self, клиент, оп, качество):
        п = next((п for п in self.персони.values() if п.контролер == клиент), None)
        if п is None:
            return False, ""
        if оп == "bells" and п.роля in ("звънар", "свещеник"):
            return self.звънни(п, качество)
        if оп == "candles" and п.роля == "свещеник":
            return self.свещи(п, качество)
        if оп in ("сватба", "кръщене") and п.роля == "свещеник":
            return self.обред_направи(п, оп, качество)
        return False, ""

    def _църква_действие(self, п):
        """E за отеца и звънаря (самите мини игри ги пуска играта). None = нищо."""
        if п.роля == "звънар":
            if п.карта != "selo":
                return False, "Камбанарията е в селото, до църквата"
            return False, "Камбаните бият по пладне и в 18:00" if not self.камбани_бият() else "Иди на камбанарията"
        if п.роля == "свещеник":
            if п.карта != "tsarkva":
                return False, "Църквата е в селото (вдясно)"
            return False, "Ела до свещника (сутрин) или до иконостаса и купела (сватба, кръщене)"
        return None

    # ---------- гощавката ----------
    def _започни_гощавка(self, вид, качество):
        г = self.пр_данни.get("гощавка", {}).get(вид)
        self.обред = None
        if not г:
            return
        self.гощавка = {"вид": вид, "име": г.get("име", вид), "ястия": dict(г.get("ястия", {})),
                        "дадени": {к: 0 for к in г.get("ястия", {})}, "до": self._абс_минута() + г.get("часа", 3) * 60,
                        "качества": [], "обред": качество, "надценка": г.get("надценка", 2.0)}
        self.обявления.append("Гощавка за %s в кръчмата! Занесете ястията на голямата маса до %02d:%02d." % (
            г.get("име", вид).lower(), (self.гощавка["до"] % 1440) // 60, self.гощавка["до"] % 60))

    def гощавка_трябва(self, предмет):
        if not self.гощавка or not предмет:
            return 0
        return self.гощавка["ястия"].get(предмет, 0) - self.гощавка["дадени"].get(предмет, 0)

    def маса_гощавка(self):
        """Голямата маса в кръчмата (центърът ѝ) - там е трапезата."""
        маси = [о for о in self.карта["objects"] if о["name"] in МАСИ]
        if not маси:
            return None
        маси.sort(key=lambda о: (о["name"] not in ("table_big", "table_big_v"), о["y"], о["x"]))
        о = маси[0]
        д = self.плочки.get(о["name"], {"w": 1, "h": 1})
        return ((о["x"] + д["w"] / 2) * ПЛОЧКА, (о["y"] + д["h"] / 2) * ПЛОЧКА, о["x"], о["y"])

    def до_трапезата(self, п):
        м = self.маса_гощавка()
        return bool(м and п.карта == "krachma" and math.hypot(м[0] - п.x, м[1] - п.y) <= ДО_ТРАПЕЗАТА)

    def гощавка_дай(self, п):
        if self.гощавка_трябва(п.носи) <= 0:
            return False, ""
        if not self.до_трапезата(п):
            return False, "Занеси го на голямата маса (трапезата)"
        предмет = п.носи
        self.гощавка["дадени"][предмет] += 1
        self.гощавка["качества"].append(п.качество)
        п.носи, п.качество = None, 0.6
        if all(self.гощавка_трябва(к) <= 0 for к in self.гощавка["ястия"]):
            return True, self._край_гощавка(True)
        return True, "На трапезата: %s (още %d)" % (self.име_на(предмет),
                                                    sum(max(0, self.гощавка_трябва(к)) for к in self.гощавка["ястия"]))

    def _край_гощавка(self, навреме):
        г = self.гощавка
        self.гощавка = None
        if not г:
            return ""
        пълно = sum(self.цена(к) * б for к, б in г["ястия"].items())
        дадено = sum(self.цена(к) * б for к, б in г["дадени"].items())
        качество = sum(г["качества"]) / len(г["качества"]) if г["качества"] else 0.5
        if навреме:
            сума = int(round(пълно * г["надценка"] * (0.6 + 0.4 * качество) * (0.8 + 0.2 * г["обред"])))
            self.репутация = min(5.0, self.репутация + 0.4)
            текст = "%s мина чудесно! Гостите платиха %d." % (г["име"], сума)
        else:
            сума = int(round(дадено * 0.8))
            self.репутация = max(0.0, self.репутация - 0.5)
            текст = "%s не стигна до края - на трапезата липсваше храна. Платиха само %d." % (г["име"], сума)
        маса = self.маса_гощавка()                     # чиниите от гощавката остават мръсни на трапезата
        с_чиния = self.склад_данни.get("с_чиния", [])
        if маса:
            for и in range(sum(б for к, б in г["дадени"].items() if к in с_чиния)):
                ъгъл = и * 2.4
                self.мръсни.append({"x": round(маса[0] + 50 * math.cos(ъгъл)), "y": round(маса[1] + 30 * math.sin(ъгъл)),
                                    "място": -1})
        с = self.собственик()
        if с:
            с.пари += сума
        self.днес["приходи"] += сума
        self.днес["гощавка"] = self.днес.get("гощавка", 0) + сума
        self.обявления.append(текст)
        return текст

    # ---------- NPC отецът и звънарят ----------
    def _npc_църква(self, п, време):
        if п.роля == "звънар":
            точка = self._селска_точка("камбанария")
            if точка is None:
                return False
            if not self._иди(п, "selo", точка, време):
                return True
            п.върви, п.посока = False, "up"
            if self.камбани_бият():
                п.маг_работа += време
                if п.маг_работа > 3:
                    п.маг_работа = 0.0
                    self.звънни(п, 0.7)
            return True
        if п.роля == "свещеник":
            if not self.църква_карта:
                return False
            цел = None
            if self.свещи_ден != self.ден and self.минути < self.пр_данни.get("свещи_до", 600):
                цел = ("svechnik", None)
            elif self.обред:
                цел = ("ikonostas" if self.обред["вид"] == "сватба" else "kupel", self.обред["вид"])
            if цел is None:
                точка = self.център(tuple(self.църква_карта.get("start", [5, 4])))
                self._иди(п, "tsarkva", точка, време)
                return True
            о = next((о for о in self.църква_карта["objects"] if о["name"] == цел[0]), None)
            if о is None:
                return False
            д = self.плочки.get(о["name"], {"w": 1, "h": 1})
            точка = self.център((о["x"] + д["w"] // 2, о["y"] + д["h"]))
            if self._иди(п, "tsarkva", точка, време) or self._до_църковна(п, цел[0]):
                п.маг_работа += време
                if п.маг_работа > 4:
                    п.маг_работа = 0.0
                    if цел[1]:
                        self.обред_направи(п, цел[1], 0.75)
                    else:
                        self.свещи(п, 0.7)
            return True
        return False

    # ---------- за мрежата ----------
    def църква_за_клиента(self):
        п = self.празник()
        г = self.гощавка
        пост = self.пост()

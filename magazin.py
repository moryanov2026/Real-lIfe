# Магазинът в селото (част от света - world.Свят го наследява). Данните са в data/magazin.json.
# Жителите идват за покупки и застават на опашка пред тезгяха. Продавачът слага стоката (E),
# касиерът маркира и връща ресто (E на касата = мини игра "Ресто"). Стоката идва от пазара сутрин.
import json
import math
import os

import tiles

ПЛОЧКА = tiles.ПЛОЧКА
ПЪТ = os.path.join(tiles.ПАПКА, "data", "magazin.json")
ПЪТ_КАРТА = os.path.join(tiles.ПАПКА, "data", "maps", "magazin.json")
БАНКНОТИ = (5, 10, 20, 50, 100)
ДО_ТЕЗГЯХА = 170                         # от колко далеч продавачът и касиерът стигат клиента


class МагазинМиксин:
    def _магазин_карта_начало(self):
        self.магазин_карта = None
        if self.село and os.path.exists(ПЪТ_КАРТА):
            self.магазин_карта = tiles.зареди_карта(ПЪТ_КАРТА)
            self.маг_заети, self.маг_препятствия = self._геометрия(self.магазин_карта)

    def _магазин_начало(self):
        try:
            with open(ПЪТ, encoding="utf-8") as f:
                self.маг_данни = json.load(f)
        except (OSError, ValueError):
            self.маг_данни = {"стоки": {}, "каса": 0}
        д = self.маг_данни
        self.маг_стока = {к: д.get("начало", 8) for к in д.get("стоки", {})}
        self.маг_каса = д.get("каса", 100)
        self.маг_днес = {"приходи": 0, "клиенти": 0, "доставка": 0, "ядосани": 0}
        self.маг_ред = 0                         # номер за опашката

    def маг_цена(self, к):
        return int(self.маг_данни.get("стоки", {}).get(к, {}).get("цена", 1))

    def магазин_отворен(self):
        return bool(self.магазин_карта) and self.отворено()

    # ---------- клиентите ----------
    def _клиенти(self):
        return sorted((п for п in self.персони.values() if п.карта == "magazin" and п.маг_ред and not п.тръгва),
                      key=lambda п: п.маг_ред)

    def _първи(self):
        к = self._клиенти()
        return к[0] if к else None

    def _спот(self, номер):
        опашка = self.маг_данни.get("опашка", [[5, 4]])
        return self.център(tuple(опашка[min(номер, len(опашка) - 1)]))

    def _сметка(self, п):
        return sum(self.маг_цена(к) * б for к, б in п.кошница.items())

    def _плаща_с(self, сметка):
        return next((б for б in БАНКНОТИ if б >= сметка), сметка)

    def _клиент_магазин(self, п, време):
        """Жител в магазина: опашка, чака продавача, после касата, после си тръгва."""
        if п.тръгва:
            self._тръгни(п, време)
            return
        if not п.маг_ред:
            self.маг_ред += 1
            п.маг_ред = self.маг_ред
            стоки = [к for к in self.маг_данни.get("стоки", {})]
            брой = self.случаен.randint(*self.маг_данни.get("иска", [1, 4]))
            п.маг_списък = {}
            for к in self.случаен.sample(стоки, min(брой, len(стоки))):
                п.маг_списък[к] = self.случаен.randint(1, 2)
            празник = self.празник() if hasattr(self, "празник") else None
            for к in (празник or {}).get("магазин", []):     # в празник се купува празничното
                if к in self.маг_данни.get("стоки", {}):
                    п.маг_списък[к] = п.маг_списък.get(к, 0) + 2
            п.маг_търпение = float(self.маг_данни.get("търпение", 70))
            п.кошница, п.маг_сметка = {}, 0
        номер = [к.id for к in self._клиенти()].index(п.id) if п in self._клиенти() else 0
        точка = self._спот(номер)
        if math.hypot(точка[0] - п.x, точка[1] - п.y) > 8:
            self._върви(п, точка, време)
        else:
            п.върви, п.посока = False, "up"
        п.маг_търпение -= време
        if п.маг_търпение <= 0:
            self._мнение(п, 0.1, "Магазинът е бавен - тръгвам си!")
            self.маг_днес["ядосани"] += 1
            п.нужди["покупки"] = 20.0
            self._маг_изпрати(п)

    def _маг_изпрати(self, п):
        п.маг_ред, п.маг_списък, п.кошница, п.маг_сметка = 0, {}, {}, 0
        п.тръгва = True

    def маг_обслужи(self, продавач):
        """Продавачът слага стоката на първия клиент от опашката."""
        к = self._първи()
        if not к or math.hypot(к.x - продавач.x, к.y - продавач.y) > ДО_ТЕЗГЯХА:
            return False, "Няма клиент пред тезгяха"
        if к.кошница:
            return False, "%s вече чака на касата" % к.име
        липсва = []
        for пр, брой in к.маг_списък.items():
            взе = min(брой, self.маг_стока.get(пр, 0))
            if взе:
                к.кошница[пр] = взе
                self.маг_стока[пр] -= взе
            if взе < брой:
                липсва.append(self.склад_данни["продукти"].get(пр, {}).get("име", пр).lower())
        if not к.кошница:
            self._мнение(к, 0.2, "Няма нищо от това, което ми трябва!")
            к.нужди["покупки"] = 0.0
            self._маг_изпрати(к)
            return False, "Няма стока за %s" % к.име
        к.маг_сметка = self._сметка(к)
        к.маг_дава = self._плаща_с(к.маг_сметка)
        текст = "Сложи стоката на %s: сметка %d лв" % (к.име, к.маг_сметка)
        if липсва:
            текст += " (няма: %s)" % ", ".join(липсва)
        return True, текст

    def маг_плати(self, касиер, качество=0.8):
        """Касиерът маркира и връща ресто (качество от мини играта; под 0.3 = сгреши рестото)."""
        к = self._първи()
        if not к or not к.кошница or math.hypot(к.x - касиер.x, к.y - касиер.y) > ДО_ТЕЗГЯХА + 60:
            return False, "Няма клиент със стока за маркиране"
        сметка = к.маг_сметка
        if к.пари < сметка:
            сметка = к.пари
        к.пари -= сметка
        self.маг_каса += сметка
        self.маг_днес["приходи"] += сметка
        self.маг_днес["клиенти"] += 1
        к.нужди["покупки"] = 0.0
        if качество < 0.3:
            self._мнение(к, 0.3, "Касиерът сгреши рестото!")
        else:
            self._мнение(к, 0.6 + 0.4 * качество, "Бързо и любезно!" if качество > 0.8 else "Купих си каквото ми трябва.")
        self._маг_изпрати(к)
        return True, "%s плати %d лв" % (к.име, сметка)

    def маг_каса_клиент(self, клиент, качество):
        п = next((п for п in self.персони.values() if п.контролер == клиент), None)
        if п is None or п.роля not in ("касиер", "продавач") or п.карта != "magazin":
            return False, ""
        return self.маг_плати(п, качество)

    def _магазин_действие(self, п):
        """E в магазина за продавача и касиера. None = нищо."""
        if п.карта != "magazin" or п.роля not in ("продавач", "касиер"):
            return None
        к = self._първи()
        if п.роля == "продавач" and к and not к.кошница:
            return self.маг_обслужи(п)
        if к and к.кошница:
            return False, "Касиерът маркира на касата (мини игра)"
        return False, "Чакаш клиенти"

    # ---------- NPC продавач и касиер ----------
    def _npc_магазин(self, п, време):
        if п.карта != "magazin":
            if not self.магазин_карта:
                return False
            self._иди(п, "magazin", None, време)
            return True
        ключ = "продавач" if п.роля == "продавач" else "касиер"
        място = self.център(tuple(self.маг_данни.get(ключ, [5, 2])))
        if math.hypot(място[0] - п.x, място[1] - п.y) > 8:
            self._върви(п, място, време)
            return True
        п.върви, п.посока = False, "down"
        к = self._първи()
        if not к or math.hypot(к.x - п.x, к.y - п.y) > ДО_ТЕЗГЯХА + 60:
            п.маг_работа = 0.0
            return True
        if (п.роля == "продавач" and not к.кошница) or (п.роля == "касиер" and к.кошница):
            п.маг_работа += време * self._усърдие(п)
            if п.маг_работа >= 2.5:
                п.маг_работа = 0.0
                if п.роля == "продавач":
                    self.маг_обслужи(п)
                else:
                    self.маг_плати(п, 0.8)
        return True

    # ---------- сутрин и вечер ----------
    def _магазин_нощ(self):
        """Вечерта: заплатите от касата на магазина. Сутринта: доставка от пазара."""
        д = self.маг_данни
        заплати = 0
        for п in self.персони.values():
            сума = д.get("заплати", {}).get(п.роля)
            if сума and self.маг_каса >= сума:
                self.маг_каса -= сума
                п.пари += сума
                заплати += сума
        отчет = dict(self.маг_днес, заплати=заплати)
        доставка = 0
        for к, брой in self.маг_стока.items():
            if брой < д.get("доставка_под", 5):
                купени, цена = self.купи_от_пазара(к, д.get("доставка", 10)) if к in self.склад_данни["продукти"] else (0, 0)
                if купени and цена <= self.маг_каса:
                    self.маг_стока[к] += купени
                    self.маг_каса -= цена
                    доставка += цена
                elif купени and к in self.пазар_стока:
                    self.пазар_стока[к] += купени             # няма пари: стоката остава на пазара
        отчет["доставка"] = доставка
        отчет["каса"] = self.маг_каса
        self.маг_днес = {"приходи": 0, "клиенти": 0, "доставка": 0, "ядосани": 0}
        for п in self.персони.values():
            if п.карта == "magazin" and self.гост(п):
                п.маг_ред = 0
        return отчет

    def магазин_за_клиента(self):
        return {"stock": self.маг_стока, "cash": self.маг_каса,
                "prices": {к: self.маг_цена(к) for к in self.маг_стока}, "today": self.маг_днес}
